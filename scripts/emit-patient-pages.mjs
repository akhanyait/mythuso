/* The eight patient pages and their hub, written out for the router and for two native apps, by a machine.

   The words, the derivations and the refusals live in packages/catalog/patient-pages.json. The web
   reads that file behind a dynamic import; the router reads the generated route file below, which
   carries only each page's name and what to say while it arrives — the same split emit-care-tips.mjs
   makes, because a JSON module imported by the entry is kept whole in the entry bundle and the
   patient's first load pays for none of this.

   iOS and Android get the words as data. Neither phone renders a page from it yet (platforms: web,
   as with care-tips), and that is recorded in the contract's platformsWhy rather than left to
   surprise somebody: the generated files exist so the native screens are a later wave's assembly
   and the wording cannot drift between a phone and the web in the meantime.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar. */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = "packages/catalog/patient-pages.json";

const swift = (value) =>
  `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const kotlin = (value) =>
  `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;

const banner = () =>
  [
    `Generated by scripts/emit-patient-pages.mjs from ${SOURCE}.`,
    "Do not edit by hand — run `npm run patient-pages`. The build fails if this file and the source",
    "disagree, so an edit here is lost rather than merely wrong.",
    "",
    "The eight pages of the full Lovable export\u2019s Gap 2 and their hub. General information, gated:",
    "the review notice is shown beside every screen until a clinician has signed, and the symptom",
    "checker and risk assessment inherit the screening capability\u2019s block.",
  ]
    .map((line) => (line ? `// ${line}` : "//"))
    .join("\n");

export function emitPatientPages(root = "") {
  const contract = JSON.parse(readFileSync(root + SOURCE, "utf8"));
  const { hub, screens, review } = contract;
  const ids = Object.keys(screens);
  const reviewedBy =
    review.reviewedBy === null ? "nil" : swift(review.reviewedBy);
  const reviewedByKt =
    review.reviewedBy === null ? "null" : kotlin(review.reviewedBy);

  /* The screen words the native files carry: the sentences every page has, not the page-specific
    panels — those stay in the contract for the web and for the wave that assembles the native
    screens, so nothing here can drift from the JSON it was emitted from. */
  const screenLines = (id) => {
    const s = screens[id];
    return {
      opens: s.opens,
      opening: s.opening,
      eyebrow: s.eyebrow,
      heading: s.heading,
      lead: s.lead,
    };
  };

  const swiftFile = `${banner()}

import SwiftUI

enum PatientPagesData {
    static let version = ${contract.version}

    enum Review {
        /// Nil until a registered clinician has read and signed the pages' health material.
        static let reviewedBy: String? = ${reviewedBy}
        static let notice = ${swift(review.notice)}
    }

    enum Hub {
        static let opens = ${swift(hub.opens)}
        static let heading = ${swift(hub.heading)}
        static let lead = ${swift(hub.lead)}
        static let shortcutTitles = [
${hub.shortcuts.map((s) => `            ${swift(s.title)}`).join(",\n")}
        ]
    }

    enum Screen: String, CaseIterable {
${ids.map((id) => `        case ${id.replace(/-(\w)/g, (_, c) => c.toUpperCase())} = ${swift(screens[id].opens)}`).join("\n")}

        var opening: String {
            switch self {
${ids.map((id) => `            case .${id.replace(/-(\w)/g, (_, c) => c.toUpperCase())}: return ${swift(screenLines(id).opening)}`).join("\n")}
            }
        }
    }

    static let refusals: [String] = [
${contract.refusals.map((r) => `        ${swift(r.sentence)}`).join(",\n")}
    ]
}
`;

  const kotlinFile = `${banner()}

package za.co.mythuso.model

object PatientPagesData {
    const val version = ${contract.version}

    object Review {
        /** Null until a registered clinician has read and signed the pages' health material. */
        val reviewedBy: String? = ${reviewedByKt}
        const val notice = ${kotlin(review.notice)}
    }

    object Hub {
        const val opens = ${kotlin(hub.opens)}
        const val heading = ${kotlin(hub.heading)}
        const val lead = ${kotlin(hub.lead)}
        val shortcutTitles = listOf(
${hub.shortcuts.map((s) => `            ${kotlin(s.title)}`).join(",\n")}
        )
    }

    val screenOpens = listOf(
${ids.map((id) => `        ${kotlin(screens[id].opens)}`).join(",\n")}
    )

    val refusals = listOf(
${contract.refusals.map((r) => `        ${kotlin(r.sentence)}`).join(",\n")}
    )
}
`;

  /* The router's copy: each page's name, its arrival sentence and the hub's one-line description of it —
     the last because the phone's More hub and the sidebar describe a page in the hub's words rather than
     a second set typed beside them. Nothing longer rides on the patient's first load. */
  const subOf = (id) => hub.shortcuts.find((s) => s.id === id)?.sub;
  const webFile = `// Generated by scripts/emit-patient-pages.mjs from ${SOURCE}.
// Do not edit by hand — run \`npm run patient-pages\`. The build fails if this file and its source disagree,
// so an edit here is lost rather than merely wrong.
//
// Only the routes: the names the router opens, what it says while each screen arrives, and the hub's one line
// about each. Every other word stays in the contract, read by apps/web/src/lib/patient-pages.ts behind
// dynamic imports.

export const patientPagesHubRoute = {
  opens: ${JSON.stringify(hub.opens)},
  opening: ${JSON.stringify(hub.opening)},
} as const;

export const patientPageRoutes = {
${ids
  .map(
    (id) => `  ${JSON.stringify(id)}: {
    opens: ${JSON.stringify(screens[id].opens)},
    opening: ${JSON.stringify(screens[id].opening)},${subOf(id) ? `
    sub: ${JSON.stringify(subOf(id))},` : ""}
  },`,
  )
  .join("\n")}
} as const;

export type PatientPageId = keyof typeof patientPageRoutes;
`;

  return [
    {
      path: "apps/web/src/lib/patient-pages-routes.generated.ts",
      content: webFile,
    },
    {
      path: "apps/ios/MyThuso/Models/PatientPagesData.swift",
      content: swiftFile,
    },
    {
      path: "apps/android/app/src/main/java/za/co/mythuso/model/PatientPagesData.kt",
      content: kotlinFile,
    },
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const file of emitPatientPages()) {
    writeFileSync(file.path, file.content);
    console.log(`patient-pages → ${file.path}`);
  }
}
