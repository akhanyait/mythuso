/* What a nurse is paid, written out for two native apps, by a machine.

   The pay cycle, the five payout states, the four kinds of line, the six rules, the four refusals,
   the payout account and four weeks of fictional visits live in packages/catalog/earnings.json. The
   web reads that file. iOS and Android cannot, and should not, for the reason the vetting generator
   gives: an app that parses JSON to draw a list is a web app wearing a Compose hat.

   One thing here is different from the other three generators, and it is the point of the feature.

   No visit amount exists in the source. A line names a service — "wound", "senior" — and the money
   is the nurse's share of that service in packages/catalog/services.json, the same row the patient
   is quoted from and the same row the public landing page prices from. The web resolves that at
   runtime. Native gets it resolved here, at generation time, and the boundary check compares this
   file's output with what is on disk on every build. So a price change moves the patient's quote,
   the nurse's payout and the public claim together, in one edit, or it fails the build. There is no
   third place for a number to be typed.

   A reversal and a correction carry their own amount, because neither is derived from anything.
   Each also carries a reason, and the check refuses a source where one does not.

   Escaping is the hazard, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and
       a lone $ starts a string template. The refusal sentences mention money.
   The sentences carry en-dashes, curly quotes and a bullet-masked account number. Those are simply
   UTF-8 and need nothing, which is worth knowing rather than guessing at. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/earnings.json';
const CATALOGUE = 'packages/catalog/services.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const optSwift = value => (value === undefined ? 'nil' : swift(value));
const optKotlin = value => (value === undefined ? 'null' : kotlin(value));
const optInt = value => (value === undefined ? 'nil' : String(value));
const optIntKt = value => (value === undefined ? 'null' : String(value));

const banner = () => [
 `Generated by scripts/emit-earnings.mjs from ${SOURCE} and ${CATALOGUE}.`,
 'Do not edit by hand — run `npm run earnings`. The build fails if this file and the two sources',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Every visit amount below is the nurse\'s share of that service in the service catalogue, resolved',
 'when this file was written. It is not a number anybody typed, and there is nowhere to type it.',
 '',
 'The arithmetic that uses this table — week totals, what has reached the account this tax year,',
 'what is still owed — is hand-written in Earnings.swift and Earnings.kt beside it.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitEarnings(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const catalogue = JSON.parse(readFileSync(root + CATALOGUE, 'utf8'));
 const shareOf = id => {
  const service = catalogue.find(s => s.id === id);
  if (!service) throw new Error(`Earnings names a service that is not in the catalogue: ${id}`);
  return service;
 };
 /* The signed amount, so a week is the sum of its lines and nothing downstream has to remember
    which way round to subtract. */
 const resolve = line => {
  const kind = contract.lineKinds.find(k => k.id === line.kind);
  if (!kind) throw new Error(`Earnings line ${line.reference} has an unknown kind ${line.kind}`);
  const service = line.service ? shareOf(line.service) : undefined;
  const base = service ? service.nurseShare : line.amount;
  if (base === undefined) throw new Error(`Earnings line ${line.reference} has neither a service nor an amount`);
  return { ...line, amount: kind.sign * base, serviceName: service?.name };
 };

 const swiftFile = `${banner()}

import Foundation

extension Earnings {
    static let cycle = PayCycle(weekEndsOn: ${swift(contract.cycle.weekEndsOn)}, closesOn: ${swift(contract.cycle.closesOn)},
                                paysOn: ${swift(contract.cycle.paysOn)}, clearsInDays: ${contract.cycle.clearsInDays[0]}...${contract.cycle.clearsInDays[1]},
                                note: ${swift(contract.cycle.note)})
    static let states: [PayoutState] = [
${contract.states.map(s => `        .init(id: ${swift(s.id)}, name: ${swift(s.name)}, detail: ${swift(s.detail)}, settled: ${s.settled})`).join(',\n')}
    ]
    static let lineKinds: [PayLineKind] = [
${contract.lineKinds.map(k => `        .init(id: ${swift(k.id)}, name: ${swift(k.name)}, detail: ${swift(k.detail)}, sign: ${k.sign})`).join(',\n')}
    ]
    /* Rendered word for word. A rule paraphrased on one platform is a different promise on that
       platform, which is the whole reason these live in one file. */
    static let rules: [PayRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let refusals: [PayRefusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let account = PayoutAccount(holder: ${swift(contract.account.holder)}, bank: ${swift(contract.account.bank)},
                                       maskedNumber: ${swift(contract.account.maskedNumber)}, coolingOffHours: ${contract.account.coolingOffHours},
                                       reverify: [
${contract.account.reverify.map(step => `                                        ${swift(step)}`).join(',\n')}
                                       ],
                                       note: ${swift(contract.account.note)})
    /* The nurse's share of each launch service, from packages/catalog/services.json. The native
       catalogue carries the price a patient is quoted; this carries what the nurse keeps of it, so
       the split on the payout screen is read rather than recomputed from a percentage. A percentage
       would be a second place for the number to live, which is the one thing this feature exists to
       avoid. */
    static let nurseShares: [String: Int] = [
${catalogue.filter(s => s.phase === 1).map(s => `        ${swift(s.id)}: ${s.nurseShare}`).join(',\n')}
    ]
    static let taxYear = TaxYear(startsOn: ${swift(contract.taxYear.startsOn)}, label: ${swift(contract.taxYear.label)}, note: ${swift(contract.taxYear.note)})
    static let weeks: [PayWeek] = [
${contract.weeks.map(week => `        PayWeek(id: ${swift(week.id)}, state: ${swift(week.state)}, weeksAgo: ${week.weeksAgo},
                paidDaysAfterPayDate: ${optInt(week.paidDaysAfterPayDate)}, failure: ${optSwift(week.failure)},
                lines: [
${week.lines.map(resolve).map(line => `                    .init(kind: ${swift(line.kind)}, reference: ${swift(line.reference)}, onDays: ${line.onDays}, patient: ${swift(line.patient)},
                          area: ${optSwift(line.area)}, plan: ${optSwift(line.plan)}, service: ${optSwift(line.serviceName)},
                          reason: ${optSwift(line.reason)}, amount: ${line.amount})`).join(',\n')}
                ])`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

val payCycle = PayCycle(
    ${kotlin(contract.cycle.weekEndsOn)}, ${kotlin(contract.cycle.closesOn)}, ${kotlin(contract.cycle.paysOn)},
    ${contract.cycle.clearsInDays[0]}, ${contract.cycle.clearsInDays[1]},
    ${kotlin(contract.cycle.note)}
)

val payoutStates = listOf(
${contract.states.map(s => `    PayoutState(${kotlin(s.id)}, ${kotlin(s.name)}, ${kotlin(s.detail)}, ${s.settled})`).join(',\n')}
)

val payLineKinds = listOf(
${contract.lineKinds.map(k => `    PayLineKind(${kotlin(k.id)}, ${kotlin(k.name)}, ${kotlin(k.detail)}, ${k.sign})`).join(',\n')}
)

/* Rendered word for word. A rule paraphrased on one platform is a different promise on that
   platform, which is the whole reason these live in one file. */
val payRules = listOf(
${contract.rules.map(r => `    PayRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val payRefusals = listOf(
${contract.refusals.map(r => `    PayRefusal(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val payoutAccount = PayoutAccount(
    ${kotlin(contract.account.holder)}, ${kotlin(contract.account.bank)}, ${kotlin(contract.account.maskedNumber)},
    ${contract.account.coolingOffHours},
    listOf(
${contract.account.reverify.map(step => `        ${kotlin(step)}`).join(',\n')}
    ),
    ${kotlin(contract.account.note)}
)

/* The nurse's share of each launch service, from packages/catalog/services.json. The native
   catalogue carries the price a patient is quoted; this carries what the nurse keeps of it, so the
   split on the payout screen is read rather than recomputed from a percentage. A percentage would
   be a second place for the number to live, which is the one thing this feature exists to avoid. */
val nurseShares: Map<String, Int> = mapOf(
${catalogue.filter(s => s.phase === 1).map(s => `    ${kotlin(s.id)} to ${s.nurseShare}`).join(',\n')}
)

val payTaxYear = TaxYear(${kotlin(contract.taxYear.startsOn)}, ${kotlin(contract.taxYear.label)}, ${kotlin(contract.taxYear.note)})

val payWeeks = listOf(
${contract.weeks.map(week => `    PayWeek(
        ${kotlin(week.id)}, ${kotlin(week.state)}, ${week.weeksAgo},
        ${optIntKt(week.paidDaysAfterPayDate)}, ${optKotlin(week.failure)},
        listOf(
${week.lines.map(resolve).map(line => `            PayLine(
                ${kotlin(line.kind)}, ${kotlin(line.reference)}, ${line.onDays}, ${kotlin(line.patient)},
                ${optKotlin(line.area)}, ${optKotlin(line.plan)}, ${optKotlin(line.serviceName)},
                ${optKotlin(line.reason)}, ${line.amount}
            )`).join(',\n')}
        )
    )`).join(',\n')}
)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/EarningsData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/EarningsData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitEarnings()) {
  writeFileSync(file.path, file.content);
  console.log(`earnings → ${file.path}`);
 }
}
