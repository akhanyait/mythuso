/* The bus's privacy rule, held against the code that publishes to it.
 *
 * packages/catalog/events.json declares, in neverInEnvelope, the names a field may never carry: an
 * identity number, a name, a phone, a reading, a diagnosis, a Trust Score under any of its words. The bus
 * refuses a payload field carrying one of them at publish time, and scripts/check-boundaries.mjs holds
 * every declared event's payload to the same list. What neither can see is the third place the rule can
 * break: the engine code that builds an emission by hand — a payload object written into a domain file,
 * or a publish() call with the fields typed out beside it. A field named reading or value added there
 * reaches the bus and is refused at runtime, which is a fault nobody sees until the route is called.
 *
 * The reading itself lives in packages/engines/src/event-privacy-scan.ts, so that this generator and the
 * suite it writes run one scanner and cannot drift apart: a tokenizer that drops comments and string
 * bodies, reads the two static shapes an emission takes, and answers the bus's own questions — is the
 * event declared and live, does the event declare this field, and does the never list refuse its name.
 *
 * This generator runs that scan over the engines as it writes. A finding throws before anything is
 * written; a clean scan has its catalog tables baked into the generated suite, which re-scans the same
 * sources on every test run. So a bad field is caught by npm run event-privacy, by
 * scripts/check-boundaries.mjs when the generated file goes stale, and by npm test at the moment somebody
 * types it.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const { loadRuntimeContract } = await import('../packages/engines/src/runtime/contract.ts');
const { scanEmissions, privacyFindings, declaredFindings } = await import('../packages/engines/src/event-privacy-scan.ts');

const ROOT = 'packages/engines/src';
const OUTPUT = 'packages/engines/src/event-privacy.generated.test.ts';

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const declaredLiteral = (declared) => {
 const keys = [...declared.keys()].sort();
 if (!keys.length) return '{}';
 const lines = ['{'];
 for (const key of keys) {
  const { owner, fields } = declared.get(key);
  lines.push(` ${quote(key)}: { owner: ${quote(owner)}, fields: [${fields.map((field) => quote(field)).join(', ')}] },`);
 }
 lines.push('}');
 return lines.join('\n');
};

export function emitEventPrivacyTests(root = '') {
 const contract = loadRuntimeContract();
 const enginesRoot = root + ROOT;
 const files = (dir) => readdirSync(enginesRoot + dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? files(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]);
 const sources = files('').filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts')).sort();
 const sites = sources.flatMap((file) => scanEmissions(readFileSync(enginesRoot + file, 'utf8')).map((site) => ({ ...site, file: ROOT + file })));
 const findings = [...privacyFindings(sites, contract.events, contract.neverOnBus), ...declaredFindings(contract.events, contract.neverOnBus)];
 if (findings.length) throw new Error(`The engines emit, or the catalog declares, fields the bus refuses:\n  ${findings.join('\n  ')}`);

 const declared = new Map();
 const withdrawn = [];
 for (const [key, event] of [...contract.events].sort((a, b) => a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)) {
  if (event.withdrawn) { withdrawn.push(key); continue; }
  declared.set(key, { owner: event.owner, fields: event.payload.map((field) => field.field).sort() });
 }
 const never = contract.neverOnBus.map((entry) => ` { field: ${quote(entry.field)}, names: [${entry.names.map((name) => quote(name)).join(', ')}], match: ${quote(entry.match)} },`);

 const lines = [];
 lines.push(
  '// Generated by scripts/emit-event-privacy-tests.mjs from packages/catalog/events.json, the event',
  '// sources it names, and the engine sources under packages/engines/src. Do not edit by hand — run',
  '// `npm run event-privacy`. The build fails if this file and its sources disagree, so an edit here is',
  '// lost rather than merely wrong.',
  '//',
  '// What is held:',
  '//',
  '//   1. The declared table, the withdrawn table and the never list below are what the catalog declares',
  '//      today — recomputed from the live contract on every run and compared, so drift fails here as',
  '//      well as at build.',
  '//   2. No live event declares a payload field the never list refuses — the boundary check applied',
  '//      again, in a suite that runs with the engines.',
  '//   3. The engines\' own emissions, re-scanned from source on every run by the scanner in',
  '//      event-privacy-scan.ts: an object literal naming a type and version (or a key) with a payload of',
  '//      its own, and every call passing a literal event key with a payload object beside it, carry only',
  '//      fields their event declares and none the never list refuses — the bus\'s not-the-frozen-shape',
  '//      refusal and its never-field refusal, read statically. Nothing visible publishes a withdrawn',
  '//      version.',
  '//   4. What the scanner cannot read statically — a spread or a payload built through a variable — is',
  '//      passed over rather than guessed at, and left to the bus, which refuses it at runtime if it is',
  '//      wrong. Comments and string bodies are tokenized away first, so prose about a name is not a',
  '//      field carrying it.',
  '//',
  '// This file sits beside the engines because it reads all of them. Nothing here is a real service.',
  '',
  "import { test } from 'node:test';",
  "import assert from 'node:assert/strict';",
  "import { readFileSync, readdirSync } from 'node:fs';",
  "import { dirname } from 'node:path';",
  "import { fileURLToPath } from 'node:url';",
  "import { loadRuntimeContract } from './runtime/contract.ts';",
  "import { scanEmissions, privacyFindings, declaredFindings } from './event-privacy-scan.ts';",
  '',
  'const HERE = dirname(fileURLToPath(import.meta.url));',
  '',
  `const DECLARED: Record<string, { owner: string; fields: string[] }> = ${declaredLiteral(declared)};`,
  '',
  `const WITHDRAWN: string[] = [${withdrawn.map((key) => quote(key)).join(', ')}];`,
  '',
  'const NEVER: { field: string; names: string[]; match: \'ending\' | \'anywhere\' }[] = [',
  ...never,
  '];',
  '',
  "const engineFiles = (dir: string): string[] => readdirSync(HERE + dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? engineFiles(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]);",
  "const engineSources = (): string[] => engineFiles('').filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts')).sort();",
  '',
  "test('the catalog: no live event declares a payload field the never list refuses', () => {",
  ' const contract = loadRuntimeContract();',
  ' const findings = declaredFindings(contract.events, contract.neverOnBus);',
  " assert.deepEqual(findings, [], findings.join('\\n'));",
  '});',
  '',
  "test('the catalog: the tables this file was generated with are the ones it reads now', () => {",
  ' const contract = loadRuntimeContract();',
  ' const declared: Record<string, { owner: string; fields: string[] }> = {};',
  ' const withdrawn: string[] = [];',
  ' for (const [key, event] of contract.events) {',
  '  if (event.withdrawn) { withdrawn.push(key); continue; }',
  '  declared[key] = { owner: event.owner, fields: event.payload.map((field) => field.field).sort() };',
  ' }',
  " assert.ok(Object.keys(DECLARED).length > 0, 'the declared table is empty, so this file proves nothing');",
  " assert.deepEqual(declared, DECLARED, 'the declared table');",
  " assert.deepEqual(withdrawn.sort(), WITHDRAWN, 'the withdrawn table');",
  " assert.deepEqual(contract.neverOnBus.map((entry) => ({ field: entry.field, names: entry.names, match: entry.match })), NEVER, 'the never list');",
  '});',
  '',
  "test('the engines: every emission this scan can read carries only declared fields, none refused', () => {",
  " const sites = engineSources().flatMap((file) => scanEmissions(readFileSync(HERE + file, 'utf8')).map((site) => ({ ...site, file })));",
  " assert.ok(sites.length > 0, 'the scan found no emissions at all, so it is not reading the engines');",
  ' const contract = loadRuntimeContract();',
  ' const findings = privacyFindings(sites, contract.events, contract.neverOnBus);',
  " assert.deepEqual(findings, [], findings.join('\\n'));",
  '});',
  '',
 );
 return [{ path: OUTPUT, content: lines.join('\n') }];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitEventPrivacyTests()) {
  writeFileSync(file.path, file.content);
  console.log(`event-privacy → ${file.path}`);
 }
}
