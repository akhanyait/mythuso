/* The family arrangements, written out for two native apps by a machine.

   packages/catalog/household.json says what a roster line holds and never holds, what a sponsorship is
   before and after the recipient answers, and what a payer of one share is never shown. The refusal
   sentences are not in that file at all — they are the routes', in packages/catalog/apis/access.json — so
   this reads them from the routes by id and writes them into HouseholdData.swift and HouseholdData.kt
   beside the screen words. A phone renders the sentence the route would have answered with, word for word,
   rather than a paraphrase somebody typed under a deadline.

   WHAT IS NOT WRITTEN. Any amount. A split's shares come out of Money's payable and a sponsor's statement
   out of programmes.json, and neither phone prices anything. Nor the sponsor's sees/neverSees lists, which
   ProgrammesData already carries from packages/catalog/programmes.json — one copy on a phone, not two.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar. */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/household.json';
const API = 'packages/catalog/apis/access.json';
/* The four a person meets on a phone: a roster grants nothing, a roster is not read by strangers, a
   sponsor reads nothing about the care, and a payer of one share reads nothing either. */
const RENDERED = [
 ['membershipIsNotConsent', 'POST /v1/access/household-memberships@1', 'membership-is-not-consent'],
 ['notInThisHousehold', 'POST /v1/access/household-memberships@1', 'not-in-this-household'],
 ['sponsorReadsNothing', 'POST /v1/access/sponsors@2', 'sponsor-reads-nothing'],
 ['splitShowsNoCare', 'POST /v1/access/bill-splits@2', 'split-shows-no-care'],
 ['sharesMustTotal', 'POST /v1/access/bill-splits@2', 'shares-must-total'],
 ['notYourShare', 'POST /v1/access/bill-splits/{splitRef}/accept@1', 'not-your-share']
];

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-household.mjs from ${SOURCE} and ${API}.`,
 'Do not edit by hand — run `npm run household`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'A household is a roster and grants nothing; a sponsorship pays and reads nothing about the care; a bill',
 'split is shares each payer accepts for themselves. No household exists, no sponsorship is agreed and',
 'nothing is charged.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitHousehold(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const said = (routeKey, id) => {
  const route = api.routes.find(r => `${r.method} ${r.path}@${r.version}` === routeKey && !r.withdrawn);
  const found = route?.refusals.find(x => x.id === id);
  if (!found) throw new Error(`${API} has no live route ${routeKey} refusing "${id}", which a native family screen renders.`);
  return found.statement;
 };
 const house = contract.screen.household;
 const split = contract.screen.split;
 const neverHolds = contract.membership.neverHolds;
 const states = contract.sponsorship.states;

 const swiftFile = `${banner()}

import Foundation

enum HouseholdData {
    enum Roster {
        static let heading = ${swift(house.heading)}
        static let intro = ${swift(house.intro)}
        static let grantsNothing = ${swift(house.grantsNothing)}
        static let neverHeading = ${swift(house.neverHeading)}
        static let preview = ${swift(house.preview)}
        /// What a roster line never holds, and why — packages/catalog/household.json's own words.
        static let neverHolds: [(field: String, why: String)] = [
${neverHolds.map(n => `            (${swift(n.field)}, ${swift(n.why)})`).join(',\n')}
        ]
    }

    enum Sponsorship {
        /// What the person being paid for is told at each state. The sponsor's half is programmes.json's.
        static let states: [(id: String, name: String, recipientWords: String)] = [
${states.map(s => `            (${swift(s.id)}, ${swift(s.name)}, ${swift(s.recipientWords)})`).join(',\n')}
        ]
    }

    enum Split {
        static let heading = ${swift(split.heading)}
        static let intro = ${swift(split.intro)}
        static let accept = ${swift(split.accept)}
        static let allAccepted = ${swift(split.allAccepted)}
        static let neverHeading = ${swift(split.neverHeading)}
        static let never: [String] = [${split.never.map(swift).join(', ')}]
        static let preview = ${swift(split.preview)}
    }

    /// The refusals a person can meet, in ${API}'s own words.
${RENDERED.map(([name, route, id]) => `    static let ${name} = ${swift(said(route, id))}`).join('\n')}
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object HouseholdData {
    object Roster {
        const val heading = ${kotlin(house.heading)}
        const val intro = ${kotlin(house.intro)}
        const val grantsNothing = ${kotlin(house.grantsNothing)}
        const val neverHeading = ${kotlin(house.neverHeading)}
        const val preview = ${kotlin(house.preview)}

        /** What a roster line never holds, and why — packages/catalog/household.json's own words. */
        val neverHolds = listOf(
${neverHolds.map(n => `            HouseholdNever(${kotlin(n.field)}, ${kotlin(n.why)})`).join(',\n')}
        )
    }

    object Sponsorship {
        /** What the person being paid for is told at each state. The sponsor's half is programmes.json's. */
        val states = listOf(
${states.map(s => `            SponsorshipState(${kotlin(s.id)}, ${kotlin(s.name)}, ${kotlin(s.recipientWords)})`).join(',\n')}
        )
    }

    object Split {
        const val heading = ${kotlin(split.heading)}
        const val intro = ${kotlin(split.intro)}
        const val accept = ${kotlin(split.accept)}
        const val allAccepted = ${kotlin(split.allAccepted)}
        const val neverHeading = ${kotlin(split.neverHeading)}
        val never = listOf(${split.never.map(kotlin).join(', ')})
        const val preview = ${kotlin(split.preview)}
    }

    /** The refusals a person can meet, in ${API}'s own words. */
${RENDERED.map(([name, route, id]) => `    const val ${name} = ${kotlin(said(route, id))}`).join('\n')}
}

data class HouseholdNever(val field: String, val why: String)
data class SponsorshipState(val id: String, val name: String, val recipientWords: String)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/HouseholdData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/HouseholdData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 if (!existsSync(SOURCE)) throw new Error(`${SOURCE} is missing; run this from the repository root.`);
 for (const file of emitHousehold()) {
  writeFileSync(file.path, file.content);
  console.log(`household → ${file.path}`);
 }
}
