/* The two typefaces, written into Swift by a machine.

   packages/design-tokens/tokens.json#typography names the families the Lovable handoff of
   28 September 2026 set — Outfit for page titles and compact feature headings, Figtree for everything
   a person has to read carefully — and the weights each is carried at. The web reads them as the
   --font-display and --font-sans stacks tokens.generated.css emits. A phone cannot read JSON at
   runtime and cannot load a stack: it registers font files by name and asks for a face by its
   PostScript name. Those names were about to be typed into the iOS design system, which is how a
   family name drifts from the token that decided it, so they are generated here instead.

   What is derived, and from where:
   - the family names are the first entry of each stack (`typography.stacks.display` / `.text`);
   - the weight ranges are the "weights 500–700" phrases in `typography.families`;
   - the file and PostScript names follow the OFL sources' own naming (Outfit-SemiBold.ttf is the
     face named Outfit-SemiBold), one static face per hundred of weight, because a static face is
     what iOS 17 resolves without ambiguity when a weight is asked for.

   The files themselves live in apps/ios/MyThuso/Fonts beside their OFL texts, and
   scripts/check-boundaries.mjs ("Wave 5a — iOS on the identity") holds Info.plist, the Xcode project
   and the directory to the list this emits. iOS only for now: Android's pass registers its own. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/design-tokens/tokens.json';

/* A stack is CSS, and CSS lets its first entry be quoted — "Outfit", ui-sans-serif is as valid as the
   unquoted form tokens.json uses today — so the quotes are stripped before the entry becomes a family
   name. What is left is written into Swift through the escaper emit-icons.mjs uses (backslash, then
   quote) and into the plist with XML's entities, so a family name that ever carries either cannot break
   the iOS build or the plist. Today's output is byte-identical with or without them. */
const unquote = value => value.trim().replace(/^(['"])(.*)\1$/, '$2').trim();
const swiftString = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const xml = value => value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;');

/* The OFL sources' style names for each hundred of weight. */
const STYLE = { 100: 'Thin', 200: 'ExtraLight', 300: 'Light', 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold', 900: 'Black' };

export function typographyFaces(root = '') {
 const tokens = JSON.parse(readFileSync(`${root}${SOURCE}`, 'utf8'));
 const { stacks, families } = tokens.typography;
 const family = (stack) => unquote(stack.split(',')[0]);
 const range = (prose, name) => {
  const m = prose.match(/weights (\d{3})[–-](\d{3})/);
  if (!m) throw new Error(`${SOURCE}#typography.families.${name} no longer says which weights it is carried at ("weights 500–700").`);
  const [lo, hi] = [Number(m[1]), Number(m[2])];
  const weights = [];
  for (let w = lo; w <= hi; w += 100) weights.push(w);
  return weights;
 };
 const roles = [
  { role: 'display', family: family(stacks.display), weights: range(families.display, 'display') },
  { role: 'text', family: family(stacks.text), weights: range(families.text, 'text') }
 ];
 for (const r of roles) r.faces = r.weights.map((weight) => ({ weight, name: `${r.family}-${STYLE[weight]}`, file: `${r.family}-${STYLE[weight]}.ttf` }));
 return roles;
}

export function emitTypography(root = '') {
 const roles = typographyFaces(root);
 const display = roles[0], text = roles[1];
 const swift = `// Generated by scripts/emit-typography.mjs from packages/design-tokens/tokens.json.
// Do not edit by hand — run \`npm run typography\`. The build fails if this file and the token source
// disagree, so an edit here is lost rather than merely wrong.
//
// The two typefaces of the identity and the faces each is carried at, by PostScript name. The
// files are registered in Info.plist under UIAppFonts and live in MyThuso/Fonts beside their OFL
// licences; DesignSystem/Typography.swift is what asks for them, and nothing else names a family.

import CoreGraphics

enum ThusoTypography {
    /// Page titles and compact feature headings.
    static let display = ${swiftString(display.family)}
    /// Everything a person has to read carefully.
    static let text = ${swiftString(text.family)}
    static let displayWeights: [Int] = [${display.weights.join(', ')}]
    static let textWeights: [Int] = [${text.weights.join(', ')}]
    /// The face registered for a family at a weight, as its PostScript name.
    static let faces: [String: String] = [
${roles.flatMap((r) => r.faces.map((f) => `        ${swiftString(`${r.family}-${f.weight}`)}: ${swiftString(f.name)}`)).join(',\n')}
    ]
    /// Every file the app bundles, in the order Info.plist lists them.
    static let files: [String] = [
${roles.flatMap((r) => r.faces.map((f) => `        ${swiftString(f.file)}`)).join(',\n')}
    ]
}
`;
 const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<!-- Generated by scripts/emit-typography.mjs from packages/design-tokens/tokens.json: the fonts the
	     identity bundles. Every other key of the app's Info.plist is generated by Xcode from the
	     INFOPLIST_KEY_ build settings in project.pbxproj and merged with this file. -->
	<key>UIAppFonts</key>
	<array>
${roles.flatMap((r) => r.faces.map((f) => `		<string>Fonts/${xml(f.file)}</string>`)).join('\n')}
	</array>
</dict>
</plist>
`;
 return [
  { path: 'apps/ios/MyThuso/DesignSystem/TypographyData.swift', content: swift },
  { path: 'apps/ios/MyThuso/Info.plist', content: plist }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitTypography()) {
  writeFileSync(file.path, file.content);
  console.log(`typography → ${file.path}`);
 }
}
