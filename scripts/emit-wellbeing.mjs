/* Live well, written out for two native apps by a machine.

   packages/catalog/wellbeing.json is the feature. Five habits, ten refusals and a neverSoften
   clause, and the refusals are the part that matters: this is the only place in the product that
   talks to somebody about their own body with no clinician in the room. Every sentence a Live well
   screen shows is one of the ones in that file, rendered word for word, because the failure mode
   here is not a screen that lies — it is a well-meaning sentence somebody wrote at eleven at night
   that congratulates a person whose condition is getting worse.

   WHAT THIS GENERATOR REFUSES TO EMIT. There is no number in the output and no field for one. The
   habits carry a name and a prompt; an entry carries a day offset and whatever the person typed.
   `unitless` is checked here rather than carried into the apps, because a boolean that is true on
   every row is a field somebody will one day set to false: the generator throws instead, so the
   only way to add a habit that takes a number is to argue with a build error.

   THE CHECK THAT READS THE SCREENS CANNOT READ THESE FILES, AND THAT IS DELIBERATE.
   scripts/check-boundaries.mjs fails any Live well source that says "score", "grade", "target" or
   "streak", and three of the contract's own refusals say exactly those words — they have to, since
   the absence is the feature and a reader cannot see an absence. So the check skips a file whose
   banner says it was generated: a carrier is the contract in another language, and the contract may
   name what it refuses. A screen may not.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. The sentences carry curly quotes, em-dashes and apostrophes, all of
   which are plain UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/wellbeing.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const wrap = (text, width = 94) => text.match(new RegExp(`.{1,${width}}(\\s|$)`, 'g')).map(line => line.trim());

export function emitWellbeing(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));

 /* Four things caught here, where they are still cheap, rather than in a screen where they would be
    a sentence somebody reads about their own body. */
 if (!contract.refusals?.length) throw new Error('packages/catalog/wellbeing.json declares no refusals, and the refusals are the feature.');
 const habitIds = new Set();
 for (const habit of contract.habits) {
  if (habit.unitless !== true) throw new Error(`The "${habit.id}" habit is not marked unitless. There is no field anywhere in Live well that takes a number, and that single decision is what makes the rest of it safe.`);
  if (!habit.prompt.trim().endsWith('?')) throw new Error(`The "${habit.id}" habit's prompt is not a question. A habit that states rather than asks has told somebody what their day was.`);
  habitIds.add(habit.id);
 }
 for (const refusal of contract.refusals) {
  if (!refusal.sentence || !refusal.why) throw new Error(`Refusal "${refusal.id}" is missing its sentence or its reasoning. The sentence is what a person reads; the reasoning is what stops the next person deleting it.`);
 }
 for (const entry of contract.sampleEntries) {
  if (!habitIds.has(entry.habit)) throw new Error(`A sample entry names the habit "${entry.habit}", which wellbeing.json has not got.`);
  if (entry.dayOffset > 0) throw new Error(`A sample entry is dated ${entry.dayOffset} days from now. Nobody writes down a day they have not had.`);
  if (/\d/.test(entry.text)) throw new Error(`The sample entry ${JSON.stringify(entry.text)} contains a digit. The fixtures are what everybody copies when they add one; a number in this feature starts in the fixtures.`);
 }

 const banner = () => [
  `Generated by scripts/emit-wellbeing.mjs from ${SOURCE}.`,
  'Do not edit by hand — run `npm run wellbeing`. The build fails if this file and the source',
  'disagree, so an edit here is lost rather than merely wrong.',
  '',
  'Live well. Five habits in a person\'s own words, ten refusals, and no number anywhere: no score,',
  'no grade, no target, no streak, no rank, no percentage and no unit. Three of the refusals below',
  'say those words out loud, because the absence is the feature and a reader cannot see an absence.',
  'A Live well SCREEN may not — scripts/check-boundaries.mjs fails on any of them in a screen, and',
  'skips this file because a generated carrier is the contract in another language.',
  '',
  'Nothing here is measured. No device is read, no permission is asked for, and nothing a person',
  'writes is stored anywhere or sent to anybody. Fictional entries.'
 ].map(line => (line ? `// ${line}` : '//')).join('\n');

 const swiftFile = `${banner()}

import Foundation

enum WellbeingData {
    /// One thing a person might write about. \`prompt\` is a question and never an instruction, and
    /// there is no unit, no range and no field for a number — see the generator.
    struct Habit: Identifiable, Hashable { let id: String; let name: String; let prompt: String }
    /// Something Live well will not do, in the words a person reads. The reasoning stays in the
    /// contract: it is written for whoever is about to delete the sentence, not for the patient.
    struct Refusal: Identifiable, Hashable { let id: String; let sentence: String }
    /// A fictional entry, dated in days from today so the preview never goes stale.
    struct SampleEntry: Hashable { let habit: String; let dayOffset: Int; let text: String }

${wrap(contract.whatItIs.why).map(line => `    // ${line}`).join('\n')}
    static let statement = ${swift(contract.whatItIs.statement)}
    static let isNot = ${swift(contract.whatItIs.isNot)}

${wrap(contract.habitsNote).map(line => `    // ${line}`).join('\n')}
    static let habits: [Habit] = [
${contract.habits.map(h => `        .init(id: ${swift(h.id)}, name: ${swift(h.name)},
              prompt: ${swift(h.prompt)})`).join(',\n')}
    ]
    static func habit(_ id: String) -> Habit? { habits.first { $0.id == id } }

${wrap(contract.neverSoften).map(line => `    // ${line}`).join('\n')}
    static let refusals: [Refusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)},
              sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static func refusal(_ id: String) -> Refusal? { refusals.first { $0.id == id } }

${wrap(contract.sampleEntriesNote).map(line => `    // ${line}`).join('\n')}
    static let sampleEntries: [SampleEntry] = [
${contract.sampleEntries.map(e => `        .init(habit: ${swift(e.habit)}, dayOffset: ${e.dayOffset}, text: ${swift(e.text)})`).join(',\n')}
    ]

${wrap(contract.timeline.why).map(line => `    // ${line}`).join('\n')}
    static let timeline = ${swift(contract.timeline.statement)}

${wrap(contract.takingItToAClinician.why).map(line => `    // ${line}`).join('\n')}
    static let bringIt = ${swift(contract.takingItToAClinician.statement)}
    static let bringItHowItWorks = ${swift(contract.takingItToAClinician.howItWorks)}

    /// ${contract.capabilityNote}
    static let capability = ${swift(contract.capability)}
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

/**
 * One thing a person might write about. [prompt] is a question and never an instruction, and there
 * is no unit, no range and no field for a number — see the generator.
 */
data class WellbeingHabit(val id: String, val name: String, val prompt: String)

/**
 * Something Live well will not do, in the words a person reads. The reasoning stays in the
 * contract: it is written for whoever is about to delete the sentence, not for the patient.
 */
data class WellbeingRefusal(val id: String, val sentence: String)

/** A fictional entry, dated in days from today so the preview never goes stale. */
data class WellbeingSample(val habit: String, val dayOffset: Int, val text: String)

${wrap(contract.habitsNote).map((line, i) => `${i ? '   ' : '/* '}${line}`).join('\n')} */
val wellbeingHabits = listOf(
${contract.habits.map(h => `    WellbeingHabit(${kotlin(h.id)}, ${kotlin(h.name)},
        ${kotlin(h.prompt)}),`).join('\n')}
)

${wrap(contract.neverSoften).map((line, i) => `${i ? '   ' : '/* '}${line}`).join('\n')} */
val wellbeingRefusals = listOf(
${contract.refusals.map(r => `    WellbeingRefusal(${kotlin(r.id)},
        ${kotlin(r.sentence)}),`).join('\n')}
)

${wrap(contract.sampleEntriesNote).map((line, i) => `${i ? '   ' : '/* '}${line}`).join('\n')} */
val wellbeingSamples = listOf(
${contract.sampleEntries.map(e => `    WellbeingSample(${kotlin(e.habit)}, ${e.dayOffset}, ${kotlin(e.text)}),`).join('\n')}
)

object WellbeingData {
${wrap(contract.whatItIs.why).map((line, i) => `${i ? '       ' : '    /* '}${line}`).join('\n')} */
    const val statement = ${kotlin(contract.whatItIs.statement)}
    const val isNot = ${kotlin(contract.whatItIs.isNot)}

${wrap(contract.timeline.why, 88).map((line, i) => `${i ? '       ' : '    /* '}${line}`).join('\n')} */
    const val timeline = ${kotlin(contract.timeline.statement)}

${wrap(contract.takingItToAClinician.why, 88).map((line, i) => `${i ? '       ' : '    /* '}${line}`).join('\n')} */
    const val bringIt = ${kotlin(contract.takingItToAClinician.statement)}
    const val bringItHowItWorks = ${kotlin(contract.takingItToAClinician.howItWorks)}

${wrap(contract.capabilityNote, 88).map((line, i) => `${i ? '       ' : '    /* '}${line}`).join('\n')} */
    const val capability = ${kotlin(contract.capability)}

    fun habit(id: String) = wellbeingHabits.firstOrNull { it.id == id }
    fun refusal(id: String) = wellbeingRefusals.firstOrNull { it.id == id }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/WellbeingData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/WellbeingData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitWellbeing()) {
  writeFileSync(file.path, file.content);
  console.log(`wellbeing → ${file.path}`);
 }
}
