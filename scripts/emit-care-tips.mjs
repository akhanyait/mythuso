/* The care tips, written out for two native apps, by a machine.

   The tips, their categories, the words on the screen and the reviewer notice live in
   packages/catalog/care-tips.json. The web reads that file; iOS and Android get this. A tip is
   health advice, and health advice that is worded one way on a phone and another on the web is
   how a caution gets softened on one of them without anybody deciding it should be.

   Each category's tint is emitted as the design token it names, resolved here against
   packages/design-tokens/tokens.json, so a card's fill and the ink on it are always a pair that
   tokens.json#contrast measures. A tint naming a colour the token file does not have stops the
   generator rather than falling back to something nobody measured.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/care-tips.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const pascal = name => name[0].toUpperCase() + name.slice(1);

const banner = () => [
 `Generated by scripts/emit-care-tips.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run care-tips`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'General guidance, shown after a visit. Not reviewed by a clinician yet — the review notice is',
 'shown beside every tip until one has signed it.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitCareTips(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const colours = JSON.parse(readFileSync(root + 'packages/design-tokens/tokens.json', 'utf8')).color;
 const token = name => {
  if (!(name in colours)) throw new Error(`${SOURCE} names the colour "${name}", which packages/design-tokens/tokens.json does not have.`);
  return name;
 };
 const tintOf = id => {
  const tint = contract.tints[id];
  if (!tint) throw new Error(`${SOURCE}: no tint called "${id}".`);
  return { fill: token(tint.fill), ink: token(tint.ink) };
 };
 const categoryOf = id => {
  const category = contract.categories.find(c => c.id === id);
  if (!category) throw new Error(`${SOURCE}: a tip names the category "${id}", which is not declared.`);
  return category;
 };
 const { screen, door, review } = contract;
 const reviewedBy = review.reviewedBy === null ? 'nil' : swift(review.reviewedBy);
 const reviewedByKt = review.reviewedBy === null ? 'null' : kotlin(review.reviewedBy);

 const swiftFile = `${banner()}

import SwiftUI

enum CareTipsData {
    static let version = ${contract.version}

    enum Review {
        /// Nil until a registered clinician has read and signed the tips.
        static let reviewedBy: String? = ${reviewedBy}
        static let notice = ${swift(review.notice)}
    }

    enum Door {
        static let opens = ${swift(door.opens)}
        static let heading = ${swift(door.heading)}
        static let detail = ${swift(door.detail)}
        static let action = ${swift(door.action)}
        static let opening = ${swift(door.opening)}
    }

    enum Screen {
        static let eyebrow = ${swift(screen.eyebrow)}
        static let heading = ${swift(screen.heading)}
        static let lead = ${swift(screen.lead)}
        /// "{n}" and "{total}" are filled by the screen.
        static let counter = ${swift(screen.counter)}
        static let progressLabel = ${swift(screen.progressLabel)}
        /// "{n}" and "{title}" are filled by the screen.
        static let jumpLabel = ${swift(screen.jumpLabel)}
        static let back = ${swift(screen.back)}
        static let next = ${swift(screen.next)}
        static let startAgain = ${swift(screen.startAgain)}
        static let refusalsHeading = ${swift(screen.refusalsHeading)}
        static let emergencyLabel = ${swift(screen.emergencyLabel)}
    }

    static let refusals: [String] = [
${contract.refusals.map(r => `        ${swift(r.sentence)}`).join(',\n')}
    ]

    static let tips: [CareTip] = [
${contract.tips.map(t => {
  const category = categoryOf(t.category);
  const tint = tintOf(category.tint);
  return `        CareTip(id: ${swift(t.id)}, category: ${swift(category.id)}, tag: ${swift(category.label)},
                title: ${swift(t.title)},
                body: ${swift(t.body)},
                fill: ThusoTheme.${tint.fill}, ink: ThusoTheme.${tint.ink}, dark: ${category.tint === 'night'})`;
 }).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object CareTipsData {
    const val version = ${contract.version}

    object Review {
        /** Null until a registered clinician has read and signed the tips. */
        val reviewedBy: String? = ${reviewedByKt}
        const val notice = ${kotlin(review.notice)}
    }

    object Door {
        const val opens = ${kotlin(door.opens)}
        const val heading = ${kotlin(door.heading)}
        const val detail = ${kotlin(door.detail)}
        const val action = ${kotlin(door.action)}
        const val opening = ${kotlin(door.opening)}
    }

    object Screen {
        const val eyebrow = ${kotlin(screen.eyebrow)}
        const val heading = ${kotlin(screen.heading)}
        const val lead = ${kotlin(screen.lead)}
        /** "{n}" and "{total}" are filled by the screen. */
        const val counter = ${kotlin(screen.counter)}
        const val progressLabel = ${kotlin(screen.progressLabel)}
        /** "{n}" and "{title}" are filled by the screen. */
        const val jumpLabel = ${kotlin(screen.jumpLabel)}
        const val back = ${kotlin(screen.back)}
        const val next = ${kotlin(screen.next)}
        const val startAgain = ${kotlin(screen.startAgain)}
        const val refusalsHeading = ${kotlin(screen.refusalsHeading)}
        const val emergencyLabel = ${kotlin(screen.emergencyLabel)}
    }

    val refusals = listOf(
${contract.refusals.map(r => `        ${kotlin(r.sentence)}`).join(',\n')}
    )

    val tips = listOf(
${contract.tips.map(t => {
  const category = categoryOf(t.category);
  const tint = tintOf(category.tint);
  return `        CareTip(${kotlin(t.id)}, ${kotlin(category.id)}, ${kotlin(category.label)},
            ${kotlin(t.title)},
            ${kotlin(t.body)},
            za.co.mythuso.ui.${pascal(tint.fill)}, za.co.mythuso.ui.${pascal(tint.ink)}, dark = ${category.tint === 'night'})`;
 }).join(',\n')}
    )
}
`;

 /* The web's router is the one reader of this contract on the patient's first load, and it needs two
    strings: the page's name and what to say while the page arrives. Importing the contract there would put
    every tip in the entry bundle — Rollup keeps a JSON module whole in the chunk that loads first — so the
    two are written out on their own, and the door and the stack read the contract behind dynamic imports. */
 const webFile = `// Generated by scripts/emit-care-tips.mjs from ${SOURCE}.
// Do not edit by hand — run \`npm run care-tips\`. The build fails if this file and its source disagree,
// so an edit here is lost rather than merely wrong.
//
// Only the route: the name the router opens and what it says while the screen arrives. The door and the
// tips stay in the contract, read by apps/web/src/lib/care-tips.ts behind dynamic imports.

export const careTipsRoute = {
  opens: ${JSON.stringify(door.opens)},
  opening: ${JSON.stringify(door.opening)},
} as const;
`;

 return [
  { path: 'apps/web/src/lib/care-tips-route.generated.ts', content: webFile },
  { path: 'apps/ios/MyThuso/Models/CareTipsData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/CareTipsData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitCareTips()) {
  writeFileSync(file.path, file.content);
  console.log(`care-tips → ${file.path}`);
 }
}
