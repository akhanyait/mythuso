/* The consent grant roles, written out for two native apps by a machine.

   packages/catalog/consent.json already holds the purposes a person consents to for their own
   account; its `grants` section holds the other half — who else may be let into the record, to see
   what, for which purpose and for how long. This emits the recipient roles and the refusal
   statements, so the grant sheet on a phone offers exactly the roles, default scopes and default
   expiries the web does, and refuses in the same words.

   There is no emitter for the purposes themselves. apps/api and apps/web read consent.json
   directly, and no native screen renders the purposes yet; when one does, it belongs here.

   WHAT THIS GENERATOR REFUSES TO EMIT. A role with no default expiry, because a grant sheet that
   pre-fills "forever" has made the patient's decision for them. And a role whose default scope is
   empty but which is identifiable, because that is a grant with nothing in it that still names a
   recipient — which is only ever the first draft of a grant with something in it.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/consent.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const optional = (value, quote, none) => (value == null ? none : quote(value));

export function emitConsentGrants(root = '') {
 const { grants } = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 if (!grants) throw new Error(`${SOURCE} has no grants section.`);
 for (const role of grants.recipientRoles) {
  if (!Number.isInteger(role.defaultExpiryDays) || role.defaultExpiryDays < 1) throw new Error(`The grant role ${role.id} has no default expiry. Every grant ends.`);
  if (!role.defaultScope.length && role.identifiable !== false) throw new Error(`The grant role ${role.id} names a recipient and opens nothing.`);
  if (!Number.isInteger(role.maxExpiryDays) || role.maxExpiryDays < role.defaultExpiryDays) throw new Error(`The grant role ${role.id} has no ceiling on how long a grant may last, or one shorter than its own default.`);
  if (!Array.isArray(role.allowedPurposes)) throw new Error(`The grant role ${role.id} does not list the purposes a grant to it may name.`);
  if (!Number.isInteger(grants.maximumExpiryDays) || role.maxExpiryDays > grants.maximumExpiryDays) throw new Error(`The grant role ${role.id} may run ${role.maxExpiryDays} days, past the contract-wide ceiling of ${grants.maximumExpiryDays}. No grant lasts longer than that ceiling.`);
 }

 const banner = [
  `Generated by scripts/emit-consent-grants.mjs from ${SOURCE}.`,
  'Do not edit by hand — run `npm run consent-grants`. The build fails if this file and the source',
  'disagree, so an edit here is lost rather than merely wrong.',
  '',
  'Nothing is granted, stored or sent. These are the roles a patient could let into their record,',
  'the defaults a grant sheet starts from, and the sentences it refuses in.'
 ].map(line => (line ? `// ${line}` : '//')).join('\n');

 const swiftFile = `${banner}

import Foundation

enum ConsentGrantsData {
    struct RecipientRole: Identifiable {
        let id: String; let name: String; let engine: String; let defaultScope: [String]
        let defaultExpiryDays: Int; let sealed: Bool; let boundTo: String?; let identifiable: Bool
        let defaultPurpose: String?
        /// The longest a grant to this role may run, and the purposes it may name. The gateway refuses past either.
        let maxExpiryDays: Int; let allowedPurposes: [String]
    }
    struct Refusal: Identifiable { let id: String; let statement: String }

    /* Revocation has no grace period. The number is here so that a screen saying "takes effect
       immediately" is reading it rather than asserting it. */
    static let revocationGraceSeconds = ${grants.revocation.graceSeconds}
    /* No consent grant lasts longer than this, for any role — the founder's decision of ${grants.maximumExpiryDecision.decidedOn}. A grant sheet caps its end-date picker here. */
    static let maximumExpiryDays = ${grants.maximumExpiryDays}

    static let roles: [RecipientRole] = [
${grants.recipientRoles.map(r => `        RecipientRole(id: ${swift(r.id)}, name: ${swift(r.name)}, engine: ${swift(r.engine)},
                      defaultScope: [${r.defaultScope.map(swift).join(', ')}],
                      defaultExpiryDays: ${r.defaultExpiryDays}, sealed: ${r.sealed === true}, boundTo: ${optional(r.boundTo, swift, 'nil')},
                      identifiable: ${r.identifiable !== false}, defaultPurpose: ${optional(r.defaultPurpose, swift, 'nil')},
                      maxExpiryDays: ${r.maxExpiryDays}, allowedPurposes: [${r.allowedPurposes.map(swift).join(', ')}])`).join(',\n')}
    ]

    static let refusals: [Refusal] = [
${grants.refusals.map(r => `        Refusal(id: ${swift(r.id)}, statement: ${swift(r.statement)})`).join(',\n')}
    ]

    static func role(_ id: String) -> RecipientRole? { roles.first { $0.id == id } }
    static func refusal(_ id: String) -> String { refusals.first { $0.id == id }?.statement ?? "" }
}
`;

 const kotlinFile = `${banner}

package za.co.mythuso.model

object ConsentGrantsData {
    data class RecipientRole(
        val id: String, val name: String, val engine: String, val defaultScope: List<String>,
        val defaultExpiryDays: Int, val sealed: Boolean, val boundTo: String?, val identifiable: Boolean,
        val defaultPurpose: String?,
        // The longest a grant to this role may run, and the purposes it may name. The gateway refuses past either.
        val maxExpiryDays: Int, val allowedPurposes: List<String>
    )
    data class Refusal(val id: String, val statement: String)

    // Revocation has no grace period. See the Swift file for why the number is emitted at all.
    const val REVOCATION_GRACE_SECONDS = ${grants.revocation.graceSeconds}
    // No consent grant lasts longer than this, for any role — the founder's decision of ${grants.maximumExpiryDecision.decidedOn}.
    const val MAXIMUM_EXPIRY_DAYS = ${grants.maximumExpiryDays}

    val roles = listOf(
${grants.recipientRoles.map(r => `        RecipientRole(${kotlin(r.id)}, ${kotlin(r.name)}, ${kotlin(r.engine)},
            listOf(${r.defaultScope.map(kotlin).join(', ')}),
            ${r.defaultExpiryDays}, ${r.sealed === true}, ${optional(r.boundTo, kotlin, 'null')}, ${r.identifiable !== false}, ${optional(r.defaultPurpose, kotlin, 'null')},
            ${r.maxExpiryDays}, listOf${r.allowedPurposes.length ? '' : '<String>'}(${r.allowedPurposes.map(kotlin).join(', ')}))`).join(',\n')}
    )

    val refusals = listOf(
${grants.refusals.map(r => `        Refusal(${kotlin(r.id)}, ${kotlin(r.statement)})`).join(',\n')}
    )

    fun role(id: String) = roles.firstOrNull { it.id == id }
    fun refusal(id: String) = refusals.first { it.id == id }.statement
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ConsentGrantsData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ConsentGrantsData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitConsentGrants()) {
  writeFileSync(file.path, file.content);
  console.log(`consent grants → ${file.path}`);
 }
}
