/* Verify in service, written out for two native apps, by a machine.
 *
 * packages/catalog/verify-in-service.json holds every sentence a nurse starting a shift, a patient checking the
 * person at her door and a family making a complaint reads, and packages/catalog/apis/trust.json holds the
 * refusals the routes answer with. The web reads both through packages/engines/src/trust/domain; iOS and Android
 * cannot read JSON at runtime, so the copy is generated rather than typed and scripts/check-boundaries.mjs compares
 * it with what this generator says on every build.
 *
 * THE NUMBERS ARE DEFAULTS, AND SAY SO. How long a door code lasts, how many tries a patient has, how soon a
 * complaint is reviewed and what an unmatched shift start does to dispatch are settings an admin changes on the
 * web. Neither native app reaches a settings route, so each uses the contract's default, written by
 * scripts/settings-defaults.mjs with the one sentence every engine's phone copy carries about whether somebody
 * decided it. A phone never types one.
 *
 * NO SCORE, NO FACE. Nothing here carries a Trust Score or anything about a face, because the contract has neither
 * to give: a badge is a tier name, and a shift start's only outcome is not-integrated.
 *
 * The emergency number a patient in danger at her door is told to call is filled from packages/catalog/sos.json
 * here, so no native file types it.
 *
 * Escaping, as everywhere: Swift needs its quotes escaped; Kotlin needs backslash, quote and $.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/verify-in-service.json';
const API = 'packages/catalog/apis/trust.json';
const TRUST = 'packages/catalog/trust.json';
const SOS = 'packages/catalog/sos.json';

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const sentences = block => Object.entries(block).filter(([key, value]) => typeof value === 'string' && !key.startsWith('_'));

const banner = () => [
 `Generated by scripts/emit-verify-in-service.mjs from ${SOURCE}, ${API}, ${TRUST} and ${SOS}.`,
 'Do not edit by hand — run `npm run verify-in-service`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'The door code lifetime and tries, the complaint review window and the unmatched shift-start rule are PROPOSED',
 'defaults an admin changes on the web back office. This app reaches no settings route, so it uses them as',
 'written here, and they change in the contract, never in this file. Nothing here is a Trust Score or a face.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitVerifyInService(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const trust = JSON.parse(readFileSync(root + TRUST, 'utf8'));
 const sos = JSON.parse(readFileSync(root + SOS, 'utf8'));

 const lifetime = settingDefault(SOURCE, contract, 'door-code-lifetime');
 const attempts = settingDefault(SOURCE, contract, 'door-code-attempts');
 const window = settingDefault(SOURCE, contract, 'complaint-review-hours');
 const rule = settingDefault(SOURCE, contract, 'unmatched-shift-start-dispatch');

 const police = sos.emergency.numbers.find(entry => entry.id === 'police');
 if (!police) throw new Error(`${SOS} has no police number, so the door check cannot tell a patient in danger who to call.`);
 const withPolice = text => text.replace(/\{police\}/g, police.number);
 if (contract.shiftStart.outcome !== 'not-integrated' || contract.shiftStart.matchPerformed !== false) throw new Error(`${SOURCE} says a shift start is matched, and nothing can match a face. Refusing to tell a phone so.`);

 /* The refusals a native screen renders, by the route that answers them, so a phone and an API say one sentence. */
 const routeRefusal = (key, id) => {
  const found = api.routes.find(r => !r.withdrawn && `${r.method} ${r.path}@${r.version}` === key)?.refusals.find(r => r.id === id);
  if (!found) throw new Error(`${API} has no refusal "${id}" on ${key}.`);
  return { id, status: found.status, statement: found.statement };
 };
 const refusals = [
  routeRefusal('POST /v1/trust/shift-starts@2', 'no-current-verification-to-start'),
  routeRefusal('POST /v1/trust/door-codes@1', 'no-badge-to-show-at-a-door'),
  routeRefusal('POST /v1/trust/door-verifications@2', 'no-door-code-for-this-visit'),
  routeRefusal('POST /v1/trust/door-verifications@2', 'door-code-expired'),
  routeRefusal('POST /v1/trust/door-verifications@2', 'door-check-closed'),
  routeRefusal('POST /v1/trust/door-verifications/{appointmentRef}/answer@1', 'door-answer-before-code'),
  routeRefusal('POST /v1/trust/complaints@2', 'complaint-category-unknown'),
  routeRefusal('POST /v1/trust/complaints@2', 'complaint-account-empty-or-long')
 ];
 const tiers = trust.tiers.map(tier => ({ id: tier.id, label: tier.name }));
 const texts = [
  ['ShiftText', sentences(contract.shiftStart)],
  ['NurseDoorText', sentences(contract.door.nurse)],
  ['PatientDoorText', [...sentences(contract.door.patient).map(([key, value]) => [key, withPolice(value)]), ['photo', contract.door.photo.sentence], ['badgeSentence', contract.badge.sentence], ['formWhy', contract.door.formWhy]]],
  ['ComplaintText', [...sentences(contract.complaints.patient), ['nurseNotTold', contract.complaints.patient.nurseNotTold], ['scoreRule', contract.complaints.scoreRule.sentence]].filter((entry, i, all) => all.findIndex(other => other[0] === entry[0]) === i)]
 ];
 const lists = [
  ['dispatchRules', contract.shiftStart.dispatchRules.map(r => ({ id: r.id, label: r.nurse }))],
  ['answers', contract.door.answers],
  ['categories', contract.complaints.categories],
  ['tiers', tiers]
 ];

 const swiftFile = `${banner()}

import Foundation

extension VerifyInService {
    /// ${lifetime.note}
    static let doorCodeMinutes = ${lifetime.value}
    /// ${attempts.note}
    static let doorCodeAttempts = ${attempts.value}
    /// ${window.note}
    static let complaintReviewHours = ${window.value}
    /// ${rule.note}
    static let unmatchedShiftStartDispatch = ${swift(rule.value)}
    /// How many digits a door code has. A design constant of the contract, not a policy.
    static let doorDigits = ${contract.door.digits}
    /// The longest complaint the form takes, in characters.
    static let complaintMaxCharacters = ${contract.complaints.maxCharacters}
    /// What the face-match door answers. Never matched without a provider.
    static let matchOutcome = ${swift(contract.shiftStart.outcome)}

${texts.map(([name, entries]) => `    enum ${name} {
${entries.map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }`).join('\n\n')}

${lists.map(([name, items]) => `    static let ${name}: [VerifyInServiceChoice] = [
${items.map(i => `        .init(id: ${swift(i.id)}, label: ${swift(i.label)})`).join(',\n')}
    ]`).join('\n')}

    static let refusals: [VerifyInServiceRefusal] = [
${refusals.map(r => `        .init(id: ${swift(r.id)}, status: ${r.status}, statement: ${swift(r.statement)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object VerifyInServiceData {
    /** ${lifetime.note} */
    const val doorCodeMinutes = ${lifetime.value}
    /** ${attempts.note} */
    const val doorCodeAttempts = ${attempts.value}
    /** ${window.note} */
    const val complaintReviewHours = ${window.value}
    /** ${rule.note} */
    const val unmatchedShiftStartDispatch = ${kotlin(rule.value)}
    /** How many digits a door code has. A design constant of the contract, not a policy. */
    const val doorDigits = ${contract.door.digits}
    /** The longest complaint the form takes, in characters. */
    const val complaintMaxCharacters = ${contract.complaints.maxCharacters}
    /** What the face-match door answers. Never matched without a provider. */
    const val matchOutcome = ${kotlin(contract.shiftStart.outcome)}

${texts.map(([name, entries]) => `    object ${name} {
${entries.map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }`).join('\n\n')}

${lists.map(([name, items]) => `    val ${name} = listOf(
${items.map(i => `        VerifyInServiceChoice(${kotlin(i.id)}, ${kotlin(i.label)})`).join(',\n')}
    )`).join('\n')}

    val refusals = listOf(
${refusals.map(r => `        VerifyInServiceRefusal(${kotlin(r.id)}, ${r.status}, ${kotlin(r.statement)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/VerifyInServiceData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/VerifyInServiceData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitVerifyInService()) {
  writeFileSync(file.path, file.content);
  console.log(`verify-in-service → ${file.path}`);
 }
}
