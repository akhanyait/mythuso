/* When a visit happens, written out for two native apps, by a machine.

   The timezone, the shape of the offer, the two kinds of booking and the four rules live in
   packages/catalog/scheduling.json. The web reads that file; iOS and Android get this.

   What is deliberately *not* generated is a single date. Every platform had a hand-typed strip —
   ("Fri", "12", "Sep") in Swift, Triple("FRI", "12", "SEP") in Kotlin, the same again in TypeScript —
   which was wrong the day after it was typed, disagreed between the chip and the review line, and
   printed a weekday that did not belong to the date beside it. Generating those labels would only
   move the lie into a machine. So the contract carries the rules and each app computes the days
   from the device clock in the timezone named here.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. The rule sentences carry curly quotes and em-dashes, which are plain
   UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/scheduling.json';

const swift = value => `"${value.replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-scheduling.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run scheduling`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'No date appears below. The days offered are computed from the device clock in the timezone named',
 'here, and a weekday is derived from its own date — which is the defect this contract exists to',
 'close, so writing one out would defeat the point.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitScheduling(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));

 const swiftFile = `${banner()}

import Foundation

extension Scheduling {
    static let timezone = ${swift(contract.timezone)}
    static let timezoneNote = ${swift(contract.timezoneNote)}
    static let daysOffered = ${contract.offer.days}
    static let firstDayOffset = ${contract.offer.firstDayOffset}
    static let firstDayNote = ${swift(contract.offer.firstDayNote)}
    static let slots = [${contract.offer.slots.map(swift).join(', ')}]
    static let slotNote = ${swift(contract.offer.slotNote)}
    static let kinds: [BookingKind] = [
${contract.kinds.map(k => `        .init(id: ${swift(k.id)}, name: ${swift(k.name)}, detail: ${swift(k.detail)},
              showsArrivalEstimate: ${k.showsArrivalEstimate}, confirmation: ${swift(k.confirmation)})`).join(',\n')}
    ]
    static let rules: [SchedulingRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    enum Label {
${Object.keys(contract.labels).map(key => `        static let ${key} = ${swift(contract.labels[key])}`).join('\n')}
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object SchedulingData {
    const val timezone = ${kotlin(contract.timezone)}
    const val timezoneNote = ${kotlin(contract.timezoneNote)}
    const val daysOffered = ${contract.offer.days}
    const val firstDayOffset = ${contract.offer.firstDayOffset}
    const val firstDayNote = ${kotlin(contract.offer.firstDayNote)}
    val slots = listOf(${contract.offer.slots.map(kotlin).join(', ')})
    const val slotNote = ${kotlin(contract.offer.slotNote)}
    val kinds = listOf(
${contract.kinds.map(k => `        BookingKind(${kotlin(k.id)}, ${kotlin(k.name)}, ${kotlin(k.detail)}, ${k.showsArrivalEstimate}, ${kotlin(k.confirmation)})`).join(',\n')}
    )
    val rules = listOf(
${contract.rules.map(r => `        SchedulingRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
    )
${Object.keys(contract.labels).map(key => `    const val ${key} = ${kotlin(contract.labels[key])}`).join('\n')}
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/SchedulingData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/SchedulingData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitScheduling()) {
  writeFileSync(file.path, file.content);
  console.log(`scheduling → ${file.path}`);
 }
}
