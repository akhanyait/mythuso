/* The clinical inbox, and the answers a nurse or a doctor is given when they start triage or guidance, written out
 * for two native apps by a machine.
 *
 * A doctor signs a nurse's visit on a phone as she does on the web. What the phone needs to refuse a signature is
 * packages/catalog/clinical.json's: the signing modes and the sentence each signature carries, the inbox's words,
 * the roles a confirmer must be and the preview's reviews; packages/catalog/records.json's consultation headings
 * and which are required, worked out by packages/engines/src/clinical/domain/contract.ts rather than again here;
 * the refusal sentences of the two inbox routes, and the engine refusals they answer, from
 * packages/catalog/apis/clinical.json; the triage, guidance and outcome-question refusals a start is answered in;
 * and the two Clinical settings' defaults, through scripts/settings-defaults.mjs. The web reads all of it through
 * packages/engines/src/clinical/domain; iOS and Android cannot read JSON at runtime, so the copy is generated
 * rather than typed and scripts/check-boundaries.mjs compares it on every build.
 *
 * WHAT IS NOT WRITTEN. No consultation frame, because no phone writes a consultation in this wave. No triage rule,
 * red flag, priority, script or question, because none exists: the registries are empty and the phone is told the
 * refusal. No value an admin put in force: neither app reaches a settings route, so each uses the defaults written
 * here and says so beside each.
 *
 * Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';
import { requiredHeadings } from '../packages/engines/src/clinical/domain/contract.ts';

const SOURCE = 'packages/catalog/clinical.json';
const API = 'packages/catalog/apis/clinical.json';

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const routeKey = r => `${r.method} ${r.path}@${r.version}`;

/* The routes a phone's inbox and its triage and guidance answers stand for. A route found withdrawn or missing is
   refused here rather than written. */
const PHONE_ROUTES = ['GET /v1/clinical/reviews@2', 'POST /v1/clinical/reviews/{reviewRef}/sign@2', 'POST /v1/clinical/triage@3', 'POST /v1/clinical/guidance@1', 'POST /v1/clinical/proms@2'];

const banner = () => [
 `Generated by scripts/emit-clinical.mjs from ${SOURCE}, packages/catalog/records.json and ${API}.`,
 'Do not edit by hand — run `npm run clinical`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'Who confirms a review and the days outcome questions are asked on are PROPOSALS, with decidedBy null in',
 'the contract, waiting on a clinical review, and defaults an admin changes on the web back office. This app',
 'reaches no settings route and uses them as written here.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitClinical(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const vetting = JSON.parse(readFileSync(root + 'packages/catalog/vetting.json', 'utf8'));
 /* The names of the roles a confirmer may be, so a phone says who signs without typing a role's name. */
 const clinicalRoles = vetting.roles.filter(role => contract.reviews.clinicalRoleHolds.every(capability => (role.grants ?? []).some(grant => grant.capability === capability)));
 if (!clinicalRoles.length) throw new Error('packages/catalog/vetting.json holds no role with every capability packages/catalog/clinical.json calls clinical, so nobody could confirm a review.');
 const confirmers = settingDefault(SOURCE, contract, contract.reviews.confirmerSetting);
 const promDays = settingDefault(SOURCE, contract, contract.proms.scheduleSetting, { list: true });

 const routes = PHONE_ROUTES.map(key => {
  const found = api.routes.find(r => routeKey(r) === key && !r.withdrawn);
  if (!found) throw new Error(`${API} has no live ${key}, which a phone's inbox or its triage and guidance answers stand for.`);
  return found;
 });
 const seen = new Map();
 for (const r of [...routes.flatMap(route => route.refusals), ...api.refusals.filter(r => (r.answeredBy ?? []).some(k => PHONE_ROUTES.includes(k)))]) {
  const before = seen.get(r.id);
  if (before && (before.status !== r.status || before.statement !== r.statement)) throw new Error(`${API} declares "${r.id}" in two different sentences on the routes a phone stands for.`);
  seen.set(r.id, { id: r.id, status: r.status, statement: r.statement });
 }
 const refusals = [...seen.values()];
 const words = section => Object.entries(section).filter(([key, value]) => typeof value === 'string' && !key.startsWith('_'));
 const [waiting, signed] = contract.reviews.states;
 const mode = code => {
  const found = contract.reviews.signingModes.find(m => m.code === code);
  if (!found) throw new Error(`${SOURCE} has lost the signing mode ${code}.`);
  return found;
 };
 const under = mode('under-ratified-protocol'), outside = mode('outside-any-protocol');
 const notTriaged = contract.triage.notTriaged;
 const list = (items, write) => items.map(write).join(', ');
 const optional = (value, write) => (value === null || value === undefined ? 'nil' : write(value));
 const optionalKt = (value, write) => (value === null || value === undefined ? 'null' : write(value));

 const swiftFile = `${banner()}

import Foundation

enum ClinicalData {
    struct Mode: Identifiable, Hashable { let id: String; let label: String; let sentence: String; let noProtocolSentence: String? }
    struct Refusal: Identifiable, Hashable { let id: String; let status: Int; let statement: String }
    struct Outcome: Identifiable, Hashable { let id: String; let label: String }
    struct PreviewReview: Identifiable, Hashable {
        let id: String; let encounterRef: String; let subjectRef: String; let protocolVersionId: String?
        let sectionsWritten: [String]; let signedOff: Bool
    }

    /// ${confirmers.note}
    static let confirmers = [${list(confirmers.value, swift)}]
    /// ${promDays.note}
    static let promDays = [${promDays.value.join(', ')}]
    /// A role may confirm a review only if the vetting register grants it every one of these.
    static let clinicalRoleHolds = [${list(contract.reviews.clinicalRoleHolds, swift)}]
    /// The clinical roles on the vetting register, by name.
    static let roleNames: [String: String] = [${clinicalRoles.map(role => `${swift(role.id)}: ${swift(role.name)}`).join(', ')}]
    /// The consultation's required headings, worked out from records.json by the Clinical domain.
    static let requiredHeadings = [${list(requiredHeadings, swift)}]

    static let waiting = ${swift(waiting.code)}
    static let signed = ${swift(signed.code)}
    static let underProtocol = ${swift(under.code)}
    static let outsideProtocol = ${swift(outside.code)}
    static let modes: [Mode] = [
${contract.reviews.signingModes.map(m => `        .init(id: ${swift(m.code)}, label: ${swift(m.label)}, sentence: ${swift(m.sentence)}, noProtocolSentence: ${optional(m.noProtocolSentence, swift)})`).join(',\n')}
    ]

    enum InboxText {
${words(contract.reviews.screen).map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }
    enum TriageText {
${words(contract.triage.screen).map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
        static let notTriaged = ${swift(notTriaged.label)}
        static let human = ${swift(notTriaged.human)}
        static let emergencyFirst = ${swift(notTriaged.emergencyFirst)}
    }
    static let triageRoutesTo = [${list(notTriaged.routesTo, swift)}]
    /// The protocols the board has named triage protocols. Empty until it names one.
    static let triageProtocols: [String] = [${list(contract.triage.triageProtocols.ids, swift)}]
    /// The ratified guidance scripts, by reference. Empty until the board writes one.
    static let guidanceScripts: [String] = [${list(contract.guidance.scripts.map(s => s.scriptRef), swift)}]
    /// The outcome instruments the board chose. Empty until it chooses one.
    static let promInstruments: [String] = [${list(contract.proms.instruments.map(i => i.id), swift)}]
    enum GuidanceText {
${words(contract.guidance.screen).map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }
    static let outcomes: [Outcome] = [
${contract.guidance.outcomes.map(o => `        .init(id: ${swift(o.code)}, label: ${swift(o.label)})`).join(',\n')}
    ]
    enum PromText {
${words(contract.proms.screen).map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }

    static let refusals: [Refusal] = [
${refusals.map(r => `        .init(id: ${swift(r.id)}, status: ${r.status}, statement: ${swift(r.statement)})`).join(',\n')}
    ]

    static let previewWrittenBy = ${swift(contract.preview.writtenBy)}
    static let previewReviews: [PreviewReview] = [
${contract.preview.reviews.map(r => `        .init(id: ${swift(r.appointmentRef)}, encounterRef: ${swift(r.encounterRef)}, subjectRef: ${swift(r.subjectRef)}, protocolVersionId: ${optional(r.protocolVersionId, swift)}, sectionsWritten: [${list(r.sectionsWritten, swift)}], signedOff: ${r.signedOff})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object ClinicalData {
    data class Mode(val id: String, val label: String, val sentence: String, val noProtocolSentence: String?)
    data class Refusal(val id: String, val status: Int, val statement: String)
    data class Outcome(val id: String, val label: String)
    data class PreviewReview(
        val appointmentRef: String, val encounterRef: String, val subjectRef: String, val protocolVersionId: String?,
        val sectionsWritten: List<String>, val signedOff: Boolean
    )

    /** ${confirmers.note} */
    val confirmers = listOf(${list(confirmers.value, kotlin)})
    /** ${promDays.note} */
    val promDays = listOf(${promDays.value.join(', ')})
    /** A role may confirm a review only if the vetting register grants it every one of these. */
    val clinicalRoleHolds = listOf(${list(contract.reviews.clinicalRoleHolds, kotlin)})
    /** The clinical roles on the vetting register, by name. */
    val roleNames = mapOf(${clinicalRoles.map(role => `${kotlin(role.id)} to ${kotlin(role.name)}`).join(', ')})
    /** The consultation's required headings, worked out from records.json by the Clinical domain. */
    val requiredHeadings = listOf(${list(requiredHeadings, kotlin)})

    const val waiting = ${kotlin(waiting.code)}
    const val signed = ${kotlin(signed.code)}
    const val underProtocol = ${kotlin(under.code)}
    const val outsideProtocol = ${kotlin(outside.code)}
    val modes = listOf(
${contract.reviews.signingModes.map(m => `        Mode(${kotlin(m.code)}, ${kotlin(m.label)}, ${kotlin(m.sentence)}, ${optionalKt(m.noProtocolSentence, kotlin)})`).join(',\n')}
    )

    object InboxText {
${words(contract.reviews.screen).map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }
    object TriageText {
${words(contract.triage.screen).map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
        const val notTriaged = ${kotlin(notTriaged.label)}
        const val human = ${kotlin(notTriaged.human)}
        const val emergencyFirst = ${kotlin(notTriaged.emergencyFirst)}
    }
    val triageRoutesTo = listOf(${list(notTriaged.routesTo, kotlin)})
    /** The protocols the board has named triage protocols. Empty until it names one. */
    val triageProtocols: List<String> = listOf(${list(contract.triage.triageProtocols.ids, kotlin)})
    /** The ratified guidance scripts, by reference. Empty until the board writes one. */
    val guidanceScripts: List<String> = listOf(${list(contract.guidance.scripts.map(s => s.scriptRef), kotlin)})
    /** The outcome instruments the board chose. Empty until it chooses one. */
    val promInstruments: List<String> = listOf(${list(contract.proms.instruments.map(i => i.id), kotlin)})
    object GuidanceText {
${words(contract.guidance.screen).map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }
    val outcomes = listOf(
${contract.guidance.outcomes.map(o => `        Outcome(${kotlin(o.code)}, ${kotlin(o.label)})`).join(',\n')}
    )
    object PromText {
${words(contract.proms.screen).map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }

    val refusals = listOf(
${refusals.map(r => `        Refusal(${kotlin(r.id)}, ${r.status}, ${kotlin(r.statement)})`).join(',\n')}
    )

    const val previewWrittenBy = ${kotlin(contract.preview.writtenBy)}
    val previewReviews = listOf(
${contract.preview.reviews.map(r => `        PreviewReview(${kotlin(r.appointmentRef)}, ${kotlin(r.encounterRef)}, ${kotlin(r.subjectRef)}, ${optionalKt(r.protocolVersionId, kotlin)}, listOf(${list(r.sectionsWritten, kotlin)}), ${r.signedOff})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ClinicalData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ClinicalData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitClinical()) {
  writeFileSync(file.path, file.content);
  console.log(`clinical → ${file.path}`);
 }
}
