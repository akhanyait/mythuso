/* The crisis lines GilbertOne's emergency answer adds, written out for two native apps, by a machine.

   The lines, the group that shows them and the sentence above them live in
   packages/catalog/crisis-lines.json. The web reads that file; iOS and Android get this. The numbers
   were already in the tree, in packages/catalog/knowledge/mental-health.json, and the build fails if
   the two files disagree — so a crisis number is typed in one contract, checked against its source,
   and never by hand into Swift or Kotlin, where a wrong digit is somebody in a crisis ringing a
   stranger.

   The lines reuse GilbertLine, the type the ambulance numbers already use, so each app prints them
   with the same function and in the same column as the ambulance numbers — and, like them, never
   dials.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/crisis-lines.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-crisis-lines.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run crisis-lines`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Shown on the emergency answer when, and only when, the message matched the crisis group of',
 'packages/catalog/gilbert-emergency-terms.json — after the ambulance numbers, never instead of them.',
 'Not reviewed by a clinician yet; required before real patients.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitCrisisLines(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));

 const swiftFile = `${banner()}

import Foundation

extension Gilbert {
    enum Crisis {
        static let version = ${contract.version}
        /// The emergency-terms group whose match adds these lines to the emergency answer.
        static let group = ${swift(contract.showsWhen.group)}
        static let heading = ${swift(contract.heading)}
        static let lines: [GilbertLine] = [
${contract.lines.map(l => `            GilbertLine(number: ${swift(l.number)}, spoken: ${swift(l.spoken)}, name: ${swift(l.name)})`).join(',\n')}
        ]
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object CrisisLinesData {
    const val version = ${contract.version}
    /** The emergency-terms group whose match adds these lines to the emergency answer. */
    const val group = ${kotlin(contract.showsWhen.group)}
    const val heading = ${kotlin(contract.heading)}
    val lines = listOf(
${contract.lines.map(l => `        GilbertLine(${kotlin(l.number)}, ${kotlin(l.spoken)}, ${kotlin(l.name)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/CrisisLinesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/CrisisLinesData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitCrisisLines()) {
  writeFileSync(file.path, file.content);
  console.log(`crisis-lines → ${file.path}`);
 }
}
