/* The doctor's medical certificate, written out for two native apps, by a machine.

   The fields, the limits, the consultations, the refusal sentences and the screen's words live in
   packages/catalog/sick-note.json. The web reads it directly through apps/web/src/lib/sick-note.ts; iOS
   and Android get this. A certificate is a legal document under rule 16 and section 23, and a limit
   worded one way on a phone and another on the web is how a phone comes to backdate further than the
   web without anybody deciding it should.

   Two things are read from other contracts rather than restated: a certificate from a call with nobody in
   the room is refused in packages/catalog/teleconsult.json's own words, named by basis.callOnlyFrom, and the
   certificate criteria protocol's name, version and status are packages/catalog/protocols.json's.
   The nurse's refusal is the sentence she already reads on her assessment, held equal to its three typed
   copies by scripts/check-sick-note.mjs. A name that resolves to nothing stops the generator rather than
   writing an empty string somebody would have to notice.

   The doctor's own refusal for a lapsed registration is not here: it is the vetting register's grant for
   issue-medical-certificate, which scripts/emit-vetting.mjs already writes into both phones.

   Escaping: Swift needs its backslashes and quotes escaped; Kotlin needs backslash, quote and dollar,
   because a lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/sick-note.json';

const swift = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const swiftList = items => `[${items.map(swift).join(', ')}]`;
const kotlinList = items => `listOf(${items.map(kotlin).join(', ')})`;
const optional = (value, quote, none) => (value === null || value === undefined ? none : quote(value));

const banner = () => [
 `Generated by scripts/emit-sick-note.mjs from ${SOURCE}, the teleconsultation's refusal and the protocol it names.`,
 'Do not edit by hand — run `npm run sick-note`. The build fails if this file and its sources',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Nothing here issues a certificate. The preview signs nothing, sends nothing and stores nothing.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitSickNote(root = '') {
 const read = path => JSON.parse(readFileSync(root + path, 'utf8'));
 const c = read(SOURCE);
 const teleconsult = read('packages/catalog/teleconsult.json');
 const protocols = read('packages/catalog/protocols.json');

 /* The criteria protocol as the register holds it: its name, its version and its status's name, never typed. */
 const protocol = protocols.protocols.find(p => p.id === c.protocol.id);
 const status = protocol && protocols.statuses.find(s => s.id === protocol.status);
 if (!protocol || !status) throw new Error(`${SOURCE}'s protocol.id names ${c.protocol.id}, which packages/catalog/protocols.json does not hold with a known status.`);
 const protocolLine = `${protocol.name}, version ${protocol.version}: ${status.name.toLowerCase()}. ${c.protocol.sentence}`;

 /* "packages/catalog/teleconsult.json#issued.items.certificate.condition" — the item by id, then its field. */
 const [, file, itemId, key] = c.basis.callOnlyFrom.match(/^([^#]+)#issued\.items\.([\w-]+)\.(\w+)$/) ?? [];
 if (file !== 'packages/catalog/teleconsult.json') throw new Error(`${SOURCE}'s basis.callOnlyFrom names ${c.basis.callOnlyFrom}, which is not an issued item of packages/catalog/teleconsult.json.`);
 const callOnly = teleconsult.issued.items.find(item => item.id === itemId)?.[key];
 if (!callOnly) throw new Error(`${SOURCE}'s basis.callOnlyFrom names ${c.basis.callOnlyFrom}, which packages/catalog/teleconsult.json does not carry.`);

 /* Every refusal, resolved to its words. `registration` is the vetting register's and stays there. */
 const refusals = c.refusals.filter(r => r.id !== 'registration').map(r => {
  if (r.sentence) return [r.id, r.sentence];
  if (r.from === 'basis.callOnlyFrom') return [r.id, callOnly];
  if (r.from === 'issuer.notADoctor') return [r.id, c.issuer.notADoctor];
  throw new Error(`${SOURCE}'s refusal "${r.id}" has no sentence and names ${r.from}, which the generator does not know how to read.`);
 });
 const label = id => {
  const field = c.fields.find(f => f.id === id);
  if (!field) throw new Error(`${SOURCE} has no field "${id}".`);
  return field.label;
 };
 const labelIds = ['practitioner', 'registration', 'qualification', 'practiceNumber', 'practiceAddress', 'patient', 'consultation', 'basis', 'statement', 'period', 'issued', 'signature'];
 const s = c.screen;
 const screenKeys = Object.keys(s);

 const webFile = `// Generated by scripts/emit-sick-note.mjs from ${SOURCE}, packages/catalog/teleconsult.json and packages/catalog/protocols.json.
// Do not edit by hand — run \`npm run sick-note\`. The build fails if this file and its sources disagree,
// so an edit here is lost rather than merely wrong.

/** A certificate from a call with nobody in the room, refused in the consultation contract's own words. */
export const callOnlyRefusal = ${JSON.stringify(callOnly)};
/** The certificate criteria protocol as packages/catalog/protocols.json holds it, and what that means here. */
export const protocolLine = ${JSON.stringify(protocolLine)};
`;

 const swiftFile = `${banner()}

import Foundation

enum SickNoteData {
    static let version = ${c.version}
    static let capability = ${swift(c.issuer.capability)}
    static let notIssued = ${swift(c.notIssued)}
    static let notIssuedShort = ${swift(c.notIssuedShort)}
    static let memoryOnly = ${swift(c.memoryOnly)}
    static let notADoctor = ${swift(c.issuer.notADoctor)}
    static let writers: [String] = ${swiftList(c.issuer.writers)}
    static let notHeld = ${swift(c.notHeld)}
    static let notCarried: [String] = ${swiftList(c.notCarried.map(n => n.sentence))}
    /// The certificate criteria protocol as packages/catalog/protocols.json holds it.
    static let protocolLine = ${swift(protocolLine)}

    enum Basis {
        static let homeVisit = ${swift(c.basis.homeVisit)}
        static let byVideo = ${swift(c.basis.byVideo)}
        static let backdated = ${swift(c.basis.backdated)}
    }

    enum Diagnosis {
        static let consentLabel = ${swift(c.diagnosis.consentLabel)}
        static let descriptionLabel = ${swift(c.diagnosis.descriptionLabel)}
        static let descriptionHint = ${swift(c.diagnosis.descriptionHint)}
        static let descriptionMaxLength = ${c.diagnosis.descriptionMaxLength}
        static let withheld = ${swift(c.diagnosis.withheld)}
    }

    enum Period {
        static let backdateDays = ${c.period.backdateDays}
        static let maxDays = ${c.period.maxDays}
        static let defaultDays = ${c.period.defaultDays}
    }

    enum Screen {
${screenKeys.map(k => `        static let ${k} = ${swift(s[k])}`).join('\n')}
    }

    /// Rule 16's items, labelled as the contract labels them.
    static let labels: [String: String] = [
${labelIds.map(id => `        ${swift(id)}: ${swift(label(id))}`).join(',\n')}
    ]

    static let fitness: [SickNoteFitness] = [
${c.fitness.map(f => `        .init(id: ${swift(f.id)}, label: ${swift(f.label)}, statement: ${swift(f.statement)})`).join(',\n')}
    ]

    /// Day offsets from today, so the preview never goes stale.
    static let consultations: [SickNoteConsultation] = [
${c.consultations.map(k => `        .init(reference: ${swift(k.reference)}, patient: ${swift(k.patient)}, kind: ${swift(k.kind)}, nurse: ${optional(k.nurse, swift, 'nil')}, dayOffset: ${k.dayOffset}, time: ${swift(k.time)})`).join(',\n')}
    ]

    /// Every refusal but the lapsed registration's, which is the vetting register's. "{days}" is filled by the model.
    static let refusals: [String: String] = [
${refusals.map(([id, sentence]) => `        ${swift(id)}: ${swift(sentence)}`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object SickNoteData {
    const val version = ${c.version}
    const val capability = ${kotlin(c.issuer.capability)}
    const val notIssued = ${kotlin(c.notIssued)}
    const val notIssuedShort = ${kotlin(c.notIssuedShort)}
    const val memoryOnly = ${kotlin(c.memoryOnly)}
    const val notADoctor = ${kotlin(c.issuer.notADoctor)}
    val writers = ${kotlinList(c.issuer.writers)}
    const val notHeld = ${kotlin(c.notHeld)}
    val notCarried = ${kotlinList(c.notCarried.map(n => n.sentence))}
    /** The certificate criteria protocol as packages/catalog/protocols.json holds it. */
    const val protocolLine = ${kotlin(protocolLine)}

    object Basis {
        const val homeVisit = ${kotlin(c.basis.homeVisit)}
        const val byVideo = ${kotlin(c.basis.byVideo)}
        const val backdated = ${kotlin(c.basis.backdated)}
    }

    object Diagnosis {
        const val consentLabel = ${kotlin(c.diagnosis.consentLabel)}
        const val descriptionLabel = ${kotlin(c.diagnosis.descriptionLabel)}
        const val descriptionHint = ${kotlin(c.diagnosis.descriptionHint)}
        const val descriptionMaxLength = ${c.diagnosis.descriptionMaxLength}
        const val withheld = ${kotlin(c.diagnosis.withheld)}
    }

    object Period {
        const val backdateDays = ${c.period.backdateDays}
        const val maxDays = ${c.period.maxDays}
        const val defaultDays = ${c.period.defaultDays}
    }

    object Screen {
${screenKeys.map(k => `        const val ${k} = ${kotlin(s[k])}`).join('\n')}
    }

    /** Rule 16's items, labelled as the contract labels them. */
    val labels = mapOf(
${labelIds.map(id => `        ${kotlin(id)} to ${kotlin(label(id))}`).join(',\n')}
    )

    val fitness = listOf(
${c.fitness.map(f => `        SickNoteFitness(${kotlin(f.id)}, ${kotlin(f.label)}, ${kotlin(f.statement)})`).join(',\n')}
    )

    /** Day offsets from today, so the preview never goes stale. */
    val consultations = listOf(
${c.consultations.map(k => `        SickNoteConsultation(${kotlin(k.reference)}, ${kotlin(k.patient)}, ${kotlin(k.kind)}, ${optional(k.nurse, kotlin, 'null')}, ${k.dayOffset}, ${kotlin(k.time)})`).join(',\n')}
    )

    /** Every refusal but the lapsed registration's, which is the vetting register's. "{days}" is filled by the model. */
    val refusals = mapOf(
${refusals.map(([id, sentence]) => `        ${kotlin(id)} to ${kotlin(sentence)}`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/web/src/lib/sick-note.generated.ts', content: webFile },
  { path: 'apps/ios/MyThuso/Models/SickNoteData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/SickNoteData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitSickNote()) {
  writeFileSync(file.path, file.content);
  console.log(`sick-note → ${file.path}`);
 }
}
