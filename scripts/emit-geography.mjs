/* Where MyThuso works, written out for two native apps, by a machine.

   The suburbs, their working radii, the map window and every privacy rule about what a map may
   draw live in packages/catalog/geography.json. The web reads that file; iOS and Android get this.

   Three copies of Johannesburg existed before this: a list of suburbs inside a React component, a
   second inside a SwiftUI view and a third inside a composable. They had already drifted — the same
   suburb sat at a different latitude in two of them — and nothing in the build could notice, because
   a coordinate typed into a view is not a number anything else can disagree with. Now there is one
   Johannesburg and two derived copies.

   What is deliberately *not* generated is the arithmetic. Distance, projection, province lookup and
   arrival estimates are packages/geo, hand-written on each platform against that directory's README,
   because those are decisions and a generator would hide the decision. Coordinates are data. The
   difference is the whole reason this file emits one and not the other.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/geography.json';

const swift = value => `"${value.replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

/* Coordinates are written at the precision the contract declares and no further. Emitting the raw
   JSON number would let a fourth decimal place reach a native app the moment somebody typed one
   into the contract, which is exactly the precision the privacy rule refuses. */
const fixed = (n, decimals) => n.toFixed(decimals);

/* Every one of these is a Double on both platforms. Emitting the raw JSON number writes `3` for a
   3.0 radius, which Kotlin reads as an Int and refuses. One decimal place, always. */
const real = n => n.toFixed(1);

const banner = () => [
 `Generated by scripts/emit-geography.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run geography`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Coordinates only. The arithmetic that consumes them — distance, projection, province, arrival',
 'estimate — is hand-written on this platform against packages/geo/README.md, because those are',
 'decisions rather than data and generating them would hide the decision.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitGeography(root = '') {
 const c = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const dp = c.precision.decimals;

 const swiftFile = `${banner()}

import Foundation

extension Geography {
    static let city = ${swift(c.coverage.city)}
    static let province = ${swift(c.coverage.province)}
    static let phase = ${c.coverage.phase}
    static let coverageSentence = ${swift(c.coverage.sentence)}

    static let centre = Point(lat: ${fixed(c.window.centre.lat, dp)}, lng: ${fixed(c.window.centre.lng, dp)})
    static let spanKm = ${real(c.window.spanKm)}
    static let zoom = ${real(c.window.zoom)}
    static let minZoom = ${real(c.window.minZoom)}
    /// Fifteen is a privacy limit, not a performance one: above it a reader can pick out one house.
    static let maxZoom = ${real(c.window.maxZoom)}

    static let coordinateDecimals = ${dp}
    static let precisionMetres = ${c.precision.metres}
    static let precisionSentence = ${swift(c.precision.sentence)}

    static let zones: [Zone] = [
${c.zones.map(z => `        .init(id: ${swift(z.id)}, name: ${swift(z.name)},
              at: Point(lat: ${fixed(z.at.lat, dp)}, lng: ${fixed(z.at.lng, dp)}), radiusKm: ${real(z.radiusKm)})`).join(',\n')}
    ]

    static let marks: [MapMark] = [
${c.marks.map(m => `        .init(id: ${swift(m.id)}, name: ${swift(m.name)}, detail: ${swift(m.detail)})`).join(',\n')}
    ]

    /// No tile server is contacted by any native build. The schematic below is what both apps draw.
    static let schematicName = ${swift(c.rendering.withoutToken.name)}
    static let schematicSentence = ${swift(c.rendering.withoutToken.sentence)}
    static let attributionRequired = ${c.rendering.attributionRequired}

    static let privacySentence = ${swift(c.privacy.sentence)}
    static let privacyRules: [GeographyRule] = [
${c.privacy.rules.map(r => `        .init(id: ${swift(r.id)}, statement: ${swift(r.statement)}, why: ${swift(r.why)})`).join(',\n')}
    ]

    static let refusals: [GeographyRefusal] = [
${c.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)}, why: ${swift(r.why)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object GeographyData {
    const val city = ${kotlin(c.coverage.city)}
    const val province = ${kotlin(c.coverage.province)}
    const val phase = ${c.coverage.phase}
    const val coverageSentence = ${kotlin(c.coverage.sentence)}

    val centre = LatLng(${fixed(c.window.centre.lat, dp)}, ${fixed(c.window.centre.lng, dp)})
    const val spanKm = ${real(c.window.spanKm)}
    const val zoom = ${real(c.window.zoom)}
    const val minZoom = ${real(c.window.minZoom)}
    /** Fifteen is a privacy limit, not a performance one: above it a reader can pick out one house. */
    const val maxZoom = ${real(c.window.maxZoom)}

    const val coordinateDecimals = ${dp}
    const val precisionMetres = ${c.precision.metres}
    const val precisionSentence = ${kotlin(c.precision.sentence)}

    val zones = listOf(
${c.zones.map(z => `        Zone(${kotlin(z.id)}, ${kotlin(z.name)}, LatLng(${fixed(z.at.lat, dp)}, ${fixed(z.at.lng, dp)}), ${real(z.radiusKm)})`).join(',\n')}
    )

    val marks = listOf(
${c.marks.map(m => `        MapMark(${kotlin(m.id)}, ${kotlin(m.name)}, ${kotlin(m.detail)})`).join(',\n')}
    )

    /** No tile server is contacted by any native build. The schematic below is what both apps draw. */
    const val schematicName = ${kotlin(c.rendering.withoutToken.name)}
    const val schematicSentence = ${kotlin(c.rendering.withoutToken.sentence)}
    const val attributionRequired = ${c.rendering.attributionRequired}

    const val privacySentence = ${kotlin(c.privacy.sentence)}
    val privacyRules = listOf(
${c.privacy.rules.map(r => `        GeographyRule(${kotlin(r.id)}, ${kotlin(r.statement)}, ${kotlin(r.why)})`).join(',\n')}
    )

    val refusals = listOf(
${c.refusals.map(r => `        GeographyRefusal(${kotlin(r.id)}, ${kotlin(r.sentence)}, ${kotlin(r.why)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/GeographyData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/GeographyData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitGeography()) {
  writeFileSync(file.path, file.content);
  console.log(`geography → ${file.path}`);
 }
}
