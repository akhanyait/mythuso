/* The account holder's own health record, written out for two native apps by a machine.

   This contract exists because the fixture was typed three times. The holder, the reviewing doctor,
   four sets of readings and the three sentences of the last review were declared once in
   apps/web/src/lib/passport.ts, once in apps/ios/MyThuso/Models/Passport.swift and once in
   apps/android/app/src/main/java/za/co/mythuso/model/Passport.kt, with nothing comparing them — and
   two of the three had already drifted to a different number of charts. The Kotlin file said as
   much at the top and named this file as the fix.

   What is generated is the record: who holds it, who reviews it, what was measured and when, what
   the doctor said, what documents came out of the last visit, the two device integrations and the
   five sentences the permission screens refuse in.

   What is deliberately not generated is anything a range decides. No reference range, unit or label
   is written below: a reading is judged against packages/catalog/records.json through RecordsData,
   which is the one place those seven numbers live, and a copy of one here would be the fourth. The
   documents carry no date of their own either — each is issued out of the visit the last reading set
   was taken at, computed here, so a document cannot claim a day on which no visit happened.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. The sentences here carry curly quotes, em-dashes and an arrow, all of
   which are plain UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/passport.json';

const swift = value => `"${value.replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
/* Kotlin's Map<String, Double> will not take an integer literal, and Swift's will. So the readings
   are written with a decimal point on one platform and as they stand on the other, from the same
   number in the same contract. */
const double = value => (Number.isInteger(value) ? `${value}.0` : String(value));
const list = (values, quote) => values.map(quote).join(', ');
/* The contract's notes are paragraphs and both languages want them as comments, so they are wrapped
   here rather than emitted as one line a reader has to scroll. */
const wrap = (text, indent, opener, continuation) => {
 const lines = text.split(' ').reduce((acc, word) => {
  const last = acc[acc.length - 1];
  if (last && (last + ' ' + word).length <= 96 - indent.length) acc[acc.length - 1] = `${last} ${word}`;
  else acc.push(word);
  return acc;
 }, []);
 return lines.map((line, i) => `${indent}${i ? continuation : opener}${line}`).join('\n');
};
const swiftNote = text => wrap(text, '    ', '/* ', '   ') + ' */';
const kotlinNote = text => wrap(text, '    ', '// ', '// ');

const banner = () => [
 `Generated by scripts/emit-passport.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run passport`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'No reference range appears below, and none is coming from here. What a reading is judged against',
 'lives in packages/catalog/records.json and reaches this app as RecordsData; a copy beside the',
 'reading it flags is how a number that decides whether a doctor sees something comes to have two',
 'answers.',
 '',
 'Fictional patient, invented readings, nothing stored and nothing sent.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitPassport(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const { holder, reviewer, readingSets, headline, lastReview, documents, devices, refusals } = contract;
 /* Every document is issued out of the visit the last readings were taken at. Derived here rather
    than written down four times in the contract, for the same reason the labels are derived from
    the offsets: a date that is stored can disagree with the visit it came from. */
 const issuedDayOffset = readingSets[readingSets.length - 1].dayOffset;

 const swiftFile = `${banner()}

import Foundation

enum PassportData {
    struct Holder { let name: String; let passportId: String; let issuedBy: String }
    struct Reviewer { let name: String; let registration: String }
    struct Readings { let dayOffset: Int; let values: [String: Double]; let note: String? }
    struct Review { let assessment: String; let plan: String; let next: String; let reviewedDayOffset: Int }
    struct Document { let name: String; let kind: String; let dayOffset: Int; let reviewed: Bool; let opens: String? }
    struct Device: Identifiable { let id: String; let name: String; let offeredOn: [String]; let sheet: String; let withdraw: String }
    struct Refusal: Identifiable { let id: String; let sentence: String }

    static let holder = Holder(name: ${swift(holder.name)}, passportId: ${swift(holder.passportId)},
                               issuedBy: ${swift(holder.issuedBy)})
    static let reviewer = Reviewer(name: ${swift(reviewer.name)}, registration: ${swift(reviewer.registration)})

${swiftNote(contract.readingSetsNote)}
    static let readingSets: [Readings] = [
${readingSets.map(set => `        Readings(dayOffset: ${set.dayOffset},
                 values: [${Object.entries(set.values).map(([id, value]) => `${swift(id)}: ${value}`).join(', ')}],
                 note: ${set.note ? swift(set.note) : 'nil'})`).join(',\n')}
    ]

${swiftNote(headline.why)}
    static let headlineMeasures = [${list(headline.measures, swift)}]

    static let lastReview = Review(
        assessment: ${swift(lastReview.assessment)},
        plan: ${swift(lastReview.plan)},
        next: ${swift(lastReview.next)},
        reviewedDayOffset: ${lastReview.reviewedDayOffset})

${swiftNote(contract.documentsNote)}
    static let documents: [Document] = [
${documents.map(d => `        Document(name: ${swift(d.name)}, kind: ${swift(d.kind)}, dayOffset: ${issuedDayOffset},
                 reviewed: ${d.reviewed === true}, opens: ${d.opens ? swift(d.opens) : 'nil'})`).join(',\n')}
    ]

${swiftNote(contract.devicesNote)}
    static let devices: [Device] = [
${devices.map(d => `        Device(id: ${swift(d.id)}, name: ${swift(d.name)}, offeredOn: [${list(d.offeredOn, swift)}],
               sheet: ${swift(d.sheet)},
               withdraw: ${swift(d.withdraw)})`).join(',\n')}
    ]
    static func devicesOn(_ platform: String) -> [Device] { devices.filter { $0.offeredOn.contains(platform) } }

    /* The sentences the passport says out loud rather than merely obeys. "Nothing on this screen
       interprets a reading for you" is the one that matters: a trends screen that says which way a
       line is going has almost interpreted it, and a screen that only *behaves* carefully still
       reads as a verdict. */
    static let refusals: [Refusal] = [
${refusals.map(r => `        Refusal(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static func refusal(_ id: String) -> String { refusals.first { $0.id == id }?.sentence ?? "" }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object PassportData {
    data class Holder(val name: String, val passportId: String, val issuedBy: String)
    data class Reviewer(val name: String, val registration: String)
    data class Readings(val dayOffset: Long, val values: Map<String, Double>, val note: String? = null)
    data class Review(val assessment: String, val plan: String, val next: String, val reviewedDayOffset: Long)
    data class Document(val name: String, val kind: String, val dayOffset: Long, val reviewed: Boolean, val opens: String? = null)
    data class Device(val id: String, val name: String, val offeredOn: List<String>, val sheet: String, val withdraw: String)
    data class Refusal(val id: String, val sentence: String)

    val holder = Holder(${kotlin(holder.name)}, ${kotlin(holder.passportId)}, ${kotlin(holder.issuedBy)})
    val reviewer = Reviewer(${kotlin(reviewer.name)}, ${kotlin(reviewer.registration)})

${kotlinNote(contract.readingSetsNote)}
    val readingSets = listOf(
${readingSets.map(set => `        Readings(${set.dayOffset}, mapOf(${Object.entries(set.values).map(([id, value]) => `${kotlin(id)} to ${double(value)}`).join(', ')})${set.note ? `, ${kotlin(set.note)}` : ''})`).join(',\n')}
    )

${kotlinNote(headline.why)}
    val headlineMeasures = listOf(${list(headline.measures, kotlin)})

    val lastReview = Review(
        ${kotlin(lastReview.assessment)},
        ${kotlin(lastReview.plan)},
        ${kotlin(lastReview.next)},
        ${lastReview.reviewedDayOffset}
    )

${kotlinNote(contract.documentsNote)}
    val documents = listOf(
${documents.map(d => `        Document(${kotlin(d.name)}, ${kotlin(d.kind)}, ${issuedDayOffset}, ${d.reviewed === true}${d.opens ? `, ${kotlin(d.opens)}` : ''})`).join(',\n')}
    )

${kotlinNote(contract.devicesNote)}
    val devices = listOf(
${devices.map(d => `        Device(${kotlin(d.id)}, ${kotlin(d.name)}, listOf(${list(d.offeredOn, kotlin)}),
               ${kotlin(d.sheet)},
               ${kotlin(d.withdraw)})`).join(',\n')}
    )
    fun devicesOn(platform: String) = devices.filter { platform in it.offeredOn }

    // The sentences the passport says out loud rather than merely obeys. See the Swift banner above.
    val refusals = listOf(
${refusals.map(r => `        Refusal(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
    )
    fun refusal(id: String) = refusals.first { it.id == id }.sentence
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/PassportData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/PassportData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitPassport()) {
  writeFileSync(file.path, file.content);
  console.log(`passport → ${file.path}`);
 }
}
