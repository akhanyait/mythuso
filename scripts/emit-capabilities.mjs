/* What MyThuso can actually do, written out for two native apps, by a machine.

   packages/catalog/capabilities.json is the one place that knows whether a thing is connected, and
   the sentence a screen shows while it is not. The web imports that file directly. iOS and Android
   cannot, so the contract is written into a Swift file and a Kotlin file here and compared against
   the sources on every build by scripts/check-boundaries.mjs.

   Generating rather than transcribing matters more on this contract than on most of the others.
   Every sentence in it is a sentence about what this product cannot do, and the failure mode the
   file was written against is nobody lying — it is somebody softening one of them at eleven at
   night because a screenshot looked better without it. A softened copy on one platform is a
   different promise on that platform, and it would be invisible: the screen still says something
   reassuring, and only the wording moved. There is no wording to move here. There is one sentence,
   one writer of it, and a build that fails when a copy disagrees.

   Three shapes in the contract need saying out loud, because each of them is a field that is absent
   rather than empty on most capabilities:
     - `evidence` is null until something exists to point at. It becomes String? / String?.
     - `neverSoften` is carried by two capabilities — voice and emergency — and by no others.
     - `requiresPermissions` is carried by voice among the capabilities and by the flags that ask
       for one: each entry names a permission, the platform it is declared on and the feature it
       serves. The apps are given the capabilities' permission names only — what each serves is for
       the reader of the contract and for scripts/check-boundaries.mjs, which allows no permission a
       capability or flag has not named there. It is written out as an empty list on the capabilities
       rather than skipped, so a new one is a data change and not a generator change.

   `flags` is the one list in the contract that is not capabilities at all: each entry is a boolean
   a build reads before it does the thing the flag names, false until the contract says otherwise.
   Both platforms get it — Swift as a `static let` inside the Capabilities extension, Kotlin as a
   top-level `const val` beside `capabilityRules` — because a gate that differs between two
   platforms is a gate on one of them, and turning one on belongs in a diff to the contract rather
   than in a source file.

   The keys beginning with an underscore — _note, _honestyNote, _permissionsNote — are commentary
   for whoever opens the contract, and they are deliberately not emitted. No other emitter carries
   them either: a generated file has its own banner explaining itself, and a paragraph about why the
   contract exists, restated in Swift, would be a second copy of prose nobody reads in that file.
   What the apps need is the data and the sentences a person is shown.

   Escaping is the hazard, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and a
       lone $ starts a string template — a `$` in a blockedBy line would either fail to compile or,
       worse, quietly interpolate something. None of the sentences carries one today; the escaper is
       written for the one that will.
   The em-dashes, curly quotes and en-dashes in these sentences are simply UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/capabilities.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const listSwift = values => values.length ? `[${values.map(swift).join(', ')}]` : '[]';
const listKotlin = values => values.length ? `listOf(${values.map(kotlin).join(', ')})` : 'emptyList()';
/* A permission is written into the contract with the feature it serves. The apps need its name. */
const permissionNames = capability => (capability.requiresPermissions ?? []).map(p => (typeof p === 'string' ? p : p.permission));
const optionalSwift = value => (value ? swift(value) : 'nil');
const optionalKotlin = value => (value ? kotlin(value) : 'null');

const banner = (count, permissions) => [
 `Generated by scripts/emit-capabilities.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run capabilities`. The build fails if this file and its source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 `The ${count} things MyThuso either does or only draws, and the sentence each one shows while it`,
 'is not connected. No screen writes its own version of that sentence: it names a capability and',
 'the sentence is rendered from here, word for word, or it is not rendered at all. When an',
 'integration lands, one boolean changes in the contract and the notice disappears from every',
 'platform at once.',
 '',
 'The flags at the end are not capabilities: each is a boolean a build reads before it does the',
 'thing the flag names, false until the contract says otherwise, and emitted so both platforms',
 'read one value rather than two.',
 '',
 'The keys beginning with an underscore in the contract are commentary and are not written out.',
 `\`requiresPermissions\` names the only permissions either app may declare — ${permissions} across the`,
 'capabilities and flags of this contract — and scripts/check-boundaries.mjs refuses any',
 'permission no capability or flag has asked for.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitCapabilities(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));

 /* The generator is the first reader of the contract, so it is the first place a missing sentence
    can be named. Without this a capability that has lost its notice reaches a string escaper and
    comes back as a TypeError with no field in it — true, and useless to whoever has to fix it. */
 for (const capability of contract.capabilities) {
  for (const field of ['id', 'name', 'notice']) {
   if (typeof capability[field] !== 'string' || !capability[field]) {
    throw new Error(`Capability "${capability.id ?? '?'}" has no ${field}. ${SOURCE} is not complete enough to write two native apps from.`);
   }
  }
  if (typeof capability.connected !== 'boolean') throw new Error(`Capability "${capability.id}" does not say whether it is connected, which is the only question this contract exists to answer.`);

  /* Three states, and the generator refuses a contract that half-declares one. A simulated
     capability whose block did not reach the native apps would render the absent sentence — a nurse
     told nothing is connected while a simulator answers her, which is the disclosure failure the
     third state was introduced to prevent rather than a cosmetic one. */
  if (!['absent', 'on-device', 'simulated', 'connected'].includes(capability.state)) throw new Error(`Capability "${capability.id}" has state ${JSON.stringify(capability.state)}. A generated file cannot carry a state nothing declares.`);
  if ((capability.state === 'simulated') !== Boolean(capability.simulation)) throw new Error(`Capability "${capability.id}" says state "${capability.state}" and ${capability.simulation ? 'carries' : 'carries no'} simulation block. One of the two is wrong and the generated file would ship it to three platforms.`); }
 for (const rule of contract.rules) {
  for (const field of ['id', 'statement', 'why']) {
   if (typeof rule[field] !== 'string' || !rule[field]) throw new Error(`Rule "${rule.id ?? '?'}" has no ${field}.`);
  }
 }
 /* Flags are validated here for the same reason capabilities are: the constant a caller gates on
    is only worth generating from a flag that says what it is and what it is for, and a boolean
    with no sentence is one nobody can decide to turn on. */
 for (const flag of contract.flags ?? []) {
  for (const field of ['id', 'statement', 'why']) {
   if (typeof flag[field] !== 'string' || !flag[field]) throw new Error(`Flag "${flag.id ?? '?'}" has no ${field}.`);
  }
  if (typeof flag.enabled !== 'boolean') throw new Error(`Flag "${flag.id}" does not say whether it is enabled. A flag with no boolean is a comment.`);
 }
 const permissionTotal = [...contract.capabilities, ...(contract.flags ?? [])].flatMap(permissionNames).length;

 const swiftFile = `${banner(contract.capabilities.length, permissionTotal)}

import Foundation

extension Capabilities {
    /// In the contract's own order, which is roughly the order a person meets them.
    static let all: [Capability] = [
${contract.capabilities.map(c => `        Capability(id: ${swift(c.id)}, name: ${swift(c.name)}, connected: ${c.connected},
                   evidence: ${optionalSwift(c.evidence)},
                   blockedBy: [
${(c.blockedBy ?? []).map(x => `                       ${swift(x)}`).join(',\n')}
                   ],
                   notice: ${swift(c.notice)},
                   state: ${swift(c.state)},
                   simulation: ${c.simulation ? `Simulation(supplier: ${swift(c.simulation.supplier)},
                                              notice: ${swift(c.simulation.notice)},
                                              refuses: [
${c.simulation.refuses.map(x => `                                                  ${swift(x)}`).join(',\n')}
                                              ])` : 'nil'},
                   surfaces: ${listSwift(c.surfaces ?? [])},
                   neverSoften: ${optionalSwift(c.neverSoften)},
                   requiresPermissions: ${listSwift(permissionNames(c))})`).join(',\n')}
    ]

    /* How the notices are meant to be used. Rendered on the readiness screens rather than only
       obeyed, because a rule nobody can read is a rule the next person breaks by accident. */
    static let rules: [CapabilityRule] = [
${contract.rules.map(r => `        CapabilityRule(id: ${swift(r.id)},
                       statement: ${swift(r.statement)},
                       why: ${swift(r.why)})`).join(',\n')}
    ]

    /* The flags: a boolean a caller reads before it does the thing the flag names. Not a
       capability — no notice, no state — and false until packages/catalog/capabilities.json says
       otherwise, so turning one on is a change to the contract and not to a source file. */
${(contract.flags ?? []).map(f => `    /// ${f.statement}
    /// ${f.why}
    static let ${f.id} = ${f.enabled}`).join('\n\n')}
}
`;

 /* Kotlin gets the two data classes as well as the values. Every other contract in this repository
    keeps its types in a hand-written model file beside the generated one, and this one will too the
    day an Android screen needs them — but that screen does not exist yet, and a generated file
    referencing types nobody has written does not compile. When it lands, its model reads these
    rather than declaring a second pair. */
 const kotlinFile = `${banner(contract.capabilities.length, permissionTotal)}

package za.co.mythuso.model

/** One thing MyThuso either does or only draws. \`evidence\` is null until there is a file to open,
 *  \`neverSoften\` is carried only by the two capabilities somebody would be tempted to soften, and
 *  \`requiresPermissions\` names permissions an app may declare: voice alone carries any among these
 *  capabilities, and the build refuses any permission no capability or flag has named. */
data class Simulation(val supplier: String, val notice: String, val refuses: List<String>)

data class Capability(
    val id: String,
    val name: String,
    val connected: Boolean,
    val evidence: String?,
    val blockedBy: List<String>,
    val notice: String,
    /** "absent", "on-device", "simulated" or "connected". A simulated capability is never quieter than an absent
     *  one: it renders [Simulation.notice] where the absent notice would have gone. */
    val state: String,
    val simulation: Simulation?,
    val surfaces: List<String>,
    val neverSoften: String?,
    val requiresPermissions: List<String>
) {
    /** The sentence a screen shows, or null because the thing is real now. Never call [notice]
     *  directly: a simulated capability that showed the absent sentence would be telling a nurse
     *  nothing is connected while a simulator answers her. */
    val noticeToShow: String? get() = if (connected) null else simulation?.notice ?: notice
}

data class CapabilityRule(val id: String, val statement: String, val why: String)

/** In the contract's own order, which is roughly the order a person meets them. */
val capabilities = listOf(
${contract.capabilities.map(c => `    Capability(${kotlin(c.id)}, ${kotlin(c.name)}, ${c.connected},
        ${optionalKotlin(c.evidence)},
        listOf(
${(c.blockedBy ?? []).map(x => `            ${kotlin(x)}`).join(',\n')}
        ),
        ${kotlin(c.notice)},
        ${kotlin(c.state)},
        ${c.simulation ? `Simulation(${kotlin(c.simulation.supplier)}, ${kotlin(c.simulation.notice)}, listOf(
${c.simulation.refuses.map(x => `            ${kotlin(x)}`).join(',\n')}
        ))` : 'null'},
        ${listKotlin(c.surfaces ?? [])},
        ${optionalKotlin(c.neverSoften)},
        ${listKotlin(permissionNames(c))})`).join(',\n')}
)

/* How the notices are meant to be used. Rendered on the readiness screens rather than only obeyed,
   because a rule nobody can read is a rule the next person breaks by accident. */
val capabilityRules = listOf(
${contract.rules.map(r => `    CapabilityRule(${kotlin(r.id)},
        ${kotlin(r.statement)},
        ${kotlin(r.why)})`).join(',\n')}
)

/* The flags: a boolean a caller reads before it does the thing the flag names. Not a capability —
   no notice, no state — and false until packages/catalog/capabilities.json says otherwise, so
   turning one on is a change to the contract and not to a source file. */
${(contract.flags ?? []).map(f => `/** ${f.statement}
 *  ${f.why} */
const val ${f.id} = ${f.enabled}`).join('\n\n')}
`;

 /* The web's first view reads a projection rather than the contract, because the contract travels whole wherever it is
    imported and most of it is for people deciding whether to trust the product: the rules, the evidence, the surfaces,
    the permissions and the commentary. A patient opening her visits on metered data is shown a capability's name, whether
    it is connected, its state, its notice, what blocks it and what its stand-in is and refuses, and nothing else is read
    by any screen on that view. The rules stay in the contract and reach only the status page, through
    apps/web/src/lib/capability-rules.ts. Written as data from the contract, so no sentence in it can be softened here. */
 const firstView = contract.capabilities.map(c => ({
  id: c.id, name: c.name, connected: c.connected, state: c.state, notice: c.notice, blockedBy: c.blockedBy ?? [],
  simulation: c.simulation ? { supplier: c.simulation.supplier, notice: c.simulation.notice, refuses: c.simulation.refuses } : null
 }));
 const webFile = `${[
  `Generated by scripts/emit-capabilities.mjs from ${SOURCE}.`,
  'Do not edit by hand — run `npm run capabilities`. The build fails if this file and its source',
  'disagree, so an edit here is lost rather than merely wrong.',
  '',
  `The ${contract.capabilities.length} capabilities as the web's first view reads them: each one's name, connection, state,`,
  'notice, what blocks it and what its stand-in is and refuses, word for word from the contract. The rules, the flags,',
  'the evidence, the surfaces, the permissions and the commentary are not written out, so a patient does not download',
  'them to read her visits; the status page reads the rules through lib/capability-rules.ts.'
 ].map(line => (line ? `// ${line}` : '//')).join('\n')}

export type FirstViewCapability = {
 readonly id: string;
 readonly name: string;
 readonly connected: boolean;
 readonly state: string;
 readonly notice: string;
 readonly blockedBy: readonly string[];
 readonly simulation: { readonly supplier: string; readonly notice: string; readonly refuses: readonly string[] } | null;
};

export const capabilities: readonly FirstViewCapability[] = ${JSON.stringify(firstView, null, 1)};
`;

 return [
  { path: 'apps/ios/MyThuso/Models/CapabilitiesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/CapabilitiesData.kt', content: kotlinFile },
  { path: 'apps/web/src/lib/capabilities.generated.ts', content: webFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitCapabilities()) {
  writeFileSync(file.path, file.content);
  console.log(`capabilities → ${file.path}`);
 }
}
