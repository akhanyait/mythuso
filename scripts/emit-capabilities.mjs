/* What MyThuso can actually do, written out for two native apps, by a machine.

   packages/catalog/capabilities.json is the one place that knows whether a thing is connected, and
   the sentence a screen shows while it is not. The web imports that file directly. iOS and Android
   cannot, so the contract is written into a Swift file and a Kotlin file here and compared against
   the sources on every build by scripts/check-boundaries.mjs.

   Generating rather than transcribing matters more on this contract than on most of the others.
   Every sentence in it is a sentence about what this product cannot do, and the failure mode the
   file was written against is nobody lying — it is somebody softening one of them at eleven at
   night because a screenshot looked better without it. A softened copy on one platform is a
   different promise on that platform, and it would be invisible: the screen still says something
   reassuring, and only the wording moved. There is no wording to move here. There is one sentence,
   one writer of it, and a build that fails when a copy disagrees.

   Three shapes in the contract need saying out loud, because each of them is a field that is absent
   rather than empty on most capabilities:
     - `evidence` is null until something exists to point at. It becomes String? / String?.
     - `neverSoften` is carried by two capabilities — voice and emergency — and by no others.
     - `requiresPermissions` is on none of them today. Both apps declare zero permissions, and
       scripts/check-boundaries.mjs will only allow one that some capability has named here. The
       field is written out as an empty list rather than skipped so that the day it stops being
       empty is a data change and not a change to this generator.

   The keys beginning with an underscore — _note, _honestyNote, _permissionsNote — are commentary
   for whoever opens the contract, and they are deliberately not emitted. No other emitter carries
   them either: a generated file has its own banner explaining itself, and a paragraph about why the
   contract exists, restated in Swift, would be a second copy of prose nobody reads in that file.
   What the apps need is the data and the sentences a person is shown.

   Escaping is the hazard, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and a
       lone $ starts a string template — a `$` in a blockedBy line would either fail to compile or,
       worse, quietly interpolate something. None of the sentences carries one today; the escaper is
       written for the one that will.
   The em-dashes, curly quotes and en-dashes in these sentences are simply UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/capabilities.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const listSwift = values => values.length ? `[${values.map(swift).join(', ')}]` : '[]';
const listKotlin = values => values.length ? `listOf(${values.map(kotlin).join(', ')})` : 'emptyList()';
const optionalSwift = value => (value ? swift(value) : 'nil');
const optionalKotlin = value => (value ? kotlin(value) : 'null');

const banner = count => [
 `Generated by scripts/emit-capabilities.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run capabilities`. The build fails if this file and its source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 `The ${count} things MyThuso either does or only draws, and the sentence each one shows while it`,
 'is not connected. No screen writes its own version of that sentence: it names a capability and',
 'the sentence is rendered from here, word for word, or it is not rendered at all. When an',
 'integration lands, one boolean changes in the contract and the notice disappears from every',
 'platform at once.',
 '',
 'The keys beginning with an underscore in the contract are commentary and are not written out.',
 '`requiresPermissions` is empty on every capability, which is why both apps may still declare no',
 'permission at all — scripts/check-boundaries.mjs refuses any permission no capability has asked',
 'for.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitCapabilities(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));

 /* The generator is the first reader of the contract, so it is the first place a missing sentence
    can be named. Without this a capability that has lost its notice reaches a string escaper and
    comes back as a TypeError with no field in it — true, and useless to whoever has to fix it. */
 for (const capability of contract.capabilities) {
  for (const field of ['id', 'name', 'notice']) {
   if (typeof capability[field] !== 'string' || !capability[field]) {
    throw new Error(`Capability "${capability.id ?? '?'}" has no ${field}. ${SOURCE} is not complete enough to write two native apps from.`);
   }
  }
  if (typeof capability.connected !== 'boolean') throw new Error(`Capability "${capability.id}" does not say whether it is connected, which is the only question this contract exists to answer.`);
 }
 for (const rule of contract.rules) {
  for (const field of ['id', 'statement', 'why']) {
   if (typeof rule[field] !== 'string' || !rule[field]) throw new Error(`Rule "${rule.id ?? '?'}" has no ${field}.`);
  }
 }

 const swiftFile = `${banner(contract.capabilities.length)}

import Foundation

extension Capabilities {
    /// In the contract's own order, which is roughly the order a person meets them.
    static let all: [Capability] = [
${contract.capabilities.map(c => `        Capability(id: ${swift(c.id)}, name: ${swift(c.name)}, connected: ${c.connected},
                   evidence: ${optionalSwift(c.evidence)},
                   blockedBy: [
${(c.blockedBy ?? []).map(x => `                       ${swift(x)}`).join(',\n')}
                   ],
                   notice: ${swift(c.notice)},
                   surfaces: ${listSwift(c.surfaces ?? [])},
                   neverSoften: ${optionalSwift(c.neverSoften)},
                   requiresPermissions: ${listSwift(c.requiresPermissions ?? [])})`).join(',\n')}
    ]

    /* How the notices are meant to be used. Rendered on the readiness screens rather than only
       obeyed, because a rule nobody can read is a rule the next person breaks by accident. */
    static let rules: [CapabilityRule] = [
${contract.rules.map(r => `        CapabilityRule(id: ${swift(r.id)},
                       statement: ${swift(r.statement)},
                       why: ${swift(r.why)})`).join(',\n')}
    ]
}
`;

 /* Kotlin gets the two data classes as well as the values. Every other contract in this repository
    keeps its types in a hand-written model file beside the generated one, and this one will too the
    day an Android screen needs them — but that screen does not exist yet, and a generated file
    referencing types nobody has written does not compile. When it lands, its model reads these
    rather than declaring a second pair. */
 const kotlinFile = `${banner(contract.capabilities.length)}

package za.co.mythuso.model

/** One thing MyThuso either does or only draws. \`evidence\` is null until there is a file to open,
 *  \`neverSoften\` is carried only by the two capabilities somebody would be tempted to soften, and
 *  \`requiresPermissions\` is empty on all of them — which is what lets both apps ask a device for
 *  nothing at all. */
data class Capability(
    val id: String,
    val name: String,
    val connected: Boolean,
    val evidence: String?,
    val blockedBy: List<String>,
    val notice: String,
    val surfaces: List<String>,
    val neverSoften: String?,
    val requiresPermissions: List<String>
)

data class CapabilityRule(val id: String, val statement: String, val why: String)

/** In the contract's own order, which is roughly the order a person meets them. */
val capabilities = listOf(
${contract.capabilities.map(c => `    Capability(${kotlin(c.id)}, ${kotlin(c.name)}, ${c.connected},
        ${optionalKotlin(c.evidence)},
        listOf(
${(c.blockedBy ?? []).map(x => `            ${kotlin(x)}`).join(',\n')}
        ),
        ${kotlin(c.notice)},
        ${listKotlin(c.surfaces ?? [])},
        ${optionalKotlin(c.neverSoften)},
        ${listKotlin(c.requiresPermissions ?? [])})`).join(',\n')}
)

/* How the notices are meant to be used. Rendered on the readiness screens rather than only obeyed,
   because a rule nobody can read is a rule the next person breaks by accident. */
val capabilityRules = listOf(
${contract.rules.map(r => `    CapabilityRule(${kotlin(r.id)},
        ${kotlin(r.statement)},
        ${kotlin(r.why)})`).join(',\n')}
)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/CapabilitiesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/CapabilitiesData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitCapabilities()) {
  writeFileSync(file.path, file.content);
  console.log(`capabilities → ${file.path}`);
 }
}
