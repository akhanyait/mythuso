/* Hands-free conversation mode, written out for two native apps, by a machine.

   The founder's decision of 28 September 2026 — speak, pause, and GilbertOne answers, never on top of
   you — lives in packages/catalog/conversation-mode.json: the pause that means "your turn", the
   amendment's utterance cap, the idle rounds before the microphone closes, the barge-in rule and its
   thresholds, every way a conversation ends, the indicator and retention rules, what the mode is not,
   and the sentences a panel shows. The web and packages/gilbertone read that file; iOS and Android get
   this. Neither phone renders a conversation screen yet — the file exists so that the day one does,
   the numbers and the sentences are already the contract's and not a Swift or Kotlin author's.

   The two tunable numbers are read through scripts/settings-defaults.mjs, the one place a setting's
   default is read for a phone and the one place the sentence about whether it was decided is written.
   The contract keeps them under proposedSettings — a settings block is reached only through
   packages/catalog/settings.json#sources, which this change leaves alone — so the block is handed to the
   helper as the settings block it is shaped as. packages/gilbertone/src/speech-state.ts resolves the same
   two keys, so all three platforms run on one default.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a lone $
   starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingBounds, settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/conversation-mode.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-conversation-mode.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run conversation-mode`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Hands-free conversation with GilbertOne, decided by the founder on 28 September 2026. Nothing on',
 'either phone renders it yet; the numbers and the sentences are here so that when one does they are',
 'the contract\'s.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitConversationMode(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 /* The proposed block, in the shape of a settings block, handed to the shared helper as one. */
 const asSettings = { settings: contract.proposedSettings };
 const endpoint = settingDefault(SOURCE, asSettings, contract.endpoint.settingKey);
 const endpointRange = settingBounds(SOURCE, asSettings, contract.endpoint.settingKey);
 const idle = settingDefault(SOURCE, asSettings, contract.sleep.settingKey);
 const idleRange = settingBounds(SOURCE, asSettings, contract.sleep.settingKey);
 const { sentences, bargeIn, endsOn, whatItIsNot, indicator, retention, starts } = contract;

 const swiftFile = `${banner()}

import Foundation

enum ConversationModeData {
    static let version = ${contract.version}
    static let decidedBy = ${swift(contract.decidedBy)}
    static let decidedOn = ${swift(contract.on)}
    /// The founder's brief, verbatim.
    static let why = ${swift(contract.why)}

    /// The numbers the speech machine runs on, in the units the contract gives them.
    enum Timing {
        /// The pause after the last word that means it is GilbertOne's turn. ${endpoint.note}
        static let endpointSilenceMs = ${endpoint.value}
        /// The range an admin may set the pause within.
        static let endpointSilenceMsLowest = ${endpointRange.lowest}
        static let endpointSilenceMsHighest = ${endpointRange.highest}
        /// The amendment's cap on one utterance.
        static let utteranceCapSeconds = ${contract.utteranceCapSeconds}
        /// Utterances in one exchange before a continue is refused.
        static let maxUtterancesPerExchange = ${contract.maxUtterancesPerExchange}
        /// Listening windows that hear nothing before the microphone closes on its own. ${idle.note}
        static let idleRoundsBeforeSleep = ${idle.value}
        static let idleRoundsBeforeSleepLowest = ${idleRange.lowest}
        static let idleRoundsBeforeSleepHighest = ${idleRange.highest}
    }

    enum BargeIn {
        static let rule = ${swift(bargeIn.rule)}
        /// Words heard over the reading before it counts as somebody talking rather than a cough.
        static let minWords = ${bargeIn.minWords}
        static let minSpeechMs = ${bargeIn.minSpeechMs}
        static let ownVoiceFilter = ${swift(bargeIn.ownVoiceFilter.rule)}
        static let keepsTranscript = ${bargeIn.keepsTranscript}
    }

    struct EndsOn {
        let id: String
        let sentence: String
        let event: String
    }

    /// Every way a conversation ends, in the contract's order.
    static let endsOn: [EndsOn] = [
${endsOn.map(e => `        EndsOn(id: ${swift(e.id)}, sentence: ${swift(e.sentence)}, event: ${swift(e.event)})`).join(',\n')}
    ]

    static let startsSentence = ${swift(starts.sentence)}
    static let indicatorRule = ${swift(indicator.rule)}
    static let retentionRule = ${swift(retention.rule)}
    static let audioKept = ${retention.audioKept}

    static let whatItIsNot: [String] = [
${whatItIsNot.map(s => `        ${swift(s)}`).join(',\n')}
    ]

    enum Sentences {
${Object.entries(sentences).filter(([k]) => !k.startsWith('_')).map(([k, v]) => `        static let ${k} = ${swift(v)}`).join('\n')}
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object ConversationModeData {
    const val version = ${contract.version}
    const val decidedBy = ${kotlin(contract.decidedBy)}
    const val decidedOn = ${kotlin(contract.on)}
    /** The founder's brief, verbatim. */
    const val why = ${kotlin(contract.why)}

    /** The numbers the speech machine runs on, in the units the contract gives them. */
    object Timing {
        /** The pause after the last word that means it is GilbertOne's turn. ${endpoint.note} */
        const val endpointSilenceMs = ${endpoint.value}
        /** The range an admin may set the pause within. */
        const val endpointSilenceMsLowest = ${endpointRange.lowest}
        const val endpointSilenceMsHighest = ${endpointRange.highest}
        /** The amendment's cap on one utterance. */
        const val utteranceCapSeconds = ${contract.utteranceCapSeconds}
        /** Utterances in one exchange before a continue is refused. */
        const val maxUtterancesPerExchange = ${contract.maxUtterancesPerExchange}
        /** Listening windows that hear nothing before the microphone closes on its own. ${idle.note} */
        const val idleRoundsBeforeSleep = ${idle.value}
        const val idleRoundsBeforeSleepLowest = ${idleRange.lowest}
        const val idleRoundsBeforeSleepHighest = ${idleRange.highest}
    }

    object BargeIn {
        const val rule = ${kotlin(bargeIn.rule)}
        /** Words heard over the reading before it counts as somebody talking rather than a cough. */
        const val minWords = ${bargeIn.minWords}
        const val minSpeechMs = ${bargeIn.minSpeechMs}
        const val ownVoiceFilter = ${kotlin(bargeIn.ownVoiceFilter.rule)}
        const val keepsTranscript = ${bargeIn.keepsTranscript}
    }

    data class EndsOn(val id: String, val sentence: String, val event: String)

    /** Every way a conversation ends, in the contract's order. */
    val endsOn = listOf(
${endsOn.map(e => `        EndsOn(${kotlin(e.id)}, ${kotlin(e.sentence)}, ${kotlin(e.event)})`).join(',\n')}
    )

    const val startsSentence = ${kotlin(starts.sentence)}
    const val indicatorRule = ${kotlin(indicator.rule)}
    const val retentionRule = ${kotlin(retention.rule)}
    const val audioKept = ${retention.audioKept}

    val whatItIsNot = listOf(
${whatItIsNot.map(s => `        ${kotlin(s)}`).join(',\n')}
    )

    object Sentences {
${Object.entries(sentences).filter(([k]) => !k.startsWith('_')).map(([k, v]) => `        const val ${k} = ${kotlin(v)}`).join('\n')}
    }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ConversationModeData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ConversationModeData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitConversationMode()) {
  writeFileSync(file.path, file.content);
  console.log(`conversation-mode → ${file.path}`);
 }
}
