/* The consultation toolkit, written out for two native apps by a machine.
 *
 * packages/catalog/consultation-toolkit.json holds the tools a clinician reaches in a consultation, the order each
 * role reaches them in, the sentences said where a tool is refused or waiting, and what the toolkit itself will
 * not do. A phone cannot read JSON at runtime, so this writes the same contract into ConsultationToolkitData.swift
 * and ConsultationToolkitData.kt rather than leaving two hand-typed copies to drift.
 *
 * WHAT IS NOT EMITTED. Anything the phones already hold from another contract: a capability's notice is
 * capabilities.json's and is read through each app's generated CapabilitiesData; the refusal a room without a
 * nurse is given is teleconsult.json's and is read through TeleconsultData by its id; whether a clinical limit
 * needs the nurse is the same file's. Only the ids travel, so there is one copy of each sentence on a phone.
 *
 * Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $, because a lone $ starts a
 * template.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/consultation-toolkit.json';

const swift = value => {
 if (value === null || value === undefined) return 'nil';
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => value === null || value === undefined ? 'null' : `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const camel = key => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const typeOf = evidence => evidence ? evidence.split('#')[1] : null;

const banner = () => [
 `Generated by scripts/emit-consultation-toolkit.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run consultation-toolkit`. The build fails if this file and its source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Every tool here is a screen that already exists, reached from the consultation. Nothing in this file sends,',
 'books, prescribes or certifies; each tool keeps its own capability notice and its own refusals.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitConsultationToolkit(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const words = Object.entries(contract.words);
 const gates = Object.entries(contract.gates);

 const swiftTool = t => `        .init(id: ${swift(t.id)}, name: ${swift(t.name)}, short: ${swift(t.short)}, capability: ${swift(t.capability)}, summary: ${swift(t.summary)}, `
  + `honesty: ${swift(t.honesty.capability)}, drawnByToolkit: ${t.honesty.drawnBy === 'toolkit'}, decision: ${!!t.decision}, signsAfterCall: ${!!t.signsAfterCall}, pending: ${!!t.pending}, `
  + `onCall: [${(t.onCall ?? []).map(g => `.init(limit: ${swift(g.limit)}, refusal: ${swift(g.refusal)})`).join(', ')}], `
  + `iosScreen: ${swift(typeOf(t.screens.ios))})`;
 const swiftSurface = s => `        .init(id: ${swift(s.id)}, role: ${swift(s.role)}, homeId: ${swift(s.home.id)}, homeName: ${swift(s.home.name)}, homeShort: ${swift(s.home.short)}, `
  + `heading: ${swift(s.heading)}, from: ${swift(s.from ?? null)}, tools: [${s.tools.map(swift).join(', ')}], `
  + `refused: [${(s.refused ?? []).map(r => `.init(tool: ${swift(r.tool)}, sentence: ${swift(r.sentence)})`).join(', ')}])`;

 const swiftFile = `${banner()}

import Foundation

extension ConsultationToolkit {
    static let tools: [ToolkitToolSpec] = [
${contract.tools.map(swiftTool).join(',\n')}
    ]
    static let surfaces: [ToolkitSurfaceSpec] = [
${contract.surfaces.map(swiftSurface).join(',\n')}
    ]
    /// What the toolkit itself will not do. A refusal with no surfaces is said on every one.
    static let refusals: [ToolkitRefusalSpec] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)}, surfaces: [${(r.surfaces ?? []).map(swift).join(', ')}])`).join(',\n')}
    ]

    enum Gates {
${gates.map(([key, value]) => `        static let ${camel(key)} = ${swift(value)}`).join('\n')}
    }
    enum Words {
${words.map(([key, value]) => `        static let ${camel(key)} = ${swift(value)}`).join('\n')}
    }
}
`;

 const kotlinTool = t => `        ToolkitToolSpec(${kotlin(t.id)}, ${kotlin(t.name)}, ${kotlin(t.short)}, ${kotlin(t.capability)}, ${kotlin(t.summary)}, `
  + `${kotlin(t.honesty.capability)}, ${t.honesty.drawnBy === 'toolkit'}, ${!!t.decision}, ${!!t.signsAfterCall}, ${!!t.pending}, `
  + `listOf(${(t.onCall ?? []).map(g => `ToolkitCallGate(${kotlin(g.limit)}, ${kotlin(g.refusal)})`).join(', ')}), `
  + `${kotlin(typeOf(t.screens.android))})`;
 const kotlinSurface = s => `        ToolkitSurfaceSpec(${kotlin(s.id)}, ${kotlin(s.role)}, ${kotlin(s.home.id)}, ${kotlin(s.home.name)}, ${kotlin(s.home.short)}, `
  + `${kotlin(s.heading)}, ${kotlin(s.from ?? null)}, listOf(${s.tools.map(kotlin).join(', ')}), `
  + `listOf(${(s.refused ?? []).map(r => `ToolkitRefusedSpec(${kotlin(r.tool)}, ${kotlin(r.sentence)})`).join(', ')}))`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object ConsultationToolkitData {
    val tools = listOf(
${contract.tools.map(kotlinTool).join(',\n')}
    )
    val surfaces = listOf(
${contract.surfaces.map(kotlinSurface).join(',\n')}
    )
    /** What the toolkit itself will not do. A refusal with no surfaces is said on every one. */
    val refusals = listOf(
${contract.refusals.map(r => `        ToolkitRefusalSpec(${kotlin(r.id)}, ${kotlin(r.sentence)}, listOf(${(r.surfaces ?? []).map(kotlin).join(', ')}))`).join(',\n')}
    )

    object Gates {
${gates.map(([key, value]) => `        const val ${camel(key)} = ${kotlin(value)}`).join('\n')}
    }
    object Words {
${words.map(([key, value]) => `        const val ${camel(key)} = ${kotlin(value)}`).join('\n')}
    }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ConsultationToolkitData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ConsultationToolkitData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitConsultationToolkit()) {
  writeFileSync(file.path, file.content);
  console.log(`consultation-toolkit → ${file.path}`);
 }
}
