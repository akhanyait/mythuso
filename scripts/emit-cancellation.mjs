/* Cancelling a visit, and moving one, written out for two native apps by a machine.

   This contract exists because the two hours were typed. Both native apps promised on the booking
   confirmation that a visit may be cancelled or rescheduled up to two hours before it, in a string
   literal written once into Swift and once into Kotlin, with nothing declaring the rule and so
   nothing for the drift check to compare against. The window is generated below and the literal is
   refused in hand-written source, which is the only arrangement in which the promise on the screen
   and the rule in the contract cannot come apart.

   What is generated is the window, the three states, the four reasons, the three things cancelling
   does not undo, and the reschedule offer. What is deliberately not generated is money. The
   contract carries a `pendingDecision` naming who must decide what a late cancellation costs, and
   emitting a placeholder — a zero, an empty string, a `charge` field waiting to be filled — is how
   a percentage nobody agreed to arrives later looking like it was always there. The two apps read
   the payments capability for what to say about money instead, the same way every other screen
   does.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. The sentences here carry curly quotes, em-dashes and a section symbol,
   all of which are plain UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/cancellation.json';

const swift = value => `"${value.replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-cancellation.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run cancellation`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'No charge appears below, and none is coming from here. What a late cancellation costs is an',
 'open decision recorded in the contract as pendingDecision; a field waiting to be filled is how',
 'a number nobody agreed to arrives later looking like it was always intended.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitCancellation(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const { window: win, always, states, reasons, money, doesNotUndo, reschedule } = contract;

 const swiftFile = `${banner()}

import Foundation

extension Cancellation {
    static let hoursBefore = ${win.hoursBefore}
    static let windowSentence = ${swift(win.sentence)}
    static let shownAt = ${swift(win.shownAt)}
    static let alwaysStatement = ${swift(always.statement)}
    static let alwaysWhy = ${swift(always.why)}
    static let reasonsNote = ${swift(contract.reasonsNote)}

    static let states: [CancellationState] = [
${states.map(s => `        .init(id: ${swift(s.id)}, name: ${swift(s.name)}, detail: ${swift(s.detail)},
              patientWords: ${swift(s.patientWords)}, refusesCancellation: ${s.refusesCancellation === true})`).join(',\n')}
    ]

    static let reasons: [CancellationReason] = [
${reasons.map(r => `        .init(id: ${swift(r.id)}, text: ${swift(r.text)}, offersRescheduleFirst: ${r.offersRescheduleFirst === true})`).join(',\n')}
    ]

    static let doesNotUndo: [CancellationLimit] = [
${doesNotUndo.map(d => `        .init(id: ${swift(d.id)}, statement: ${swift(d.statement)}, why: ${swift(d.why)})`).join(',\n')}
    ]

    enum Reschedule {
        static let offeredBeforeCancelling = ${reschedule.offeredBeforeCancelling}
        static let sentence = ${swift(reschedule.sentence)}
        static let keepsTheSameVisit = ${swift(reschedule.keepsTheSameVisit)}
    }

    /* What is said about money while payments are not connected. The refund sentence itself is not
       here — it comes from the payments capability, so one notice answers everywhere. */
    enum Money {
        static let capability = ${swift(money.capability)}
        static let whileNotConnected = ${swift(money.whileNotConnected)}
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object CancellationData {
    const val hoursBefore = ${win.hoursBefore}
    const val windowSentence = ${kotlin(win.sentence)}
    const val shownAt = ${kotlin(win.shownAt)}
    const val alwaysStatement = ${kotlin(always.statement)}
    const val alwaysWhy = ${kotlin(always.why)}
    const val reasonsNote = ${kotlin(contract.reasonsNote)}

    val states = listOf(
${states.map(s => `        CancellationState(${kotlin(s.id)}, ${kotlin(s.name)}, ${kotlin(s.detail)}, ${kotlin(s.patientWords)}, ${s.refusesCancellation === true})`).join(',\n')}
    )

    val reasons = listOf(
${reasons.map(r => `        CancellationReason(${kotlin(r.id)}, ${kotlin(r.text)}, ${r.offersRescheduleFirst === true})`).join(',\n')}
    )

    val doesNotUndo = listOf(
${doesNotUndo.map(d => `        CancellationLimit(${kotlin(d.id)}, ${kotlin(d.statement)}, ${kotlin(d.why)})`).join(',\n')}
    )

    const val rescheduleOfferedBeforeCancelling = ${reschedule.offeredBeforeCancelling}
    const val rescheduleSentence = ${kotlin(reschedule.sentence)}
    const val rescheduleKeepsTheSameVisit = ${kotlin(reschedule.keepsTheSameVisit)}

    // The refund sentence is not here; it comes from the payments capability so one notice answers
    // everywhere.
    const val moneyCapability = ${kotlin(money.capability)}
    const val moneyWhileNotConnected = ${kotlin(money.whileNotConnected)}
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/CancellationData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/CancellationData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitCancellation()) {
  writeFileSync(file.path, file.content);
  console.log(`cancellation → ${file.path}`);
 }
}
