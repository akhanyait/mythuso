/* The open-source register, written out for people rather than for a platform.

   packages/catalog/open-source.json records every open-source module, standard, open-weights model
   and commercial speech provider that ThusoIQ Master v3.5 names, what the specification decided for
   each, what it would plug into here, and what stands in its way. This writes it as
   docs/OPEN-SOURCE.md for the founder and for a Head of Engineering who has not been hired yet.

   It is generated rather than written because the register's one dangerous sentence is "adopted".
   A hand-kept markdown table is the document somebody updates the afternoon a pilot goes well, and
   it would then say one thing while the contract, the status page and the checks said another. There
   is nothing to update here: the adopted count is counted, and the sentence saying nothing is adopted
   is printed only while the count is nought.

   No native copy is emitted. The apps draw no screen from this register, and a Swift table of
   licences nobody renders is a second copy with no reader. If a screen ever needs it, the emitter
   grows a Swift and a Kotlin file like every other one. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/open-source.json';
const TARGET = 'docs/OPEN-SOURCE.md';

/* A table cell cannot hold a pipe or a line break. Neither is in the contract today; a licence
   expression like "MIT OR Apache-2.0" will not need it, but a sentence one day might. */
const cell = value => String(value ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const link = (text, url) => (url ? `[${cell(text)}](${url})` : cell(text));

export function emitOpenSource(root = '') {
 const register = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const components = register.components;
 const adopted = components.filter(c => c.adoption.status === 'adopted');
 const refused = components.filter(c => c.kind === 'refused');
 const unverified = components.filter(c => c.source.unverified === true);
 const rule = id => register.rules.find(r => r.id === id);

 const licenceOf = c => {
  if (c.kind === 'refused') return 'Not recorded — declined';
  if (c.source.licence) return c.source.licenceUrl ? link(c.source.licence, c.source.licenceUrl) : cell(c.source.licence);
  if (c.source.licenceTerms) return cell(c.source.licenceTerms);
  return 'Not verified';
 };
 const whereFrom = c => c.source.repository ? link(c.source.repository.replace('https://', ''), c.source.repository) : c.source.url ? link(c.source.url.replace('https://', ''), c.source.url) : '—';
 const linksOf = c => {
  if (!c.links.length) return cell(c.unlinkedBecause ?? '—');
  return c.links.map(l => {
   const parts = [`**${l.engine}**`];
   if (l.apiRoutes.length) parts.push(l.apiRoutes.map(r => `\`${r}\``).join(', '));
   if (l.doors.length) parts.push('doors ' + l.doors.map(d => `\`${d}\``).join(', '));
   if (l.through?.length) parts.push('through ' + l.through.map(g => `\`${g}\``).join(', '));
   if (l.noSeamBecause) parts.push(cell(l.noSeamBecause));
   return parts.join(' · ');
  }).join('<br>');
 };
 const adoptionOf = c => {
  const status = c.adoption.status === 'adopted' ? '**Adopted**' : 'Not adopted';
  return [status, ...c.adoption.blockedBy.map(b => `— ${cell(b)}`)].join('<br>');
 };
 const maintained = c => c.source.maintenance?.lastSeen ? link(c.source.maintenance.lastSeen, c.source.maintenance.evidenceUrl) : 'Not verified';

 const out = [];
 out.push(`<!-- Generated by scripts/emit-open-source.mjs from ${SOURCE}. Do not edit by hand — run \`npm run open-source\`. The build fails if this file and its source disagree. -->`);
 out.push('');
 out.push('# The open-source register');
 out.push('');
 out.push(`Every open-source module, standard, open-weights model and speech provider that ${register.specification.document} names in ${register.specification.sections.join(', ')}, with the decision the specification made for it, the engine, routes and doors in this repository it would plug into, and what stands in its way. Sources were checked on ${register.verifiedOn}.`);
 out.push('');
 /* Derived, never typed. It is printed for as long as it is true and no longer. */
 if (adopted.length === 0) {
  out.push(`**Nothing in this register is adopted.** ${components.length} components are recorded and not one of them is part of MyThuso: no code from any of them is in this repository, no dependency on any of them is declared, and no service calls one. ${rule('open-source-is-not-production-approved').statement}`);
 } else {
  out.push(`**${adopted.length} of ${components.length} components are adopted:** ${adopted.map(c => c.name).join(', ')}.`);
 }
 out.push('');
 out.push(`${rule('open-source-is-not-production-approved').why}`);
 out.push('');

 out.push('## What MyThuso owns, and no module replaces');
 out.push('');
 out.push('| Component | Owner | What it is | Why it is not a module |');
 out.push('|---|---|---|---|');
 for (const o of register.owned) out.push(`| **${cell(o.name)}** | ${cell(o.owner)} | ${cell(o.what)} | ${cell(o.refusal.statement)} ${cell(o.refusal.why)} |`);
 out.push('');

 out.push('## Procurement rules (§15D)');
 out.push('');
 for (const r of register.procurementRules) out.push(`- **${cell(r.statement)}** ${r.why}`);
 out.push('');

 for (const decision of register.decisions) {
  const group = components.filter(c => c.specDecision === decision.id);
  if (!group.length) continue;
  out.push(`## ${decision.id}`);
  out.push('');
  out.push(decision.meaning);
  out.push('');
  if (decision.id === 'DECLINED') {
   out.push('| Name | Section | Why it is declined | What is done instead |');
   out.push('|---|---|---|---|');
   for (const c of group) out.push(`| **${cell(c.name)}** | ${cell(c.specSection)} | ${cell(c.refusals[0].why)} | ${cell(c.provides)} |`);
   out.push('');
   continue;
  }
  out.push('| Name | Kind | Licence | Source | Last activity seen | Links to | Adoption and what blocks it |');
  out.push('|---|---|---|---|---|---|---|');
  for (const c of group) out.push(`| **${cell(c.name)}**<br>${cell(c.provides)} | ${cell(c.kind)} | ${licenceOf(c)} | ${whereFrom(c)} | ${maintained(c)} | ${linksOf(c)} | ${adoptionOf(c)} |`);
  out.push('');
 }

 out.push('## Doors the links need that do not exist yet');
 out.push('');
 out.push(`${rule('a-proposed-door-is-not-a-door').statement} ${rule('a-proposed-door-is-not-a-door').why}`);
 out.push('');
 for (const d of register.proposedDoors) {
  out.push(`### \`${d.id}\``);
  out.push('');
  out.push(`${d.why} Needed by: ${components.filter(c => c.links.some(l => l.doors.includes(`proposed:${d.id}`))).map(c => c.name).join(', ')}.`);
  out.push('');
  for (const b of d.beforeSwitchOn) out.push(`- **${cell(b.must)}** ${b.why}`);
  out.push('');
 }

 out.push('## What each component refuses');
 out.push('');
 for (const c of components) {
  if (!c.refusals.length) continue;
  out.push(`- **${cell(c.name)}**`);
  for (const r of c.refusals) out.push(`  - ${r.statement} *${r.why}*`);
 }
 out.push('');

 out.push('## What could not be verified');
 out.push('');
 if (!unverified.length) out.push('Everything above was verified against its primary source.');
 for (const c of unverified) out.push(`- **${cell(c.name)}** — ${c.source.unverifiedReason}`);
 out.push('');

 out.push('## The register\'s own rules');
 out.push('');
 for (const r of register.rules) out.push(`- **${cell(r.statement)}** ${r.why}`);
 out.push('');
 out.push(`Held by the "open-source register" section of \`scripts/check-boundaries.mjs\`. Refused vendors: ${refused.map(c => c.name).join('; ')}.`);
 out.push('');

 return [{ path: TARGET, content: out.join('\n') }];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitOpenSource()) {
  writeFileSync(file.path, file.content);
  console.log(`open-source → ${file.path}`);
 }
}
