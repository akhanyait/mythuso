/* Employer and sponsor programme administration, written out for two native apps, by a machine.

   The suppression floor, what an employer sees and never sees, how somebody joins and leaves, what
   a sponsor is shown, the seven rules, the six refusals, two fictional programmes and one sponsor's
   statement live in packages/catalog/programmes.json. The web reads that file. iOS and Android
   cannot, and should not, for the reason the vetting generator gives.

   Two things here are the point of the generator rather than incidental to it.

   No suppressed figure is written out. Every cohort in the source carries its real counts, and each
   platform applies the floor itself — below twelve people, above four fifths dominance, and the
   secondary rule that hides a second group when only one would otherwise be hidden. Emitting the
   suppressed table instead would mean the rule lived in this file and the apps merely drew what
   they were given, which is precisely the arrangement in which somebody eventually asks for the
   unsuppressed version "just for the board pack" and gets it.

   No amount is written out either. A sponsor's statement line names a service, and what it cost is
   that service's price in packages/catalog/services.json — the same row the recipient would have
   been quoted from if she were paying herself, because a sponsored visit is not a different visit.
   The web resolves it at runtime; native gets it resolved here, and the boundary check compares.

   Escaping, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and a
       lone $ starts a string template. The sentences mention money.
   Curly quotes and en-dashes are simply UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/programmes.json';
const CATALOGUE = 'packages/catalog/services.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-programmes.mjs from ${SOURCE} and ${CATALOGUE}.`,
 'Do not edit by hand — run `npm run programmes`. The build fails if this file and the two sources',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Every cohort below carries its real counts, unsuppressed. The floor — twelve people, four fifths',
 'dominance, and the secondary rule that hides a second group when only one would otherwise be',
 'hidden — is applied in Programmes.swift and Programmes.kt beside this file, from the same numbers',
 'the web applies it from. A pre-suppressed table here would mean the rule lived in a generator and',
 'the apps drew whatever they were handed.',
 '',
 'Each statement line names a service; what it cost is that service\'s price in the catalogue,',
 'resolved when this file was written. It is not a number anybody typed.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitProgrammes(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const catalogue = JSON.parse(readFileSync(root + CATALOGUE, 'utf8'));
 const priced = line => {
  const service = catalogue.find(s => s.id === line.service);
  if (!service) throw new Error(`A sponsor statement line names a service that is not in the catalogue: ${line.service}`);
  return { ...line, amount: service.price, serviceName: service.name };
 };
 const lines = contract.statement.lines.map(priced);
 const { floor, employer, sponsor, statement } = contract;

 const pairs = (list, keyA, keyB) => list.map(entry => [entry[keyA], entry[keyB]]);
 const swiftPairs = (list, keyA, keyB, type) => pairs(list, keyA, keyB)
  .map(([a, b]) => `        ${type}(${swift(a)}, ${swift(b)})`).join(',\n');
 const kotlinPairs = (list, keyA, keyB, type) => pairs(list, keyA, keyB)
  .map(([a, b]) => `    ${type}(${kotlin(a)}, ${kotlin(b)})`).join(',\n');

 const swiftFile = `${banner()}

import Foundation

extension Programmes {
    /* A judgement, not a standard. Nothing in POPIA names a number; this one is written down so it
       can be argued with, which is the opposite of a threshold buried in a query. */
    static let floor = SuppressionFloor(
        minimumCohort: ${floor.minimumCohort}, dominanceCeiling: ${floor.dominanceCeiling}, roundTo: ${floor.roundTo},
        minimumSuppressed: ${floor.minimumSuppressed},
        whyTwelve: ${swift(floor.whyTwelve)},
        whyDominance: ${swift(floor.whyDominance)},
        whyRounding: ${swift(floor.whyRounding)},
        whySecondary: ${swift(floor.whySecondary)})
    static let employerSees: [Disclosure] = [
${swiftPairs(employer.sees, 'what', 'why', '.init')}
    ]
    static let employerNeverSees: [Disclosure] = [
${swiftPairs(employer.neverSees, 'what', 'why', '.init')}
    ]
    static let declining = Declining(headline: ${swift(employer.declining.headline)},
                                     detail: ${swift(employer.declining.detail)},
                                     note: ${swift(employer.declining.note)})
    static let enrolment: [ProgrammeStep] = [
${swiftPairs(employer.enrolment, 'step', 'detail', '.init')}
    ]
    static let leaving: [ProgrammeStep] = [
${swiftPairs(employer.leaving, 'what', 'detail', '.init')}
    ]
    static let sponsorSees: [Disclosure] = [
${swiftPairs(sponsor.sees, 'what', 'why', '.init')}
    ]
    static let sponsorNeverSees: [Disclosure] = [
${swiftPairs(sponsor.neverSees, 'what', 'why', '.init')}
    ]
    static let lineDetailChoices: [LineDetailChoice] = [
${sponsor.lineDetail.map(c => `        .init(id: ${swift(c.id)}, name: ${swift(c.name)}, detail: ${swift(c.detail)}, isDefault: ${c.isDefault})`).join(',\n')}
    ]
    static let sponsorConsent = SponsorConsent(headline: ${swift(sponsor.consent.headline)},
                                               detail: ${swift(sponsor.consent.detail)},
                                               withdrawal: ${swift(sponsor.consent.withdrawal)})
    /* Rendered word for word. A rule paraphrased on one platform is a different promise on that
       platform, which is the whole reason these live in one file. */
    static let rules: [ProgrammeRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let refusals: [ProgrammeRefusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let suppressionReasons: [SuppressionReason] = [
${contract.suppressionReasons.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    /* Unsuppressed. The floor is applied in Programmes.swift, not here. */
    static let programmes: [Programme] = [
${contract.programmes.map(p => `        .init(id: ${swift(p.id)}, name: ${swift(p.name)}, employer: ${swift(p.employer)}, startedInDays: ${p.startedInDays},
              note: ${swift(p.note)},
              cohorts: [
${p.cohorts.map(c => `                  .init(id: ${swift(c.id)}, name: ${swift(c.name)}, eligible: ${c.eligible}, tookPart: ${c.tookPart}, advisedToSeeADoctor: ${c.advisedToSeeADoctor})`).join(',\n')}
              ])`).join(',\n')}
    ]
    static let statement = SponsorStatement(
        sponsor: ${swift(statement.sponsor)}, recipient: ${swift(statement.recipient)},
        relationship: ${swift(statement.relationship)}, setAside: ${statement.setAside},
        note: ${swift(statement.note)},
        lines: [
${lines.map(l => `            .init(onDays: ${l.onDays}, amount: ${l.amount}, service: ${swift(l.serviceName)})`).join(',\n')}
        ])
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

/* A judgement, not a standard. Nothing in POPIA names a number; this one is written down so it can
   be argued with, which is the opposite of a threshold buried in a query. */
val suppressionFloor = SuppressionFloor(
    ${floor.minimumCohort}, ${floor.dominanceCeiling}, ${floor.roundTo}, ${floor.minimumSuppressed},
    ${kotlin(floor.whyTwelve)},
    ${kotlin(floor.whyDominance)},
    ${kotlin(floor.whyRounding)},
    ${kotlin(floor.whySecondary)}
)

val employerSees = listOf(
${kotlinPairs(employer.sees, 'what', 'why', 'Disclosure')}
)

val employerNeverSees = listOf(
${kotlinPairs(employer.neverSees, 'what', 'why', 'Disclosure')}
)

val programmeDeclining = Declining(
    ${kotlin(employer.declining.headline)},
    ${kotlin(employer.declining.detail)},
    ${kotlin(employer.declining.note)}
)

val programmeEnrolment = listOf(
${kotlinPairs(employer.enrolment, 'step', 'detail', 'ProgrammeStep')}
)

val programmeLeaving = listOf(
${kotlinPairs(employer.leaving, 'what', 'detail', 'ProgrammeStep')}
)

val sponsorSees = listOf(
${kotlinPairs(sponsor.sees, 'what', 'why', 'Disclosure')}
)

val sponsorNeverSees = listOf(
${kotlinPairs(sponsor.neverSees, 'what', 'why', 'Disclosure')}
)

val lineDetailChoices = listOf(
${sponsor.lineDetail.map(c => `    LineDetailChoice(${kotlin(c.id)}, ${kotlin(c.name)}, ${kotlin(c.detail)}, ${c.isDefault})`).join(',\n')}
)

val sponsorConsent = SponsorConsent(
    ${kotlin(sponsor.consent.headline)},
    ${kotlin(sponsor.consent.detail)},
    ${kotlin(sponsor.consent.withdrawal)}
)

/* Rendered word for word. A rule paraphrased on one platform is a different promise on that
   platform, which is the whole reason these live in one file. */
val programmeRules = listOf(
${contract.rules.map(r => `    ProgrammeRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val programmeRefusals = listOf(
${contract.refusals.map(r => `    ProgrammeRefusal(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val suppressionReasons = listOf(
${contract.suppressionReasons.map(r => `    SuppressionReason(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
)

/* Unsuppressed. The floor is applied in Programmes.kt, not here. */
val programmes = listOf(
${contract.programmes.map(p => `    Programme(
        ${kotlin(p.id)}, ${kotlin(p.name)}, ${kotlin(p.employer)}, ${p.startedInDays},
        ${kotlin(p.note)},
        listOf(
${p.cohorts.map(c => `            Cohort(${kotlin(c.id)}, ${kotlin(c.name)}, ${c.eligible}, ${c.tookPart}, ${c.advisedToSeeADoctor})`).join(',\n')}
        )
    )`).join(',\n')}
)

val sponsorStatement = SponsorStatement(
    ${kotlin(statement.sponsor)}, ${kotlin(statement.recipient)}, ${kotlin(statement.relationship)},
    ${statement.setAside},
    ${kotlin(statement.note)},
    listOf(
${lines.map(l => `        StatementLine(${l.onDays}, ${l.amount}, ${kotlin(l.serviceName)})`).join(',\n')}
    )
)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ProgrammesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ProgrammesData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitProgrammes()) {
  writeFileSync(file.path, file.content);
  console.log(`programmes → ${file.path}`);
 }
}
