/* The live vitals board, written out for two native apps by a machine.
 *
 * packages/catalog/live-vitals.json holds the streams, the pace, the jitter's constants, the board's words and
 * the refusals it draws where the Lovable export drew a score, a triage colour, an interpretation, alarms and a
 * heatmap. Each stream's label, unit, reference range and step are packages/catalog/records.json's and its
 * instrument's name packages/catalog/capture.json's, joined by packages/engines/src/devices/live-vitals.ts —
 * imported here, so the join a phone is given is the join the web draws, not a second one. The presets'
 * baselines are packages/catalog/devices/simulator-presets.json's; the simulated class, the simulated mark and
 * the stale sentence are packages/catalog/devices.json's; the devices notice is packages/catalog/capabilities.json's.
 *
 * WHY THE PRESETS TRAVEL. The simulator engine is TypeScript and a phone cannot run it, so each app works the
 * readings out itself — LiveVitals.swift and LiveVitals.kt, the same pure function of scenario, patient, stream
 * and reading number — from the baselines written here. The arithmetic is three integer steps whose products
 * stay below 2^53, so a JavaScript number, a Swift Int and a Kotlin Long agree.
 *
 * WHAT IS NOT EMITTED. A reference range: each stream names its measure, and the phone reads the label, unit, range
 * and step from the generated records data (Records.observations, observationRanges), where scripts/check-boundaries.mjs
 * allows a range to be written. Nor any severity, band or colour: the board says inside, below or above the record's range,
 * and nothing about what that means.
 *
 * Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $, because a lone $ starts a
 * template.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';
import * as engine from '../packages/engines/src/devices/live-vitals.ts';

const SOURCE = 'packages/catalog/live-vitals.json';
const PRESETS = 'packages/catalog/devices/simulator-presets.json';
const DEVICES = 'packages/catalog/devices.json';
const CAPABILITIES = 'packages/catalog/capabilities.json';

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const num = n => (Number.isInteger(n) ? `${n}.0` : String(n));
const camel = key => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/* The stale interval in the words lib/devices.ts intervalText gives the web: whole days, whole hours, or minutes. */
const intervalText = minutes => {
 if (minutes % (24 * 60) === 0) { const d = minutes / (24 * 60); return `${d} ${d === 1 ? 'day' : 'days'}`; }
 if (minutes % 60 === 0) { const h = minutes / 60; return `${h} ${h === 1 ? 'hour' : 'hours'}`; }
 return `${minutes} minutes`;
};

const banner = () => [
 `Generated by scripts/emit-live-vitals.mjs from ${SOURCE}, ${PRESETS}, packages/catalog/records.json,`,
 `packages/catalog/capture.json, ${DEVICES} and ${CAPABILITIES}.`,
 'Do not edit by hand — run `npm run live-vitals`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'Every reading the board shows is simulated and carries no clinical weight. The board says where a value',
 'stands against the record\'s indicative range, in words, and draws no score, priority or severity: no',
 'triage protocol is ratified. Nothing here contacts an instrument, a phone\'s health store or a watch.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitLiveVitals(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const presets = JSON.parse(readFileSync(root + PRESETS, 'utf8')).presets;
 const devices = JSON.parse(readFileSync(root + DEVICES, 'utf8'));
 const capabilities = JSON.parse(readFileSync(root + CAPABILITIES, 'utf8'));

 const cap = capabilities.capabilities.find(c => c.id === 'devices');
 if (!cap) throw new Error(`${CAPABILITIES} has no "devices" capability, whose notice stands over the board.`);
 const notice = cap.connected ? '' : cap.state === 'simulated' && cap.simulation?.notice ? cap.simulation.notice : cap.notice;
 const stale = settingDefault(DEVICES, devices, 'stale-after-minutes').value;
 const staleSentence = devices.screens.nurse.staleSince.replace('{interval}', intervalText(stale));
 const presetTypes = new Set(engine.streams.map(s => s.presetType));
 const words = Object.entries(contract.board).filter(([, v]) => typeof v === 'string');
 const facts = [
  ['simulatedClass', engine.simulatedClass.label], ['simulatedMark', engine.simulatedMark.label], ['simulatedSentence', engine.simulatedMark.sentence],
  ['provenance', engine.deviceProvenance.name], ['rangeNote', engine.rangeNote], ['notice', notice], ['stale', staleSentence]
 ];
 const { pace, jitter } = contract;

 const swiftFile = `${banner()}

import Foundation

extension LiveVitals {
    static let tickMs = ${pace.tickMs}
    static let ticksPerStep = ${pace.ticksPerStep}
    static let history = ${pace.history}
    static let defaultPreset = ${swift(pace.defaultPreset)}
    static let modulus = ${jitter.modulus}
    static let multiplier = ${jitter.multiplier}
    static let tickStride = ${jitter.tickStride}
    static let streamStride = ${jitter.streamStride}

    /// One measure from one instrument. Its label, unit, range and step are read from Records.observations, never written here.
    static let streams: [LiveStreamSpec] = [
${engine.streams.map(s => `        .init(id: ${swift(s.id)}, measure: ${swift(s.measure)}, instrument: ${swift(s.instrument)}, presetType: ${swift(s.presetType)}, jitter: ${num(s.jitter)}, ceiling: ${s.ceiling === null ? 'nil' : num(s.ceiling)})`).join(',\n')}
    ]
    /// The simulator's scenarios, with only the readings a stream reads.
    static let presets: [LivePresetSpec] = [
${presets.map(p => `        .init(id: ${swift(p.id)}, name: ${swift(p.name)}, readings: [${p.readings.filter(r => presetTypes.has(r.type)).map(r => `.init(type: ${swift(r.type)}, value: ${num(r.value)}, offsetMs: ${r.timestamp_offset_ms})`).join(', ')}])`).join(',\n')}
    ]
    static let refusals: [LiveRefusalSpec] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, heading: ${swift(r.heading)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    /// What cannot be streamed, worked out from the record and the instrument list.
    static let notStreamed: [String] = [
${engine.notStreamed.map(line => `        ${swift(line)}`).join(',\n')}
    ]

    enum Words {
${[...words, ...facts].map(([key, value]) => `        static let ${camel(key)} = ${swift(value)}`).join('\n')}
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object LiveVitalsData {
    const val tickMs = ${pace.tickMs}L
    const val ticksPerStep = ${pace.ticksPerStep}
    const val history = ${pace.history}
    const val defaultPreset = ${kotlin(pace.defaultPreset)}
    const val modulus = ${jitter.modulus}L
    const val multiplier = ${jitter.multiplier}L
    const val tickStride = ${jitter.tickStride}L
    const val streamStride = ${jitter.streamStride}L

    /** One measure from one instrument. Its label, unit, range and step are read from observationRanges, never written here. */
    val streams = listOf(
${engine.streams.map(s => `        LiveStreamSpec(${kotlin(s.id)}, ${kotlin(s.measure)}, ${kotlin(s.instrument)}, ${kotlin(s.presetType)}, ${num(s.jitter)}, ${s.ceiling === null ? 'null' : num(s.ceiling)})`).join(',\n')}
    )
    /** The simulator's scenarios, with only the readings a stream reads. */
    val presets = listOf(
${presets.map(p => `        LivePresetSpec(${kotlin(p.id)}, ${kotlin(p.name)}, listOf(${p.readings.filter(r => presetTypes.has(r.type)).map(r => `LivePresetReading(${kotlin(r.type)}, ${num(r.value)}, ${r.timestamp_offset_ms}L)`).join(', ')}))`).join(',\n')}
    )
    val refusals = listOf(
${contract.refusals.map(r => `        LiveRefusalSpec(${kotlin(r.id)}, ${kotlin(r.heading)}, ${kotlin(r.sentence)})`).join(',\n')}
    )
    /** What cannot be streamed, worked out from the record and the instrument list. */
    val notStreamed = listOf(
${engine.notStreamed.map(line => `        ${kotlin(line)}`).join(',\n')}
    )

    object Words {
${[...words, ...facts].map(([key, value]) => `        const val ${camel(key)} = ${kotlin(value)}`).join('\n')}
    }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/LiveVitalsData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/LiveVitalsData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitLiveVitals()) {
  writeFileSync(file.path, file.content);
  console.log(`live-vitals → ${file.path}`);
 }
}
