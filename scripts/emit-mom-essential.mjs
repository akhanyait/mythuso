/* MyThuso for Mom Essential's journey, written out for two native apps, by a machine.

   A son or daughter asks for the plan for a parent, the parent agrees in her own account and chooses what they see,
   and the first month is paid. What a phone needs to draw that honestly is packages/catalog/mom-essential.json's —
   the states and the words each person reads, what is shared and for how long, the medicine sentence, the guardian
   sentence and what is not built — and the refusal a sponsor gets for agreeing, from
   packages/catalog/apis/money.json. The longest a parent's summary grant may run is the caregiver role's ceiling in
   packages/catalog/consent.json, never past the founder's maximum, worked out here rather than typed. What a statement
   line may say is programmes.json's, already generated into ProgrammesData; the tier's name, price and inclusions are
   PlansData's. The web reads all of it through apps/web/src/lib/mom-essential.ts; iOS and Android cannot read JSON at
   runtime, so the copy is generated and scripts/check-boundaries.mjs compares it on every build.

   WHAT IS NOT WRITTEN. No simulated provider: neither app runs one, so a phone's pay step says what did not happen, in
   packages/catalog/money.json's providerless sentence, and a plan on a phone never starts. No vouchers and no USSD menu:
   neither is drawn on a phone in this wave (packages/catalog/vouchers.json and ussd.json say why).

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/mom-essential.json';
const API = 'packages/catalog/apis/money.json';
const CONSENT = 'packages/catalog/consent.json';
const MONEY = 'packages/catalog/money.json';
const ACCEPT = 'POST /v1/money/plan-subscriptions/{subscriptionRef}/accept@1';

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const routeKey = r => `${r.method} ${r.path}@${r.version}`;

const banner = () => [
 `Generated by scripts/emit-mom-essential.mjs from ${SOURCE}, ${API}, ${CONSENT} and ${MONEY}.`,
 'Do not edit by hand — run `npm run mom-essential`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'This app runs no simulated provider, so its pay step says nothing was charged and a plan never starts here.',
 'Nothing in this file is a real service.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitMomEssential(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const consent = JSON.parse(readFileSync(root + CONSENT, 'utf8'));
 const money = JSON.parse(readFileSync(root + MONEY, 'utf8'));

 const accept = api.routes.find(r => routeKey(r) === ACCEPT && !r.withdrawn);
 if (!accept) throw new Error(`${API} has no live ${ACCEPT}, whose refusal a sponsor reads.`);
 const onlyTheParent = accept.refusals.find(r => r.id === contract.agreement.refusal);
 if (!onlyTheParent) throw new Error(`${ACCEPT} no longer refuses "${contract.agreement.refusal}".`);
 const role = consent.grants.recipientRoles.find(r => r.id === contract.sharing.summaries.recipientRole);
 if (!role) throw new Error(`${CONSENT} has no recipient role "${contract.sharing.summaries.recipientRole}".`);
 const summaryDays = Math.min(role.maxExpiryDays, consent.grants.maximumExpiryDays);
 const visit = contract.included.find(i => i.heardOn === 'appointment.booked@2');
 if (!visit?.perPeriod || !visit.serviceId) throw new Error(`${SOURCE} no longer says which visit a month includes, and how many.`);
 const s = contract.screen;

 const swiftFile = `${banner()}

import Foundation

enum MomEssentialData {
    static let planCode = ${swift(contract.planCode)}
    static let includedServiceId = ${swift(visit.serviceId)}
    static let includedVisitsPerMonth = ${visit.perPeriod}
    /// The caregiver role's ceiling in consent.json, never past the founder's maximum.
    static let summaryDays = ${summaryDays}

    /// What a sponsor is shown of a parent's plan. What a sponsor never sees is ProgrammesData's.
    static let sponsorSees: [String] = [
${contract.sharing.sponsorSees.map(s => `        ${swift(s.what)}`).join(',\n')}
    ]

    static let states: [MomEssentialState] = [
${contract.states.map(st => `        .init(id: ${swift(st.id)}, name: ${swift(st.name)}, sponsorWords: ${swift(st.sponsorWords)}, parentWords: ${swift(st.parentWords)})`).join(',\n')}
    ]

    enum Words {
        static let open = ${swift(s.open)}
        static let previewNote = ${swift(s.previewNote)}
        static let actingSponsor = ${swift(s.actingSponsor)}
        static let actingParent = ${swift(s.actingParent)}
        static let seesHeading = ${swift(s.seesHeading)}
        static let neverSeesHeading = ${swift(s.neverSeesHeading)}
        static let sponsorHeading = ${swift(s.sponsor.heading)}
        static let who = ${swift(s.sponsor.who)}
        static let ask = ${swift(s.sponsor.ask)}
        static let asked = ${swift(s.sponsor.asked)}
        static let openAsParent = ${swift(s.sponsor.openAsParent)}
        static let pay = ${swift(s.sponsor.pay)}
        static let payWith = ${swift(s.sponsor.payWith)}
        static let view = ${swift(s.sponsor.view)}
        static let lines = ${swift(s.sponsor.lines)}
        static let careGiven = ${swift(s.sponsor.careGiven)}
        static let noLines = ${swift(s.sponsor.noLines)}
        static let parentHeading = ${swift(s.parent.heading)}
        static let lineDetailLegend = ${swift(s.parent.lineDetailLegend)}
        static let agree = ${swift(s.parent.agree)}
        static let backToSponsor = ${swift(s.parent.backToSponsor)}
        static let medicineHeading = ${swift(s.parent.medicine)}
        static let summariesLabel = ${swift(contract.sharing.summaries.label)}
        static let summariesDetail = ${swift(contract.sharing.summaries.detail)}
        static let summariesNone = ${swift(contract.sharing.summaries.none)}
        static let summariesShared = ${swift(contract.sharing.summaries.shared)}
        static let medicine = ${swift(contract.medicine.sentence)}
        static let delegate = ${swift(contract.medicine.delegate)}
        static let guardian = ${swift(contract.agreement.guardian.sentence)}
        static let notBuilt = ${swift(contract.notBuilt)}
        /// ${ACCEPT}, refusal ${onlyTheParent.id}.
        static let onlyTheParentAgrees = ${swift(onlyTheParent.statement)}
        /// packages/catalog/money.json providerless: what a phone says instead of a receipt.
        static let nothingCharged = ${swift(money.providerless.words)}
    }
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object MomEssentialData {
    const val planCode = ${kotlin(contract.planCode)}
    const val includedServiceId = ${kotlin(visit.serviceId)}
    const val includedVisitsPerMonth = ${visit.perPeriod}
    /** The caregiver role's ceiling in consent.json, never past the founder's maximum. */
    const val summaryDays = ${summaryDays}

    /** What a sponsor is shown of a parent's plan. What a sponsor never sees is ProgrammesData's. */
    val sponsorSees = listOf(
${contract.sharing.sponsorSees.map(s => `        ${kotlin(s.what)}`).join(',\n')}
    )

    val states = listOf(
${contract.states.map(st => `        MomEssentialState(${kotlin(st.id)}, ${kotlin(st.name)}, ${kotlin(st.sponsorWords)}, ${kotlin(st.parentWords)})`).join(',\n')}
    )

    object Words {
        const val open = ${kotlin(s.open)}
        const val previewNote = ${kotlin(s.previewNote)}
        const val actingSponsor = ${kotlin(s.actingSponsor)}
        const val actingParent = ${kotlin(s.actingParent)}
        const val seesHeading = ${kotlin(s.seesHeading)}
        const val neverSeesHeading = ${kotlin(s.neverSeesHeading)}
        const val sponsorHeading = ${kotlin(s.sponsor.heading)}
        const val who = ${kotlin(s.sponsor.who)}
        const val ask = ${kotlin(s.sponsor.ask)}
        const val asked = ${kotlin(s.sponsor.asked)}
        const val openAsParent = ${kotlin(s.sponsor.openAsParent)}
        const val pay = ${kotlin(s.sponsor.pay)}
        const val payWith = ${kotlin(s.sponsor.payWith)}
        const val view = ${kotlin(s.sponsor.view)}
        const val lines = ${kotlin(s.sponsor.lines)}
        const val careGiven = ${kotlin(s.sponsor.careGiven)}
        const val noLines = ${kotlin(s.sponsor.noLines)}
        const val parentHeading = ${kotlin(s.parent.heading)}
        const val lineDetailLegend = ${kotlin(s.parent.lineDetailLegend)}
        const val agree = ${kotlin(s.parent.agree)}
        const val backToSponsor = ${kotlin(s.parent.backToSponsor)}
        const val medicineHeading = ${kotlin(s.parent.medicine)}
        const val summariesLabel = ${kotlin(contract.sharing.summaries.label)}
        const val summariesDetail = ${kotlin(contract.sharing.summaries.detail)}
        const val summariesNone = ${kotlin(contract.sharing.summaries.none)}
        const val summariesShared = ${kotlin(contract.sharing.summaries.shared)}
        const val medicine = ${kotlin(contract.medicine.sentence)}
        const val delegate = ${kotlin(contract.medicine.delegate)}
        const val guardian = ${kotlin(contract.agreement.guardian.sentence)}
        const val notBuilt = ${kotlin(contract.notBuilt)}
        /** ${ACCEPT}, refusal ${onlyTheParent.id}. */
        const val onlyTheParentAgrees = ${kotlin(onlyTheParent.statement)}
        /** packages/catalog/money.json providerless: what a phone says instead of a receipt. */
        const val nothingCharged = ${kotlin(money.providerless.words)}
    }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/MomEssentialData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/MomEssentialData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 if (!existsSync(SOURCE)) throw new Error(`${SOURCE} is missing; run this from the repository root.`);
 for (const file of emitMomEssential()) {
  writeFileSync(file.path, file.content);
  console.log(`mom-essential → ${file.path}`);
 }
}
