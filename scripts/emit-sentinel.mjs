/* Sentinel tiers and safeguarding reports, written out for two native apps by a machine.
 *
 * packages/catalog/sentinel.json holds what each tier means and who is told, why tier four is refused, what a baseline is
 * made of and what suspends it, why nothing is evaluated, and the groups, kinds and sentences of a safeguarding report.
 * packages/catalog/apis/safety.json holds the refusal sentences of the four Sentinel and safeguarding routes, resolved
 * here so the sentence a route answers with and the sentence a phone shows are one string. The window and minimum a
 * baseline is opened under are packages/catalog/field-safety.json's settings, written through scripts/settings-defaults.mjs
 * like every other engine's. iOS and Android cannot read JSON at runtime, so the copy is generated rather than typed and
 * scripts/check-boundaries.mjs compares it on every build.
 *
 * WHAT IS NOT EMITTED. No threshold, rule or reference range, because none exists and none is Sentinel's to hold. No stale
 * interval: a phone reads DevicesData's, so the number lives where Devices keeps it. No tier four: the refusal sentence is
 * here and no rung above three is. And the reason an evaluation is not made is emitted only while no rule is ratified,
 * because a phone cannot read the protocol register; the day one is, this generator refuses and somebody decides what a
 * phone may say.
 *
 * Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $, because a lone $ starts a template.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/sentinel.json';
const API = 'packages/catalog/apis/safety.json';
const SETTINGS = 'packages/catalog/field-safety.json';
const ROUTES = ['POST /v1/safety/sentinel-deviations@2', 'GET /v1/safety/sentinel-baselines@1', 'POST /v1/safety/safeguarding-reports@2', 'GET /v1/safety/safeguarding-reports@1'];

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const camel = key => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const strings = block => Object.entries(block).filter(([key, value]) => typeof value === 'string' && !key.startsWith('_'));

const banner = () => [
 `Generated by scripts/emit-sentinel.mjs from ${SOURCE}, ${API} and ${SETTINGS}.`,
 'Do not edit by hand — run `npm run sentinel`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'Sentinel offers tiers one to three and refuses tier four. Nothing is evaluated, because no baseline rule or',
 'deviation threshold is ratified, and no threshold is written here. A safeguarding report is recorded, held',
 'open and never sent. The baseline window and minimum are PROPOSALS that wait on a clinical review; this app',
 'has no admin surface and uses them as written. Nothing here monitors a patient or reaches anybody.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitSentinel(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const settings = JSON.parse(readFileSync(root + SETTINGS, 'utf8'));

 const windowDays = settingDefault(SETTINGS, settings, 'sentinel-baseline-window-days');
 const minimum = settingDefault(SETTINGS, settings, 'sentinel-baseline-minimum-readings');

 const refusals = new Map();
 for (const key of ROUTES) {
  const route = api.routes.find(r => !r.withdrawn && `${r.method} ${r.path}@${r.version}` === key);
  if (!route) throw new Error(`${API} does not declare ${key}, whose refusals a phone shows.`);
  for (const r of route.refusals) {
   const seen = refusals.get(r.id);
   if (seen && seen.statement !== r.statement) throw new Error(`${API} declares "${r.id}" in two different sentences.`);
   refusals.set(r.id, { id: r.id, status: r.status, statement: r.statement });
  }
 }
 if (contract.rungs.some(r => !Number.isInteger(r.rung) || r.rung < 1) || Math.max(...contract.rungs.map(r => r.rung)) >= 4 || contract.tierFour.refused !== true) throw new Error(`${SOURCE} offers a tier outside one to three, or no longer refuses tier four. A phone is never given a rung that dispatches.`);
 if (contract.evaluation.ratifiedRules.length) throw new Error(`${SOURCE} names a ratified rule. A phone cannot read the protocol register, so decide what it may say before emitting again.`);
 const notEvaluated = contract.evaluation.reasons.find(r => r.id === 'no-ratified-rule');
 if (!notEvaluated) throw new Error(`${SOURCE} has lost the reason no-ratified-rule.`);
 const statutory = contract.safeguarding.statutory;
 if (statutory.integrated !== false || statutory.statusCode !== 'not-sent') throw new Error(`${SOURCE} says a report reaches the police or social development. Nothing sends one, so no phone may say one was.`);

 const texts = [
  ['SentinelText', strings(contract.screens.sentinel)],
  ['ReportText', strings(contract.screens.report)],
  ['DeskText', strings(contract.screens.desk)],
  ['RuleText', [
   ['whereValuesLive', contract.whereValuesLive.sentence], ['baselines', contract.baselines.sentence], ['keepsItsSettings', contract.baselines.keepsItsSettings],
   ['suspendedMeans', contract.baselines.suspendedMeans], ['recalledMeans', contract.baselines.recalledMeans], ['staleWhy', contract.baselines.staleWhy],
   ['notEvaluated', notEvaluated.sentence], ['raisedByHand', contract.evaluation.raisedByHand], ['tierFourMeans', contract.tierFour.means],
   ['categoryIsProtected', contract.safeguarding.categoryIsProtected], ['neverAutoCloses', contract.safeguarding.neverAutoCloses],
   ['heldFor', contract.safeguarding.officer.heldFor], ['heldForCode', contract.safeguarding.officer.heldForCode], ['notSent', statutory.notSent],
   ['statutoryCode', statutory.statusCode], ['statutoryReasonCode', statutory.reasonCode], ['reporterNeverShown', contract.safeguarding.reporterNeverShown],
   ['guardian', contract.safeguarding.guardian], ['noNarrative', contract.safeguarding.noNarrative], ['preview', contract.screens.preview]
  ]]
 ];
 const tierFourRefusal = refusals.get(contract.tierFour.refusal);
 if (!tierFourRefusal) throw new Error(`${API} does not declare ${contract.tierFour.refusal}, the sentence tier four is refused in.`);

 const swiftFile = `${banner()}

import Foundation

extension Sentinel {
    /// ${windowDays.note}
    static let baselineWindowDays = ${windowDays.value}
    /// ${minimum.note}
    static let baselineMinimumReadings = ${minimum.value}
    /// Whether the window and minimum above still wait on a clinical review.
    static let baselineSettingsUnreviewed = ${windowDays.unreviewed || minimum.unreviewed}

    static let rungs: [SentinelRung] = [
${contract.rungs.map(r => `        .init(rung: ${r.rung}, id: ${swift(r.id)}, label: ${swift(r.label)}, means: ${swift(r.means)}, toldCode: ${swift(r.toldCode)}, whoIsTold: ${swift(r.whoIsTold)})`).join(',\n')}
    ]
    static let tierFourNeeds: [String] = [
${contract.tierFour.needs.map(n => `        ${swift(n.sentence)}`).join(',\n')}
    ]
    static let tierFourRefusal = ${swift(tierFourRefusal.statement)}
    static let baselineStates: [SentinelChoice] = [
${contract.baselines.states.map(s => `        .init(id: ${swift(s.id)}, label: ${swift(s.label)}, sentence: ${swift(s.sentence)})`).join(',\n')}
    ]
    static let groups: [SentinelChoice] = [
${contract.safeguarding.groups.map(g => `        .init(id: ${swift(g.id)}, label: ${swift(g.label)}, sentence: "")`).join(',\n')}
    ]
    static let categories: [SentinelChoice] = [
${contract.safeguarding.categories.map(c => `        .init(id: ${swift(c.id)}, label: ${swift(c.label)}, sentence: "")`).join(',\n')}
    ]
    /// What the law may ask of a report about each group. A proposal nobody with legal authority has reviewed.
    static let statutoryMayApply: [SentinelChoice] = [
${statutory.mayApply.map(m => `        .init(id: ${swift(m.group)}, label: "", sentence: ${swift(m.sentence)})`).join(',\n')}
    ]

${texts.map(([name, entries]) => `    enum ${name} {
${entries.map(([key, value]) => `        static let ${camel(key)} = ${swift(value)}`).join('\n')}
    }`).join('\n\n')}

    static let refusals: [SentinelRefusal] = [
${[...refusals.values()].map(r => `        .init(id: ${swift(r.id)}, status: ${r.status}, statement: ${swift(r.statement)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object SentinelData {
    /** ${windowDays.note} */
    const val baselineWindowDays = ${windowDays.value}
    /** ${minimum.note} */
    const val baselineMinimumReadings = ${minimum.value}
    /** Whether the window and minimum above still wait on a clinical review. */
    const val baselineSettingsUnreviewed = ${windowDays.unreviewed || minimum.unreviewed}

    val rungs = listOf(
${contract.rungs.map(r => `        SentinelRung(${r.rung}, ${kotlin(r.id)}, ${kotlin(r.label)}, ${kotlin(r.means)}, ${kotlin(r.toldCode)}, ${kotlin(r.whoIsTold)})`).join(',\n')}
    )
    val tierFourNeeds = listOf(
${contract.tierFour.needs.map(n => `        ${kotlin(n.sentence)}`).join(',\n')}
    )
    const val tierFourRefusal = ${kotlin(tierFourRefusal.statement)}
    val baselineStates = listOf(
${contract.baselines.states.map(s => `        SentinelChoice(${kotlin(s.id)}, ${kotlin(s.label)}, ${kotlin(s.sentence)})`).join(',\n')}
    )
    val groups = listOf(
${contract.safeguarding.groups.map(g => `        SentinelChoice(${kotlin(g.id)}, ${kotlin(g.label)}, "")`).join(',\n')}
    )
    val categories = listOf(
${contract.safeguarding.categories.map(c => `        SentinelChoice(${kotlin(c.id)}, ${kotlin(c.label)}, "")`).join(',\n')}
    )
    /** What the law may ask of a report about each group. A proposal nobody with legal authority has reviewed. */
    val statutoryMayApply = listOf(
${statutory.mayApply.map(m => `        SentinelChoice(${kotlin(m.group)}, "", ${kotlin(m.sentence)})`).join(',\n')}
    )

${texts.map(([name, entries]) => `    object ${name} {
${entries.map(([key, value]) => `        const val ${camel(key)} = ${kotlin(value)}`).join('\n')}
    }`).join('\n\n')}

    val refusals = listOf(
${[...refusals.values()].map(r => `        SentinelRefusal(${kotlin(r.id)}, ${r.status}, ${kotlin(r.statement)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/SentinelData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/SentinelData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitSentinel()) {
  writeFileSync(file.path, file.content);
  console.log(`sentinel → ${file.path}`);
 }
}
