/* The South African Sign Language accommodation, written out for two native apps, by a machine.

   The modes, the four fictional interpreters and their free hours, the hold, the honest wait, the
   free cancellation, the seven rules and the eight refusals live in
   packages/catalog/interpreting.json. The web reads that file. iOS and Android cannot, and should
   not, for the reason the vetting generator gives.

   One thing here is the point of the generator rather than incidental to it: **no wait is written
   out.** The roster carries the hours each interpreter is free, unresolved, and each platform works
   out for itself which is the first one after the hour that was asked for — and returns nothing at
   all when there is none. Emitting a resolved "next free" would mean the arithmetic lived in this
   file and the three apps drew whatever they were handed, which is exactly the arrangement in which
   a screen quietly learns to print a number for a wait nobody can measure. It is the same rule the
   programmes generator is held to, for the same reason.

   Escaping, and the two languages disagree about it:
     - Swift needs only its quotes escaped; nothing in this contract carries a backslash.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and a
       lone $ starts a string template.
   Curly quotes, en-dashes and em-dashes are simply UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/interpreting.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const swiftOptional = value => (value === null || value === undefined ? 'nil' : swift(value));
const kotlinOptional = value => (value === null || value === undefined ? 'null' : kotlin(value));

const banner = () => [
 `Generated by scripts/emit-interpreting.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run interpreting`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Every interpreter below carries the hours they are actually free, unresolved. Which of them is the',
 'first free after the hour a patient asked for — and whether there is one at all — is worked out in',
 'Interpreting.swift and Interpreting.kt beside this file, from the same hours the web works it out',
 'from. A resolved wait here would mean the arithmetic lived in a generator, and a screen that is',
 'handed a number never has to decide whether it knows one.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitInterpreting(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const { accreditation, hold, estimate, cancellation, withdrawal, cost, labels } = contract;

 const swiftFile = `${banner()}

import Foundation

extension Interpreting {
    static let requirementId = ${swift(contract.requirementId)}
    static let roleId = ${swift(contract.roleId)}
    static let participantId = ${swift(contract.participantId)}
    /* Drafted, not confirmed. \`confirmedBy\` is nil and every screen that shows this check says so
       — the same rule the locale contract holds a translation to. */
    static let accreditation = InterpreterAccreditation(
        body: ${swift(accreditation.body)}, short: ${swift(accreditation.short)},
        authorityId: ${swift(accreditation.authorityId)},
        route: ${swift(accreditation.route)},
        confirmedBy: ${swiftOptional(accreditation.confirmedBy)},
        confirmedOrganisation: ${swiftOptional(accreditation.confirmedOrganisation)},
        confirmedOn: ${swiftOptional(accreditation.confirmedOn)},
        uncertainty: ${swift(accreditation.uncertainty)},
        whatWouldMakeItTrue: ${swift(accreditation.whatWouldMakeItTrue)})
    static let modes: [InterpretingMode] = [
${contract.modes.map(m => `        .init(id: ${swift(m.id)}, name: ${swift(m.name)}, detail: ${swift(m.detail)}, note: ${swift(m.note)})`).join(',\n')}
    ]
    /* Free hours, unresolved. Interpreting.swift decides which one answers a request. */
    static let roster: [Interpreter] = [
${contract.roster.map(person => `        .init(id: ${swift(person.id)}, name: ${swift(person.name)}, reference: ${swift(person.reference)},
              mode: ${swift(person.mode)}, area: ${swift(person.area)},
              settings: [${person.settings.map(swift).join(', ')}],
              free: [${person.free.map(day => `.init(dayOffset: ${day.dayOffset}, slots: [${day.slots.map(swift).join(', ')}])`).join(', ')}])`).join(',\n')}
    ]
    static let hold = InterpreterHold(
        status: ${swift(hold.status)}, title: ${swift(hold.title)},
        sentence: ${swift(hold.sentence)},
        whyNotDispatched: ${swift(hold.whyNotDispatched)},
        whatHappensNext: ${swift(hold.whatHappensNext)})
    static let estimate = InterpreterEstimate(
        knownPrefix: ${swift(estimate.knownPrefix)},
        unknown: ${swift(estimate.unknown)},
        unknownDetail: ${swift(estimate.unknownDetail)},
        horizonNote: ${swift(estimate.horizonNote)})
    static let cancellation = InterpreterCancellation(
        fee: ${cancellation.fee}, attributedTo: ${swift(cancellation.attributedTo)},
        label: ${swift(cancellation.label)},
        sentence: ${swift(cancellation.sentence)},
        notThePatientsChoice: ${swift(cancellation.notThePatientsChoice)},
        keepsTheRequirement: ${swift(cancellation.keepsTheRequirement)})
    static let withdrawal = InterpreterWithdrawal(
        endsTheConsultation: ${withdrawal.endsTheConsultation},
        question: ${swift(withdrawal.question)},
        sentence: ${swift(withdrawal.sentence)},
        why: ${swift(withdrawal.why)},
        notAPunishment: ${swift(withdrawal.notAPunishment)})
    static let cost = InterpreterCost(charged: ${cost.charged}, sentence: ${swift(cost.sentence)})
    /* Rendered word for word. A refusal paraphrased on one platform is a different promise on that
       platform, which is the whole reason these live in one file. */
    static let rules: [InterpretingRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let refusals: [InterpretingRefusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let labels = InterpretingLabels(
${Object.entries(labels).map(([key, value]) => `        ${key}: ${swift(value)}`).join(',\n')})
    static let notYetBuilt = ${swift(contract.notYetBuilt)}
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

const val interpreterRequirementId = ${kotlin(contract.requirementId)}
const val interpreterRoleId = ${kotlin(contract.roleId)}
const val interpreterParticipantId = ${kotlin(contract.participantId)}

/* Drafted, not confirmed. \`confirmedBy\` is null and every screen that shows this check says so —
   the same rule the locale contract holds a translation to. */
val interpreterAccreditation = InterpreterAccreditation(
    ${kotlin(accreditation.body)}, ${kotlin(accreditation.short)}, ${kotlin(accreditation.authorityId)},
    ${kotlin(accreditation.route)},
    ${kotlinOptional(accreditation.confirmedBy)},
    ${kotlinOptional(accreditation.confirmedOrganisation)},
    ${kotlinOptional(accreditation.confirmedOn)},
    ${kotlin(accreditation.uncertainty)},
    ${kotlin(accreditation.whatWouldMakeItTrue)}
)

val interpretingModes = listOf(
${contract.modes.map(m => `    InterpretingMode(${kotlin(m.id)}, ${kotlin(m.name)}, ${kotlin(m.detail)}, ${kotlin(m.note)})`).join(',\n')}
)

/* Free hours, unresolved. Interpreting.kt decides which one answers a request. */
val interpreterRoster = listOf(
${contract.roster.map(person => `    Interpreter(
        ${kotlin(person.id)}, ${kotlin(person.name)}, ${kotlin(person.reference)},
        ${kotlin(person.mode)}, ${kotlin(person.area)},
        listOf(${person.settings.map(kotlin).join(', ')}),
        listOf(${person.free.map(day => `FreeDay(${day.dayOffset}, listOf(${day.slots.map(kotlin).join(', ')}))`).join(', ')})
    )`).join(',\n')}
)

val interpreterHold = InterpreterHold(
    ${kotlin(hold.status)}, ${kotlin(hold.title)},
    ${kotlin(hold.sentence)},
    ${kotlin(hold.whyNotDispatched)},
    ${kotlin(hold.whatHappensNext)}
)

val interpreterEstimate = InterpreterEstimate(
    ${kotlin(estimate.knownPrefix)},
    ${kotlin(estimate.unknown)},
    ${kotlin(estimate.unknownDetail)},
    ${kotlin(estimate.horizonNote)}
)

val interpreterCancellation = InterpreterCancellation(
    ${cancellation.fee}, ${kotlin(cancellation.attributedTo)},
    ${kotlin(cancellation.label)},
    ${kotlin(cancellation.sentence)},
    ${kotlin(cancellation.notThePatientsChoice)},
    ${kotlin(cancellation.keepsTheRequirement)}
)

val interpreterWithdrawal = InterpreterWithdrawal(
    ${withdrawal.endsTheConsultation},
    ${kotlin(withdrawal.question)},
    ${kotlin(withdrawal.sentence)},
    ${kotlin(withdrawal.why)},
    ${kotlin(withdrawal.notAPunishment)}
)

val interpreterCost = InterpreterCost(${cost.charged}, ${kotlin(cost.sentence)})

/* Rendered word for word. A refusal paraphrased on one platform is a different promise on that
   platform, which is the whole reason these live in one file. */
val interpretingRules = listOf(
${contract.rules.map(r => `    InterpretingRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val interpretingRefusals = listOf(
${contract.refusals.map(r => `    InterpretingRefusal(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val interpretingLabels = InterpretingLabels(
${Object.entries(labels).map(([, value]) => `    ${kotlin(value)}`).join(',\n')}
)

const val interpretingNotYetBuilt = ${kotlin(contract.notYetBuilt)}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/InterpretingData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/InterpretingData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitInterpreting()) {
  writeFileSync(file.path, file.content);
  console.log(`interpreting → ${file.path}`);
 }
}
