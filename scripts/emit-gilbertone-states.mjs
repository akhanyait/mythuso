/* GilbertOne's helper lines (the MyThuso v3 pack, 29 October 2026), written out for the two native apps, by a machine.

   The lines live in packages/catalog/gilbertone-states.json with the six states they take their pose from. The web
   reads that file; iOS and Android get this, so a sentence GilbertOne says on a phone is the contract's and never
   typed into Swift or Kotlin. The phones draw GilbertOne's existing mark beside the line and carry the state as a
   name: the six shape-changing poses are the web's drawing for now.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a lone $ starts a
   template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/gilbertone-states.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

const banner = () => [
 `Generated by scripts/emit-gilbertone-states.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run gilbertone-states`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'GilbertOne helps people find their way and tidy notes. It never diagnoses, never interprets readings',
 'clinically and never makes care decisions.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitGilbertOneStates(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const helpers = Object.entries(contract.helpers);

 const swiftFile = `${banner()}

import Foundation

struct GilbertOneHelper: Hashable {
    let state: String
    let text: String
}

enum GilbertOneStatesData {
    static let rule = ${swift(contract.rule)}
    static let states: [String] = [${contract.states.map(s => swift(s.id)).join(', ')}]
${helpers.map(([id, h]) => `    static let ${id} = GilbertOneHelper(state: ${swift(h.state)}, text: ${swift(h.text)})`).join('\n')}
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

data class GilbertOneHelper(val state: String, val text: String)

object GilbertOneStatesData {
    const val rule = ${kotlin(contract.rule)}
    val states = listOf(${contract.states.map(s => kotlin(s.id)).join(', ')})
${helpers.map(([id, h]) => `    val ${id} = GilbertOneHelper(${kotlin(h.state)}, ${kotlin(h.text)})`).join('\n')}
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/GilbertOneStatesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/GilbertOneStatesData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitGilbertOneStates()) {
  writeFileSync(file.path, file.content);
  console.log(`gilbertone-states → ${file.path}`);
 }
}
