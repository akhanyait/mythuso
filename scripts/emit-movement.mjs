/* Thuso Ride's responder app, written out for two native apps by a machine.

   packages/catalog/movement.json holds the priorities and the sentence that Thuso Ride is not an ambulance, the trip
   states, who may receive a patient at a hand-over and the checklist, the synthetic facilities a trip goes to, the
   responder screen's words and the heartbeat interval. packages/catalog/apis/movement.json holds every refusal
   sentence the responder's routes answer with, resolved here so the sentence a route answers with and the sentence a
   phone shows are one string. A zone's name is packages/catalog/geography.json's. The web reads all of it through
   packages/engines/src/movement/domain; iOS and Android cannot read JSON at runtime, so the copy is generated rather
   than typed, and scripts/check-boundaries.mjs compares it on every build.

   WHAT A PHONE IS GIVEN. The responder's side and nothing else: the admissions desk, the facility's simulated answer
   and the P1 route are the desk's, on the web. No admission state is emitted, so no phone can draw a pending bed at
   all, and the emergency summary's category names are the Health Passport's generated contract, not this file's.

   WHAT THIS GENERATOR REFUSES TO EMIT. A priority list in which Thuso Ride takes a P1, a checklist or a receiving
   role list that is empty, a facility in a zone geography.json does not hold, and a responder refusal the contract
   does not declare.

   THE SETTINGS ARE DEFAULTS. An admin changes them on the web; neither app reaches a settings route, so both use the
   defaults written here and say so in the sentence scripts/settings-defaults.mjs writes for every engine.

   Escaping: Swift needs its backslashes and quotes escaped; Kotlin needs backslash, quote and dollar, because a lone
   $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/movement.json';
const API = 'packages/catalog/apis/movement.json';
const GEOGRAPHY = 'packages/catalog/geography.json';

const swift = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const camel = key => key.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const snake = key => key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/-/g, '_').toUpperCase();

/* The refusals the responder's phone can be answered with, by the routes a responder calls. */
const RESPONDER_ROUTES = [
 'POST /v1/movement/responder-heartbeats@2',
 'POST /v1/movement/trips/{tripRef}/accept@2',
 'POST /v1/movement/trips/{tripRef}/decline@1',
 'POST /v1/movement/trips/{tripRef}/handover@2'
];

const banner = () => [
 `Generated by scripts/emit-movement.mjs from ${SOURCE}, ${API} and ${GEOGRAPHY}.`,
 'Do not edit by hand — run `npm run movement`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'Thuso Ride is non-emergency transport and never an ambulance. A responder sees a trip offered to them, accepts or',
 'declines it, reads the emergency summary only while the trip is under way, and hands the patient over by role',
 'with the checklist. The heartbeat interval is a PROPOSAL an admin changes on the web; this app has no admin',
 'surface and uses it as written. Nothing here reads this phone\'s position or reaches a responder.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitMovement(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const geography = JSON.parse(readFileSync(root + GEOGRAPHY, 'utf8'));

 if (contract.priorities.some(p => p.id === 'P1' && (p.takenByThusoRide !== false || p.routedTo !== null))) throw new Error(`${SOURCE} lets Thuso Ride take a P1, or routes one somewhere. A phone is never handed a priority list in which a P1 is a trip.`);
 if (!contract.trips.receivingRoles.length || !contract.trips.checklist.length) throw new Error(`${SOURCE} gives a hand-over no receiving roles or no checklist, so a phone could record a patient left at a door.`);
 const zoneName = id => {
  const zone = geography.zones.find(z => z.id === id);
  if (!zone) throw new Error(`${SOURCE} names the zone "${id}", which ${GEOGRAPHY} does not hold.`);
  return zone.name;
 };
 for (const f of contract.facilities.entries) zoneName(f.zoneId);

 const interval = settingDefault(SOURCE, contract, 'heartbeat-interval-seconds');

 const refusals = new Map();
 for (const key of RESPONDER_ROUTES) {
  const route = api.routes.find(r => `${r.method} ${r.path}@${r.version}` === key && !r.withdrawn);
  if (!route) throw new Error(`${API} has no live ${key}, whose refusals a responder's phone shows.`);
  const own = [...route.refusals, ...api.refusals.filter(r => (r.answeredBy ?? []).includes(key))];
  for (const r of own) {
   const seen = refusals.get(r.id);
   if (seen && seen !== r.statement) throw new Error(`${API} declares "${r.id}" in two different sentences.`);
   refusals.set(r.id, r.statement);
  }
 }

 const words = Object.entries(contract.screens.responder).filter(([, v]) => typeof v === 'string');
 const trip = contract.preview.trips[0];
 const facility = contract.facilities.entries.find(f => f.ref === trip.destinationFacilityRef);
 if (!facility) throw new Error(`${SOURCE} previews a trip to "${trip.destinationFacilityRef}", which its directory does not hold.`);

 const swiftFile = `${banner()}

import Foundation

extension Movement {
    /// ${interval.note}
    static let heartbeatIntervalSeconds = ${interval.value}

    static let notAnAmbulance = ${swift(contract.notAnAmbulance.sentence)}
    static let emsBoundary = ${swift(contract.emsBoundary.sentence)}
    static let preview = ${swift(contract.screens.previewPhone)}
    static let positionRule = ${swift(contract.position.sentence)}

    static let priorities: [PrioritySpec] = [
${contract.priorities.map(p => `        .init(id: ${swift(p.id)}, label: ${swift(p.label)}, takenByThusoRide: ${p.takenByThusoRide}, sentence: ${swift(p.sentence)})`).join(',\n')}
    ]
    static let tripStates: [Choice] = [
${contract.trips.states.map(s => `        .init(id: ${swift(s.id)}, label: ${swift(s.label)})`).join(',\n')}
    ]
    static let receivingRoles: [Choice] = [
${contract.trips.receivingRoles.map(s => `        .init(id: ${swift(s.id)}, label: ${swift(s.label)})`).join(',\n')}
    ]
    static let checklist: [String] = [
${contract.trips.checklist.map(line => `        ${swift(line)}`).join(',\n')}
    ]
    static let facilities: [Choice] = [
${contract.facilities.entries.map(f => `        .init(id: ${swift(f.ref)}, label: ${swift(f.name)})`).join(',\n')}
    ]
    static let zones: [Choice] = [
${geography.zones.map(z => `        .init(id: ${swift(z.id)}, label: ${swift(z.name)})`).join(',\n')}
    ]

    enum ResponderText {
${words.map(([k, v]) => `        static let ${camel(k)} = ${swift(v)}`).join('\n')}
    }

    /// The sentences the responder's routes refuse in, word for word from ${API}.
    enum Refusals {
${[...refusals].map(([id, statement]) => `        static let ${camel(id)} = ${swift(statement)}`).join('\n')}
    }

    static let previewTrip = PreviewTrip(ref: ${swift(trip.ref)}, priorityClass: ${swift(trip.priorityClass)}, zoneId: ${swift(trip.pickupZoneId)},
                                         pickupInMinutes: ${trip.pickupInMinutes}, facilityRef: ${swift(trip.destinationFacilityRef)}, responderRef: ${swift(contract.preview.responderRef)})
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object MovementData {
    /** ${interval.note} */
    const val HEARTBEAT_INTERVAL_SECONDS = ${interval.value}

    const val NOT_AN_AMBULANCE = ${kotlin(contract.notAnAmbulance.sentence)}
    const val EMS_BOUNDARY = ${kotlin(contract.emsBoundary.sentence)}
    const val PREVIEW = ${kotlin(contract.screens.previewPhone)}
    const val POSITION_RULE = ${kotlin(contract.position.sentence)}

    val priorities = listOf(
${contract.priorities.map(p => `        MovementPriority(${kotlin(p.id)}, ${kotlin(p.label)}, ${p.takenByThusoRide}, ${kotlin(p.sentence)})`).join(',\n')}
    )
    val tripStates = listOf(
${contract.trips.states.map(s => `        MovementChoice(${kotlin(s.id)}, ${kotlin(s.label)})`).join(',\n')}
    )
    val receivingRoles = listOf(
${contract.trips.receivingRoles.map(s => `        MovementChoice(${kotlin(s.id)}, ${kotlin(s.label)})`).join(',\n')}
    )
    val checklist = listOf(
${contract.trips.checklist.map(line => `        ${kotlin(line)}`).join(',\n')}
    )
    val facilities = listOf(
${contract.facilities.entries.map(f => `        MovementChoice(${kotlin(f.ref)}, ${kotlin(f.name)})`).join(',\n')}
    )
    val zones = listOf(
${geography.zones.map(z => `        MovementChoice(${kotlin(z.id)}, ${kotlin(z.name)})`).join(',\n')}
    )

    object ResponderText {
${words.map(([k, v]) => `        const val ${snake(k)} = ${kotlin(v)}`).join('\n')}
    }

    /** The sentences the responder's routes refuse in, word for word from ${API}. */
    object Refusals {
${[...refusals].map(([id, statement]) => `        const val ${snake(id)} = ${kotlin(statement)}`).join('\n')}
    }

    val previewTrip = MovementPreviewTrip(${kotlin(trip.ref)}, ${kotlin(trip.priorityClass)}, ${kotlin(trip.pickupZoneId)}, ${trip.pickupInMinutes}, ${kotlin(trip.destinationFacilityRef)}, ${kotlin(contract.preview.responderRef)})
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/MovementData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/MovementData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitMovement()) {
  writeFileSync(file.path, file.content);
  console.log(`movement → ${file.path}`);
 }
}
