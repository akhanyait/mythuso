/* The teleconsultation call, written out for two native apps, by a machine.

   The roster, the five consent questions, the recording decision, the four connection states, the
   six clinical limits, the reconnection protocol, the seven encounter outcomes, the six rules and
   the six refusals live in packages/catalog/teleconsult.json. The web reads that file. iOS and
   Android cannot, and should not, for the reason the vetting generator gives.

   Two things about this contract are worth knowing before editing the output.

   Nobody is named in it. The doctor, the nurse and the guardian are roles — a participant carries a
   roleId into packages/catalog/vetting.json and the app resolves the party from the register, so a
   registration number appears in one place and the name on the patient's screen is the name the
   vetting record holds. That is also why no refusal sentence for a lapsed clinician is written
   here: the call refuses in can(subject, 'sign-clinical-review')'s own words, which are the clinical
   queue's words, because a patient told two different things by two screens believes neither.

   And `where` is a keyword in Swift, so a participant's location is emitted as `place`. The one
   place a generator is allowed to rename something is where the target language has taken the word.

   Escaping is the hazard, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped.
   The sentences carry en-dashes and curly quotes, which are simply UTF-8 and need nothing. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/teleconsult.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const optSwift = value => (value === undefined || value === null ? 'nil' : swift(value));
const optKotlin = value => (value === undefined || value === null ? 'null' : kotlin(value));
const swiftList = values => `[${values.map(swift).join(', ')}]`;
const kotlinList = values => `listOf(${values.map(kotlin).join(', ')})`;

const banner = () => [
 `Generated by scripts/emit-teleconsult.mjs from ${SOURCE}.`,
 'Do not edit by hand — run `npm run teleconsult`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Nobody is named below. A participant carries a roleId into the vetting register and the screen',
 'resolves the party from it, so the name and the registration number the patient is shown are the',
 'ones the register holds rather than a second copy of them.',
 '',
 'The reasoning that uses this table — which limits a connection state permits, whether an outcome',
 'may be called a consultation, and which sections of the record it writes — is hand-written in',
 'Teleconsult.swift and Teleconsult.kt beside it.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitTeleconsult(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const { media, identity, recording, reconnect } = contract;
 const kept = recording.whenItExists;

 const swiftFile = `${banner()}

import Foundation

extension Teleconsult {
    static let media = MediaPosture(declared: ${media.declared}, state: ${swift(media.state)}, sentence: ${swift(media.sentence)},
                                    states: [
${media.states.map(s => `                                        .init(id: ${swift(s.id)}, name: ${swift(s.name)}, detail: ${swift(s.detail)})`).join(',\n')}
                                    ],
                                    whyTheDistinctionMatters: ${swift(media.whyTheDistinctionMatters)})

    static let identity = CallIdentity(patientSideDetail: ${swift(identity.patientSideDetail)},
                                       doctorSideDetail: ${swift(identity.doctorSideDetail)},
                                       failure: ${swift(identity.failure)},
                                       whyOneMechanism: ${swift(identity.whyOneMechanism)})

    /* A participant is a role, not a person. The name on the screen comes from the vetting register
       through roleId, so the patient reads the registration the reviewer verified. */
    static let participants: [CallParticipant] = [
${contract.participants.map(p => `        .init(id: ${swift(p.id)}, name: ${swift(p.name)}, roleId: ${optSwift(p.roleId)}, place: ${swift(p.where)},
              sees: ${swift(p.sees)}, hears: ${swift(p.hears)}, essential: ${p.essential}, mayBeAskedToLeave: ${p.mayBeAskedToLeave},
              consentQuestion: ${optSwift(p.consentQuestion)}, ifDeclined: ${optSwift(p.ifDeclined)}, note: ${swift(p.note)})`).join(',\n')}
    ]

    /* Consent to each person's presence, separately, and every one of them revocable in the middle
       of the call — which is the only kind of consent worth asking for. */
    static let consent: [ConsentItem] = [
${contract.consent.map(c => `        .init(id: ${swift(c.id)}, participant: ${optSwift(c.participant)}, required: ${c.required}, revocable: ${c.revocable},
              revokedMidCall: ${swift(c.revokedMidCall)})`).join(',\n')}
    ]

    static let recording = RecordingPolicy(offeredInPreview: ${recording.offeredInPreview}, decision: ${swift(recording.decision)},
                                           why: ${swift(recording.why)},
                                           instead: [
${recording.instead.map(line => `                                            ${swift(line)}`).join(',\n')}
                                           ],
                                           whenItExists: .init(askedSeparately: ${swift(kept.askedSeparately)},
                                                               refusingIsCostless: ${swift(kept.refusingIsCostless)},
                                                               whileRecording: ${swift(kept.whileRecording)},
                                                               whoMayView: [
${kept.whoMayView.map(line => `                                                                ${swift(line)}`).join(',\n')}
                                                               ],
                                                               keptForDays: ${kept.keptForDays},
                                                               afterwards: ${swift(kept.afterwards)}))

    static let clinicalLimits: [ClinicalLimit] = [
${contract.clinicalLimits.map(l => `        .init(id: ${swift(l.id)}, name: ${swift(l.name)}, needs: ${swift(l.needs)}, detail: ${swift(l.detail)})`).join(',\n')}
    ]

    /* Ordered by fidelity, and what each one permits is a subset of the one above it. The build
       fails if that stops being true, because a degraded line that permits more than a good one is
       a screen telling a doctor they may conclude something they may not. */
    static let connection: [ConnectionState] = [
${contract.connection.map(c => `        .init(id: ${swift(c.id)}, name: ${swift(c.name)}, fidelity: ${c.fidelity}, patientSees: ${swift(c.patientSees)},
              doctorSees: ${swift(c.doctorSees)}, permits: ${swiftList(c.permits)}, note: ${swift(c.note)})`).join(',\n')}
    ]

    static let reconnect = Reconnect(holdSeconds: ${reconnect.holdSeconds}, attempts: ${reconnect.attempts},
                                     whoCallsWhom: ${swift(reconnect.whoCallsWhom)},
                                     duringTheHold: ${swift(reconnect.duringTheHold)},
                                     afterTheHold: ${swift(reconnect.afterTheHold)},
                                     ifUnreachable: ${swift(reconnect.ifUnreachable)},
                                     nurseInTheRoom: ${swift(reconnect.nurseInTheRoom)},
                                     whyNotLonger: ${swift(reconnect.whyNotLonger)})

    /* The 'writes' list names sections of the consultation record in packages/catalog/records.json. An
       outcome that is not a consultation cannot name the assessment or the plan, and the build
       fails if one does — that is the whole invariant of this feature, held as arithmetic rather
       than as a paragraph asking people to be careful. */
    static let outcomes: [EncounterOutcome] = [
${contract.outcomes.map(o => `        .init(id: ${swift(o.id)}, name: ${swift(o.name)}, reachedDecision: ${o.reachedDecision}, connectionLost: ${o.connectionLost},
              countsAsConsultation: ${o.countsAsConsultation}, charged: ${o.charged}, writes: ${swiftList(o.writes)},
              record: ${swift(o.record)})`).join(',\n')}
    ]

    /* Rendered word for word. A rule paraphrased on one platform is a different promise on that
       platform, which is the whole reason these live in one file. */
    static let rules: [CallRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]

    static let refusals: [CallRefusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

val callMedia = MediaPosture(
    ${media.declared}, ${kotlin(media.state)}, ${kotlin(media.sentence)},
    listOf(
${media.states.map(s => `        MediaState(${kotlin(s.id)}, ${kotlin(s.name)}, ${kotlin(s.detail)})`).join(',\n')}
    ),
    ${kotlin(media.whyTheDistinctionMatters)}
)

val callIdentity = CallIdentity(
    ${kotlin(identity.patientSideDetail)},
    ${kotlin(identity.doctorSideDetail)},
    ${kotlin(identity.failure)},
    ${kotlin(identity.whyOneMechanism)}
)

/* A participant is a role, not a person. The name on the screen comes from the vetting register
   through roleId, so the patient reads the registration the reviewer verified. */
val callParticipants = listOf(
${contract.participants.map(p => `    CallParticipant(
        ${kotlin(p.id)}, ${kotlin(p.name)}, ${optKotlin(p.roleId)}, ${kotlin(p.where)},
        ${kotlin(p.sees)}, ${kotlin(p.hears)}, ${p.essential}, ${p.mayBeAskedToLeave},
        ${optKotlin(p.consentQuestion)}, ${optKotlin(p.ifDeclined)}, ${kotlin(p.note)}
    )`).join(',\n')}
)

/* Consent to each person's presence, separately, and every one of them revocable in the middle of
   the call — which is the only kind of consent worth asking for. */
val callConsent = listOf(
${contract.consent.map(c => `    ConsentItem(${kotlin(c.id)}, ${optKotlin(c.participant)}, ${c.required}, ${c.revocable}, ${kotlin(c.revokedMidCall)})`).join(',\n')}
)

val callRecording = RecordingPolicy(
    ${recording.offeredInPreview}, ${kotlin(recording.decision)},
    ${kotlin(recording.why)},
    listOf(
${recording.instead.map(line => `        ${kotlin(line)}`).join(',\n')}
    ),
    RecordingIfItExisted(
        ${kotlin(kept.askedSeparately)},
        ${kotlin(kept.refusingIsCostless)},
        ${kotlin(kept.whileRecording)},
        listOf(
${kept.whoMayView.map(line => `            ${kotlin(line)}`).join(',\n')}
        ),
        ${kept.keptForDays},
        ${kotlin(kept.afterwards)}
    )
)

val callClinicalLimits = listOf(
${contract.clinicalLimits.map(l => `    ClinicalLimit(${kotlin(l.id)}, ${kotlin(l.name)}, ${kotlin(l.needs)}, ${kotlin(l.detail)})`).join(',\n')}
)

/* Ordered by fidelity, and what each one permits is a subset of the one above it. The build fails
   if that stops being true, because a degraded line that permits more than a good one is a screen
   telling a doctor they may conclude something they may not. */
val callConnectionStates = listOf(
${contract.connection.map(c => `    ConnectionState(
        ${kotlin(c.id)}, ${kotlin(c.name)}, ${c.fidelity}, ${kotlin(c.patientSees)},
        ${kotlin(c.doctorSees)}, ${kotlinList(c.permits)}, ${kotlin(c.note)}
    )`).join(',\n')}
)

val callReconnect = Reconnect(
    ${reconnect.holdSeconds}, ${reconnect.attempts},
    ${kotlin(reconnect.whoCallsWhom)},
    ${kotlin(reconnect.duringTheHold)},
    ${kotlin(reconnect.afterTheHold)},
    ${kotlin(reconnect.ifUnreachable)},
    ${kotlin(reconnect.nurseInTheRoom)},
    ${kotlin(reconnect.whyNotLonger)}
)

/* The 'writes' list names sections of the consultation record in packages/catalog/records.json. An outcome
   that is not a consultation cannot name the assessment or the plan, and the build fails if one
   does — that is the whole invariant of this feature, held as arithmetic rather than as a paragraph
   asking people to be careful. */
val callOutcomes = listOf(
${contract.outcomes.map(o => `    EncounterOutcome(
        ${kotlin(o.id)}, ${kotlin(o.name)}, ${o.reachedDecision}, ${o.connectionLost},
        ${o.countsAsConsultation}, ${o.charged}, ${kotlinList(o.writes)},
        ${kotlin(o.record)}
    )`).join(',\n')}
)

/* Rendered word for word. A rule paraphrased on one platform is a different promise on that
   platform, which is the whole reason these live in one file. */
val callRules = listOf(
${contract.rules.map(r => `    CallRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val callRefusals = listOf(
${contract.refusals.map(r => `    CallRefusal(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/TeleconsultData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/TeleconsultData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitTeleconsult()) {
  writeFileSync(file.path, file.content);
  console.log(`teleconsult → ${file.path}`);
 }
}
