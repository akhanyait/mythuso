/* The chain of custody at the door, written out for two native apps, by a machine.
 *
 * A nurse, a courier or a responder holds a phone at a patient's door with a sealed bag in the other hand. What the
 * phone needs to refuse a hand-over is packages/catalog/medicines.json's: the collector roles, the PIN's length, the
 * custody states and why a collection is voided, and the screen's words; packages/catalog/dispensing.json's
 * schedules and who drives; the refusal sentences of the two routes a collector calls, and the engine refusals
 * those routes answer, from packages/catalog/apis/medicines.json; and the three collection settings' defaults,
 * through scripts/settings-defaults.mjs. The web reads all of them through packages/engines/src/medicines/domain;
 * iOS and Android cannot read JSON at runtime, so the copy is generated rather than typed and
 * scripts/check-boundaries.mjs compares it on every build.
 *
 * WHAT IS NOT WRITTEN. No formulary, no check outcome and nothing about a lab result: no phone prescribes,
 * verifies, dispenses or acknowledges in this wave, and a list a phone does not use is a list nobody updates. No
 * setting's value an admin put in force: neither app reaches a settings route, so each uses the defaults written
 * here and says so beside each.
 *
 * Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and $.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/medicines.json';
const DISPENSING = 'packages/catalog/dispensing.json';
const API = 'packages/catalog/apis/medicines.json';

const swift = value => {
 if (String(value).includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${String(value).replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const routeKey = r => `${r.method} ${r.path}@${r.version}`;

/* The routes a collector calls from a phone. A route found withdrawn or missing is refused here rather than written. */
const COLLECTOR_ROUTES = ['POST /v1/medicines/collections@2', 'POST /v1/medicines/collections/{collectionRef}/handover@2'];

const banner = () => [
 `Generated by scripts/emit-medicines.mjs from ${SOURCE}, ${DISPENSING} and ${API}.`,
 'Do not edit by hand — run `npm run medicines`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'The PIN lifetime, the attempts and the collection window are PROPOSALS, with decidedBy null in the',
 'contract, and defaults an admin changes on the web back office. This app reaches no settings route and',
 'uses them as written here; a collection keeps the terms it was authorised under either way.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitMedicines(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const dispensing = JSON.parse(readFileSync(root + DISPENSING, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));

 const pinLifetime = settingDefault(SOURCE, contract, 'pin-lifetime');
 const pinAttempts = settingDefault(SOURCE, contract, 'pin-attempts');
 const window = settingDefault(SOURCE, contract, 'collection-window');
 const pinDigits = contract.custody.pinDigits;
 if (pinDigits.decidedBy === null && !(pinDigits.proposedBy?.trim() && pinDigits.proposedBecause?.trim())) throw new Error(`${SOURCE} custody.pinDigits is a proposal that does not say who proposed it and why.`);

 const routes = COLLECTOR_ROUTES.map(key => {
  const found = api.routes.find(r => routeKey(r) === key && !r.withdrawn);
  if (!found) throw new Error(`${API} has no live ${key}, which a collector's phone calls.`);
  return found;
 });
 const seen = new Map();
 for (const r of [...routes.flatMap(route => route.refusals), ...api.refusals.filter(r => (r.answeredBy ?? []).some(k => COLLECTOR_ROUTES.includes(k)))]) {
  const before = seen.get(r.id);
  if (before && (before.status !== r.status || before.statement !== r.statement)) throw new Error(`${API} declares "${r.id}" in two different sentences on the routes a collector calls.`);
  seen.set(r.id, { id: r.id, status: r.status, statement: r.statement });
 }
 const refusals = [...seen.values()];
 const text = Object.entries(contract.screen.handover).filter(([key, value]) => typeof value === 'string' && !key.startsWith('_'));
 const schedules = dispensing.schedules.items;
 const drivers = dispensing.schedules.drivers.roles;
 const list = (items, write) => items.map(write).join(', ');

 const swiftFile = `${banner()}

import Foundation

extension Medicines {
    /// ${pinLifetime.note}
    static let pinLifetimeMinutes = ${pinLifetime.value}
    /// ${pinAttempts.note}
    static let pinAttempts = ${pinAttempts.value}
    /// ${window.note}
    static let collectionWindowMinutes = ${window.value}
    /// ${pinDigits.decidedBy === null ? 'A proposal nobody has decided.' : `Decided by the ${pinDigits.decidedBy}.`} Not a setting: a phone's PIN field is built to it.
    static let pinDigits = ${pinDigits.value}

    static let collectorRoles = [${list(contract.custody.collectorRoles, swift)}]
    static let driverRoles = [${list(drivers, swift)}]
    static let schedules: [MedicineSchedule] = [
${schedules.map(s => `        .init(id: ${swift(s.id)}, name: ${swift(s.name)}, driverMayCarry: ${s.driverMayCarry})`).join(',\n')}
    ]
    static let custodyStates: [MedicinesChoice] = [
${contract.custody.states.map(s => `        .init(id: ${swift(s.code)}, label: ${swift(s.label)})`).join(',\n')}
    ]
    static let voidReasons: [MedicinesChoice] = [
${contract.custody.voidReasons.map(s => `        .init(id: ${swift(s.code)}, label: ${swift(s.label)})`).join(',\n')}
    ]

    enum HandoverText {
${text.map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }

    static let refusals: [MedicinesRefusal] = [
${refusals.map(r => `        .init(id: ${swift(r.id)}, status: ${r.status}, statement: ${swift(r.statement)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object MedicinesData {
    /** ${pinLifetime.note} */
    const val pinLifetimeMinutes = ${pinLifetime.value}
    /** ${pinAttempts.note} */
    const val pinAttempts = ${pinAttempts.value}
    /** ${window.note} */
    const val collectionWindowMinutes = ${window.value}
    /** ${pinDigits.decidedBy === null ? 'A proposal nobody has decided.' : `Decided by the ${pinDigits.decidedBy}.`} Not a setting: a phone's PIN field is built to it. */
    const val pinDigits = ${pinDigits.value}

    val collectorRoles = listOf(${list(contract.custody.collectorRoles, kotlin)})
    val driverRoles = listOf(${list(drivers, kotlin)})
    val schedules = listOf(
${schedules.map(s => `        MedicineSchedule(${kotlin(s.id)}, ${kotlin(s.name)}, ${s.driverMayCarry})`).join(',\n')}
    )
    val custodyStates = listOf(
${contract.custody.states.map(s => `        MedicinesChoice(${kotlin(s.code)}, ${kotlin(s.label)})`).join(',\n')}
    )
    val voidReasons = listOf(
${contract.custody.voidReasons.map(s => `        MedicinesChoice(${kotlin(s.code)}, ${kotlin(s.label)})`).join(',\n')}
    )

    object HandoverText {
${text.map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }

    val refusals = listOf(
${refusals.map(r => `        MedicinesRefusal(${kotlin(r.id)}, ${r.status}, ${kotlin(r.statement)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/MedicinesData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/MedicinesData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitMedicines()) {
  writeFileSync(file.path, file.content);
  console.log(`medicines → ${file.path}`);
 }
}
