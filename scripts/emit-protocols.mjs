/* The protocol registry, written out for two native apps by a machine.

   packages/catalog/protocols.json names the twelve launch protocols, their versions and whether the
   clinical governance board has ratified them — and none of them is, yet. This emits the id, name,
   engine, version and status of each, and the refusal statements, so that a nurse's checklist on a
   phone can say which protocol and version it is following and say plainly when that protocol is
   still a draft.

   WHAT THIS GENERATOR REFUSES TO EMIT. Any content. contentRef is not written out even when it
   exists, because a phone that holds a protocol's text holds a copy that will not change when the
   board ratifies the next version. And a draft carrying anything but its name and number: the
   check refuses one first, and this refuses again so that the refusal survives somebody running
   the generator without the check.

   Escaping: Swift needs its quotes escaped; Kotlin needs backslash, quote and dollar, because a
   lone $ starts a template. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/protocols.json';

const swift = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;

export function emitProtocols(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 for (const p of contract.protocols) {
  if (p.status === 'draft' && p.contentRef !== null) throw new Error(`The draft protocol ${p.id} carries content. A draft holds a name and a number.`);
 }

 const banner = [
  `Generated by scripts/emit-protocols.mjs from ${SOURCE}.`,
  'Do not edit by hand — run `npm run protocols`. The build fails if this file and the source',
  'disagree, so an edit here is lost rather than merely wrong.',
  '',
  'Names, versions and status only. No protocol content, threshold or dose is written here, and none',
  'is coming from here: a protocol is read at the version the registry names, not from a copy.'
 ].map(line => (line ? `// ${line}` : '//')).join('\n');

 const swiftFile = `${banner}

import Foundation

enum ProtocolsData {
    struct Entry: Identifiable {
        let id: String; let name: String; let engine: String; let version: Int; let status: String
        var reference: String { "\\(id)@\\(version)" }
        var ratified: Bool { status == "ratified" }
    }
    struct Refusal: Identifiable { let id: String; let statement: String }

    static let protocols: [Entry] = [
${contract.protocols.map(p => `        Entry(id: ${swift(p.id)}, name: ${swift(p.name)}, engine: ${swift(p.engine)}, version: ${p.version}, status: ${swift(p.status)})`).join(',\n')}
    ]

    static let refusals: [Refusal] = [
${contract.refusals.map(r => `        Refusal(id: ${swift(r.id)}, statement: ${swift(r.statement)})`).join(',\n')}
    ]

    static func entry(_ id: String) -> Entry? { protocols.first { $0.id == id } }
}
`;

 const kotlinFile = `${banner}

package za.co.mythuso.model

object ProtocolsData {
    data class Entry(val id: String, val name: String, val engine: String, val version: Int, val status: String) {
        val reference get() = "$id@$version"
        val ratified get() = status == "ratified"
    }
    data class Refusal(val id: String, val statement: String)

    val protocols = listOf(
${contract.protocols.map(p => `        Entry(${kotlin(p.id)}, ${kotlin(p.name)}, ${kotlin(p.engine)}, ${p.version}, ${kotlin(p.status)})`).join(',\n')}
    )

    val refusals = listOf(
${contract.refusals.map(r => `        Refusal(${kotlin(r.id)}, ${kotlin(r.statement)})`).join(',\n')}
    )

    fun entry(id: String) = protocols.firstOrNull { it.id == id }
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/ProtocolsData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/ProtocolsData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitProtocols()) {
  writeFileSync(file.path, file.content);
  console.log(`protocols → ${file.path}`);
 }
}
