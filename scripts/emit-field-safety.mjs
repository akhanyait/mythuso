/* The nurse safety suite, written out for two native apps, by a machine.
 *
 * packages/catalog/field-safety.json holds the grace, the extension steps and ceiling, the panic
 * window, every sentence a nurse or the desk reads, and the refusals. Some of those refusals belong to
 * a route in packages/catalog/apis/safety.json and are resolved from there, so the sentence a route
 * would return and the sentence a native screen shows are one string. The emergency numbers the panic
 * confirmation names are filled in from packages/catalog/sos.json here, at generation time, so no
 * native file types 10177 a second time. The web reads all three through
 * packages/engines/src/safety/domain; iOS and Android cannot read JSON at runtime, so the copy is
 * generated rather than typed and scripts/check-boundaries.mjs compares it on every build.
 *
 * The grace and the panic window were decided by the founder on 15 September 2026; the extension steps
 * and ceiling are still proposals. Each has `decidedBy` in the contract — null until somebody with the
 * authority sets it — and this generator refuses a number whose question has been deleted, a decision
 * that does not say who took it and when, and a proposal that does not say why it was proposed. A panic
 * window that silently became policy is the failure this file exists to make loud, and each constant
 * says in its own comment which of the two it is.
 *
 * Those four numbers are defaults. An admin changes them on the web back office, against the Safety
 * engine's settings routes; neither native app has an admin surface or reaches those routes, so both
 * time a visit and open a panic with the defaults written here, and say so rather than guessing at a
 * change they cannot see.
 *
 * Escaping, as in emit-sos.mjs: Swift needs its quotes escaped; Kotlin needs backslash, quote and $.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { settingDefault } from './settings-defaults.mjs';

const SOURCE = 'packages/catalog/field-safety.json';
const API = 'packages/catalog/apis/safety.json';
const SOS = 'packages/catalog/sos.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
/* The string fields of a block, in contract order. Notes and lists are not screen copy. */
const sentences = block => Object.entries(block).filter(([key, value]) => typeof value === 'string' && !key.startsWith('_'));

const banner = () => [
 `Generated by scripts/emit-field-safety.mjs from ${SOURCE}, ${API} and ${SOS}.`,
 'Do not edit by hand — run `npm run field-safety`. The build fails if this file and its sources disagree,',
 'so an edit here is lost rather than merely wrong.',
 '',
 'The grace and the panic window were decided by the founder; the extension steps and ceiling are',
 'PROPOSALS, with decidedBy null in the contract. All four are defaults an admin changes on the web back',
 'office. This app has no admin surface and reaches no settings route, so it uses them as written here,',
 'and they change in the contract, never in this file.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitFieldSafety(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const api = JSON.parse(readFileSync(root + API, 'utf8'));
 const sos = JSON.parse(readFileSync(root + SOS, 'utf8'));

 /* The four timings are settings in the contract's settings block. A decided default names who decided it;
    a proposal says who proposed it and why; either way the constant's comment says which it is, in the one
    sentence scripts/settings-defaults.mjs writes for every engine. The day and the reasoning, and every
    bound, are held by scripts/check-boundaries.mjs on every build; the phones are told who, not when. */
 const grace = settingDefault(SOURCE, contract, 'grace');
 const steps = settingDefault(SOURCE, contract, 'extension-steps', { list: true });
 const ceiling = settingDefault(SOURCE, contract, 'extension-ceiling');
 const window = settingDefault(SOURCE, contract, 'panic-window');
 const feed = contract.simulation.positionEverySeconds;

 /* {police} and {ambulance} are resolved here and nowhere else in the native copy. Every other token
    ({ends}, {at}) is a value the phone knows at the moment it draws the sentence, and is left in. */
 const numbers = Object.fromEntries(['police', 'ambulance'].map(id => {
  const found = sos.emergency.numbers.find(entry => entry.id === id);
  if (!found) throw new Error(`${SOS} has no emergency number "${id}", so the panic confirmation cannot say who to call.`);
  return [id, found.number];
 }));
 const withNumbers = text => text.replace(/\{(police|ambulance)\}/g, (_, id) => numbers[id]);

 const refusals = [
  ...contract.refusals.map(({ id, status, statement }) => ({ id, status, statement })),
  ...contract.routeRefusals.map(({ route, id }) => {
   const found = api.routes.find(r => `${r.method} ${r.path}` === route)?.refusals.find(r => r.id === id);
   if (!found) throw new Error(`${SOURCE} names the refusal "${id}" on ${route}, and ${API} has no such refusal on that route.`);
   return { id, status: found.status, statement: found.statement };
  })
 ];
 const choice = (list, flag) => list.map(item => ({ id: item.id, label: item.label, flag: flag ? item[flag] === true : false }));
 const lists = [
  ['timerStates', choice(contract.states.timer)],
  ['panicStates', choice(contract.states.panic)],
  ['extensionReasons', choice(contract.extensionReasons)],
  ['silenceReasons', choice(contract.silenceReasons, 'needsNurseAnswer')],
  ['outcomes', choice(contract.outcomes, 'humanCalledServices')]
 ];
 const texts = [
  ['NurseText', sentences(contract.nurse)],
  ['PanicText', sentences(contract.panic).map(([key, value]) => [key, withNumbers(value)])],
  ['DeskText', [...sentences(contract.desk), ['kindPanic', contract.desk.kinds.panic], ['kindOverdue', contract.desk.kinds.overdue]]]
 ];

 const swiftFile = `${banner()}

import Foundation

extension FieldSafety {
    /// ${grace.note}
    static let graceMinutes = ${grace.value}
    /// ${steps.note}
    static let extensionSteps = [${steps.value.join(', ')}]
    /// ${ceiling.note}
    static let maxExtensionMinutes = ${ceiling.value}
    /// ${window.note}
    static let panicWindowMinutes = ${window.value}
    /// The simulated feed's cadence, not a policy.
    static let positionEverySeconds = ${feed}

${texts.map(([name, entries]) => `    enum ${name} {
${entries.map(([key, value]) => `        static let ${key} = ${swift(value)}`).join('\n')}
    }`).join('\n\n')}

${lists.map(([name, items]) => `    static let ${name}: [FieldSafetyChoice] = [
${items.map(i => `        .init(id: ${swift(i.id)}, label: ${swift(i.label)}, flag: ${i.flag})`).join(',\n')}
    ]`).join('\n')}

    static let refusals: [FieldSafetyRefusal] = [
${refusals.map(r => `        .init(id: ${swift(r.id)}, status: ${r.status}, statement: ${swift(r.statement)})`).join(',\n')}
    ]
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

object FieldSafetyData {
    /** ${grace.note} */
    const val graceMinutes = ${grace.value}
    /** ${steps.note} */
    val extensionSteps = listOf(${steps.value.join(', ')})
    /** ${ceiling.note} */
    const val maxExtensionMinutes = ${ceiling.value}
    /** ${window.note} */
    const val panicWindowMinutes = ${window.value}
    /** The simulated feed's cadence, not a policy. */
    const val positionEverySeconds = ${feed}

${texts.map(([name, entries]) => `    object ${name} {
${entries.map(([key, value]) => `        const val ${key} = ${kotlin(value)}`).join('\n')}
    }`).join('\n\n')}

${lists.map(([name, items]) => `    val ${name} = listOf(
${items.map(i => `        FieldSafetyChoice(${kotlin(i.id)}, ${kotlin(i.label)}, ${i.flag})`).join(',\n')}
    )`).join('\n')}

    val refusals = listOf(
${refusals.map(r => `        FieldSafetyRefusal(${kotlin(r.id)}, ${r.status}, ${kotlin(r.statement)})`).join(',\n')}
    )
}
`;

 return [
  { path: 'apps/ios/MyThuso/Models/FieldSafetyData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/FieldSafetyData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitFieldSafety()) {
  writeFileSync(file.path, file.content);
  console.log(`field-safety → ${file.path}`);
 }
}
