/* Substitution and chronic authorisation, written out for two native apps, by a machine.

   The three substitution classes, the ten grounds, what a substitution may and may not change, the
   six rules, the six refusals, the chronic authorisation and one fictional prescription of five
   items live in packages/catalog/dispensing.json. The web reads that file. iOS and Android cannot,
   and should not, for the reason the vetting generator gives: an app that parses JSON to draw a
   list is a web app wearing a Compose hat.

   Two things here are worth knowing rather than guessing at.

   The first is that no date is written out. The authorisation carries the day it was authorised and
   the months it runs for; when it expires is arithmetic, done identically in Dispensing.swift,
   Dispensing.kt and apps/web/src/lib/dispensing.ts, and checked against all three. An expiry typed
   beside a validity period is two numbers that can disagree about the same day, and the day in
   question is the one a repeat stops on.

   The second is escaping, and the two languages disagree about it:
     - Swift needs only its quotes escaped.
     - Kotlin needs backslash, quote and dollar escaped, because a lone backslash is an escape and a
       lone $ starts a string template.
   The copy carries curly quotes, en-dashes and a µ. Those are simply UTF-8 and need nothing.

   The third is who the native prescription is for, which is nobody. The only native screen that reads
   it is the pharmacy's Substitution & repeats, and medicines.json#partnerQueue.neverCarries lists the
   patient and the prescriber, so the patient's name and birth date and the prescriber's subject id
   are not written into either app at all (2 October 2026). The contract keeps them, because the
   patient's own Passport on the web reads them; a copy the phones never draw is a copy that can only
   leak. In their place go dispensing.json#partner — what a partner reads where the people were — and
   the first sentence of medicines.json#partnerQueue.why, taken here exactly as the web takes it, so
   the reason a partner is told for the gap is one sentence in one file. */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'packages/catalog/dispensing.json';
const MEDICINES = 'packages/catalog/medicines.json';

const swift = value => {
 if (value.includes('\\')) throw new Error(`Cannot write ${JSON.stringify(value)} as a Swift literal here`);
 return `"${value.replace(/"/g, '\\"')}"`;
};
const kotlin = value => `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
const optSwift = value => (value === undefined ? 'nil' : swift(value));
const optKotlin = value => (value === undefined ? 'null' : kotlin(value));
const swiftList = values => `[${values.map(swift).join(', ')}]`;
const kotlinList = values => `listOf(${values.map(kotlin).join(', ')})`;

const banner = () => [
 `Generated by scripts/emit-dispensing.mjs from ${SOURCE} and ${MEDICINES}#partnerQueue.`,
 'Do not edit by hand — run `npm run dispensing`. The build fails if this file and the source',
 'disagree, so an edit here is lost rather than merely wrong.',
 '',
 'Not one date is written out below. The authorisation carries the day it was authorised and the',
 'months it runs for; when it expires, how many repeats are left, how much medicine those cover and',
 'whether one may be collected today are all worked out in Dispensing.swift and Dispensing.kt beside',
 'this file — from the same two numbers the web works them out from.'
].map(line => (line ? `// ${line}` : '//')).join('\n');

export function emitDispensing(root = '') {
 const contract = JSON.parse(readFileSync(root + SOURCE, 'utf8'));
 const { authorisation: auth, prescription: rx, partner } = contract;
 /* Split as apps/web/src/features/OrderDetails.tsx splits it, so both draw the same sentence. */
 const told = JSON.parse(readFileSync(root + MEDICINES, 'utf8')).partnerQueue.why.split('. ')[0] + '.';

 const swiftFile = `${banner()}

import Foundation

extension Dispensing {
    /* Three classes, and the middle one is the point of the screen. The lowest is not "may
       substitute": section 22F makes telling the patient a duty, so a silent swap is outside this
       table rather than at the bottom of it. */
    static let substitutionClasses: [SubstitutionClass] = [
${contract.substitutionClasses.map(c => `        .init(id: ${swift(c.id)}, name: ${swift(c.name)}, shortName: ${swift(c.shortName)},
              detail: ${swift(c.detail)},
              whoDecides: ${swift(c.whoDecides)}, needsWrittenReason: ${c.needsWrittenReason}, tellsThePrescriber: ${c.tellsThePrescriber}, tone: ${swift(c.tone)})`).join(',\n')}
    ]
    /* Why this item falls where it falls. The four that carry a section number are the four
       exceptions in the Act; the rest are clinical. */
    static let grounds: [SubstitutionGround] = [
${contract.grounds.map(g => `        .init(id: ${swift(g.id)}, name: ${swift(g.name)}, section: ${optSwift(g.section)}, classId: ${swift(g.class)},
              detail: ${swift(g.detail)})`).join(',\n')}
    ]
    static let neverChanges: [MedicineChange] = [
${contract.neverChanges.map(c => `        .init(what: ${swift(c.what)}, why: ${swift(c.why)})`).join(',\n')}
    ]
    static let mayChange: [MedicineChange] = [
${contract.mayChange.map(c => `        .init(what: ${swift(c.what)}, why: ${swift(c.why)})`).join(',\n')}
    ]
    /* Rendered word for word. A rule paraphrased on one platform is a different promise on that
       platform, which is the whole reason these live in one file. */
    static let rules: [DispensingRule] = [
${contract.rules.map(r => `        .init(id: ${swift(r.id)}, title: ${swift(r.title)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    static let refusals: [DispensingRefusal] = [
${contract.refusals.map(r => `        .init(id: ${swift(r.id)}, sentence: ${swift(r.sentence)})`).join(',\n')}
    ]
    /* The one sentence three other screens need. It was written out in each of them and had to be
       changed in all three at once, which is exactly the drift this repository generates its way
       out of everywhere else. */
    static let crossReference = ${swift(contract.crossReference)}
    /* What a partner reads where the people behind an order were: the vetting register's answer
       about the prescriber rather than who they are, why the people are missing, and the sentence a
       laboratory reads where a release control was. Assembled in Dispensing.swift. */
    enum Partner {
        static let prescriberMay = ${swift(partner.prescriberMay)}
        static let prescriberMayNot = ${swift(partner.prescriberMayNot)}
        static let checksJoinedBy = ${swift(partner.checksJoinedBy)}
        static let noCheckNamed = ${swift(partner.noCheckNamed)}
        static let releaseWithheld = ${swift(partner.releaseWithheld)}
        static let told = ${swift(told)}
    }
    static let handover: [HandoverStep] = [
${contract.handover.map(s => `        .init(id: ${swift(s.id)}, label: ${swift(s.label)}, detail: ${swift(s.detail)})`).join(',\n')}
    ]
    static let authorisation = ChronicAuthorisation(
        reference: ${swift(auth.reference)}, programme: ${swift(auth.programme)}, condition: ${swift(auth.condition)},
        authorisedByDays: ${auth.authorisedByDays}, validMonths: ${auth.validMonths},
        repeatsAuthorised: ${auth.repeatsAuthorised}, repeatsUsed: ${auth.repeatsUsed},
        daysPerRepeat: ${auth.daysPerRepeat}, minimumDaysBetween: ${auth.minimumDaysBetween},
        lastCollectedDays: ${auth.lastCollectedDays}, reviewedBy: ${swift(auth.reviewedBy)},
        endsWith: ${swift(auth.endsWith)},
        note: ${swift(auth.note)},
        quantityNote: ${swift(auth.quantityNote)})
    static let prescription = DispensedPrescription(
        reference: ${swift(rx.reference)}, issuedInDays: ${rx.issuedInDays}, pharmacy: ${swift(rx.pharmacy)},
        pharmacist: DispensingPharmacist(name: ${swift(rx.pharmacist.name)}, registration: ${swift(rx.pharmacist.registration)}, role: ${swift(rx.pharmacist.role)}),
        items: [
${rx.items.map(item => `            .init(id: ${swift(item.id)}, prescribed: ${swift(item.prescribed)}, molecule: ${swift(item.molecule)},
                  strength: ${swift(item.strength)}, form: ${swift(item.form)}, dose: ${swift(item.dose)}, quantity: ${swift(item.quantity)},
                  classId: ${swift(item.class)}, ground: ${swift(item.ground)}, secondGround: ${optSwift(item.secondGround)},
                  outcome: ${swift(item.outcome)}, dispensed: ${swift(item.dispensed)},
                  sameness: ${swiftList(item.sameness)},
                  differences: ${swiftList(item.differences)},
                  patientWords: ${swift(item.patientWords)},
                  writtenReason: ${optSwift(item.writtenReason)}, accepted: ${item.accepted}, note: ${swift(item.note)})`).join(',\n')}
        ])
}
`;

 const kotlinFile = `${banner()}

package za.co.mythuso.model

/* Three classes, and the middle one is the point of the screen. The lowest is not "may substitute":
   section 22F makes telling the patient a duty, so a silent swap is outside this table rather than
   at the bottom of it. */
val substitutionClasses = listOf(
${contract.substitutionClasses.map(c => `    SubstitutionClass(
        ${kotlin(c.id)}, ${kotlin(c.name)}, ${kotlin(c.shortName)},
        ${kotlin(c.detail)},
        ${kotlin(c.whoDecides)}, ${c.needsWrittenReason}, ${c.tellsThePrescriber}, ${kotlin(c.tone)}
    )`).join(',\n')}
)

/* Why this item falls where it falls. The four that carry a section number are the four exceptions
   in the Act; the rest are clinical. */
val substitutionGrounds = listOf(
${contract.grounds.map(g => `    SubstitutionGround(
        ${kotlin(g.id)}, ${kotlin(g.name)}, ${optKotlin(g.section)}, ${kotlin(g.class)},
        ${kotlin(g.detail)}
    )`).join(',\n')}
)

val substitutionNeverChanges = listOf(
${contract.neverChanges.map(c => `    MedicineChange(${kotlin(c.what)}, ${kotlin(c.why)})`).join(',\n')}
)

val substitutionMayChange = listOf(
${contract.mayChange.map(c => `    MedicineChange(${kotlin(c.what)}, ${kotlin(c.why)})`).join(',\n')}
)

/* Rendered word for word. A rule paraphrased on one platform is a different promise on that
   platform, which is the whole reason these live in one file. */
val dispensingRules = listOf(
${contract.rules.map(r => `    DispensingRule(${kotlin(r.id)}, ${kotlin(r.title)}, ${kotlin(r.sentence)})`).join(',\n')}
)

val dispensingRefusals = listOf(
${contract.refusals.map(r => `    DispensingRefusal(${kotlin(r.id)}, ${kotlin(r.sentence)})`).join(',\n')}
)

/* The one sentence three other screens need. It was written out in each of them and had to be
   changed in all three at once, which is exactly the drift this repository generates its way out of
   everywhere else. */
val dispensingCrossReference = ${kotlin(contract.crossReference)}

/* What a partner reads where the people behind an order were: the vetting register's answer about the
   prescriber rather than who they are, why the people are missing, and the sentence a laboratory reads
   where a release control was. Assembled in Dispensing.kt. */
object DispensingPartner {
    const val prescriberMay = ${kotlin(partner.prescriberMay)}
    const val prescriberMayNot = ${kotlin(partner.prescriberMayNot)}
    const val checksJoinedBy = ${kotlin(partner.checksJoinedBy)}
    const val noCheckNamed = ${kotlin(partner.noCheckNamed)}
    const val releaseWithheld = ${kotlin(partner.releaseWithheld)}
    const val told = ${kotlin(told)}
}

val dispensingHandover = listOf(
${contract.handover.map(s => `    HandoverStep(${kotlin(s.id)}, ${kotlin(s.label)}, ${kotlin(s.detail)})`).join(',\n')}
)

val chronicAuthorisation = ChronicAuthorisation(
    ${kotlin(auth.reference)}, ${kotlin(auth.programme)}, ${kotlin(auth.condition)},
    ${auth.authorisedByDays}, ${auth.validMonths}, ${auth.repeatsAuthorised}, ${auth.repeatsUsed},
    ${auth.daysPerRepeat}, ${auth.minimumDaysBetween}, ${auth.lastCollectedDays}, ${kotlin(auth.reviewedBy)},
    ${kotlin(auth.endsWith)},
    ${kotlin(auth.note)},
    ${kotlin(auth.quantityNote)}
)

val dispensedPrescription = DispensedPrescription(
    ${kotlin(rx.reference)}, ${rx.issuedInDays}, ${kotlin(rx.pharmacy)},
    DispensingPharmacist(${kotlin(rx.pharmacist.name)}, ${kotlin(rx.pharmacist.registration)}, ${kotlin(rx.pharmacist.role)}),
    listOf(
${rx.items.map(item => `        PrescriptionItem(
            ${kotlin(item.id)}, ${kotlin(item.prescribed)}, ${kotlin(item.molecule)}, ${kotlin(item.strength)},
            ${kotlin(item.form)}, ${kotlin(item.dose)}, ${kotlin(item.quantity)},
            ${kotlin(item.class)}, ${kotlin(item.ground)}, ${optKotlin(item.secondGround)},
            ${kotlin(item.outcome)}, ${kotlin(item.dispensed)},
            ${kotlinList(item.sameness)},
            ${kotlinList(item.differences)},
            ${kotlin(item.patientWords)},
            ${optKotlin(item.writtenReason)}, ${item.accepted}, ${kotlin(item.note)}
        )`).join(',\n')}
    )
)
`;

 return [
  { path: 'apps/ios/MyThuso/Models/DispensingData.swift', content: swiftFile },
  { path: 'apps/android/app/src/main/java/za/co/mythuso/model/DispensingData.kt', content: kotlinFile }
 ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
 for (const file of emitDispensing()) {
  writeFileSync(file.path, file.content);
  console.log(`dispensing → ${file.path}`);
 }
}
